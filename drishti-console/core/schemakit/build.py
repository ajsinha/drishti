def make_bundle(pack_dir: pathlib.Path, out_dir: pathlib.Path, packbundle, tool_versions: dict | None = None, required_server: str | None = None) -> dict:
    """Writes <out_dir>/<name>-<version>.tar.gz (+ .sha256, .manifest.json) with tools/packbundle.py: the format of `pack bundle`."""
    return packbundle.bundle(pack_dir, out_dir, tool_versions or {}, required_server)
