HEADER_NOTE = "# Generated by drishti schemakit (docs/guides/DATA_GUIDE.md); now yours to edit.\n"


@dataclass
class Sample:
    name: str                    # file name stem, e.g. sample-1, sample-example-1, sample-synthetic-1
    doc: dict
    source: str                  # real | example | synthetic


@dataclass
class Item:
    """One Sutra to draft: the plan's kind and Sutra, and the documents the draft and its tests are made from."""
    kp: KindPlan
    sp: SutraPlan
    samples: list = field(default_factory=list)

    @property
    def name(self) -> str:
        return self.sp.name

    @property
    def synthetic(self) -> bool:
        return all(s.source == "synthetic" for s in self.samples)



SAMPLE_PART_MB = 50      # a kind's samples are split into <kind>.part-001.jsonl ... only above this (tools/packgen/common/packsamples.py)


def write_jsonl(samples_dir, kind: str, lines: list[str], part_mb: float = SAMPLE_PART_MB) -> None:
    """samples/<kind>.jsonl, or <kind>.part-NNN.jsonl parts when it would pass part_mb."""
    samples_dir.mkdir(parents=True, exist_ok=True)
    parts, cur, size, limit = [], [], 0, int(part_mb * 1024 * 1024)
    for ln in lines:
        b = len(ln.encode("utf-8")) + 1
        if cur and size + b > limit:
            parts.append(cur)
            cur, size = [], 0
        cur.append(ln)
        size += b
    if cur:
        parts.append(cur)
    names = [f"{kind}.jsonl"] if len(parts) == 1 else [f"{kind}.part-{n:03d}.jsonl" for n in range(1, len(parts) + 1)]
    for name, part in zip(names, parts):
        (samples_dir / name).write_text("\n".join(part) + "\n", encoding="utf-8")

def _matches(doc: dict, sp: SutraPlan) -> bool:
    return all(doc.get(f) == v for f, v in sp.values.items())


def _spaced(docs: list, n: int, key: str | None) -> list:
    ordered = sorted(docs, key=lambda d: str(d.get(key)) if key and d.get(key) is not None else json.dumps(d, sort_keys=True))
    if len(ordered) <= n:
        return ordered
    return [ordered[(i * len(ordered)) // n] for i in range(n)]


def shape_of(doc, prefix: str = "", out: set | None = None, depth: int = 0) -> set:
    """The paths a document fills, with how each array is (``LEGS[]`` filled, ``EVENTS:empty``, ``EVENTS:absent`` is added by the caller)."""
    out = set() if out is None else out
    if isinstance(doc, dict) and depth < 8:
        for k, v in doc.items():
            p = f"{prefix}{k}"
            if v is None or (isinstance(v, str) and not v.strip()):
                continue
            if isinstance(v, list):
                out.add(p + (":empty" if not v else "[]"))
                for item in v[:50]:
                    shape_of(item, p + "[].", out, depth + 1)
            elif isinstance(v, dict):
                shape_of(v, p + ".", out, depth + 1)
            else:
                out.add(p)
    return out


def covering(docs: list, n: int, key: str | None) -> list:
    """Up to ``n`` documents that together show every path the documents fill and every way an optional array comes (filled, empty,
    absent): greedy, the document adding most new paths first; then spread over the key, as ``_spaced`` does."""
    if len(docs) <= n:
        return _spaced(docs, n, key)
    arrays = {p.split(":")[0].removesuffix("[]") for d in docs for p in shape_of(d) if p.endswith(("[]", ":empty")) and "." not in p}
    shapes = []
    for d in docs:
        s = shape_of(d)
        s |= {f"{a}:absent" for a in arrays if a not in d}
        shapes.append(s)
    order = sorted(range(len(docs)), key=lambda i: str(docs[i].get(key)) if key and docs[i].get(key) is not None else str(i))
    seen: set = set()
    picked: list = []
    while len(picked) < n:
        best = max((i for i in order if i not in picked), key=lambda i: len(shapes[i] - seen), default=None)
        if best is None or not (shapes[best] - seen):
            break
        picked.append(best)
        seen |= shapes[best]
    rest = [docs[i] for i in order if i not in picked]
    out = [docs[i] for i in picked] + _spaced(rest, n - len(picked), key) if len(picked) < n else [docs[i] for i in picked]
    return sorted(out, key=lambda d: str(d.get(key)) if key and d.get(key) is not None else json.dumps(d, sort_keys=True))


def prepare(plan: Plan, n: int | None = None) -> list[Item]:
    """For every Sutra of every kind, its samples: real documents that match first (spread over the key), the schema's own ``examples``,
    then synthetic documents until there are ``n`` (and always at least two when the Sutra has no real match)."""
    n = int(n or plan.settings.get("samples", 5))
    items = []
    for kp in plan.kinds:
        for idx, sp in enumerate(kp.sutras):
            real = [d for d in kp.samples if sp.fallback or _matches(d, sp)]
            picks = [Sample(f"sample-{i}", d, "real") for i, d in enumerate(covering(real, n, kp.key), 1)]
            ex = [Sample(f"sample-example-{i}", d, "example") for i, d in enumerate(synth.examples_of(kp, sp), 1)] if kp.node else []
            samples = picks + ex[: max(0, n - len(picks))]
            need = max(0, n - len(samples)) if not picks else (max(0, 2 - len(samples)) if not sp.fallback else 0)
            if need:
                docs = synth.documents(kp, plan, need, sp, offset=idx * n)
                samples += [Sample(f"sample-synthetic-{i}", d, "synthetic") for i, d in enumerate(docs, 1)]
            items.append(Item(kp, sp, samples))
    return items


def catalog_docs(kp: KindPlan, plan: Plan, n: int = 8) -> list:
    """The documents of ``samples/<kind>/``: real ones (up to 25), else synthetic ones whose keys are KEY-0001.. so links between kinds resolve."""
    if kp.real:
        return [(d, "real") for d in _spaced(kp.samples, 25, kp.key)]
    variants = [s for s in kp.sutras if s.variant is not None or s.values]
    s = synth.Synth(plan)
    out = []
    for i in range(max(n, len(variants))):
        sp = variants[i % len(variants)] if variants else None
        out.append((s.document(kp, i, sp), "synthetic"))
    return out


def panel_ids(yaml_text: str) -> list[str]:
    return re.findall(r"^\s+- id: (\S+)", yaml_text, re.M)


def drafts_ok(items: list[Item], drafts: dict) -> list[str]:
    return [i.name for i in items if not drafts.get(i.name)]


# ----------------------------------------------------------------------------------------------- pack.yaml

def connector_block(pack: str, kinds: list, store: str, plan_cols: dict) -> dict:
    """A connector for kinds that share a logical name: the file or delta plugin on the usual root, one layout per kind."""
    if store == "file":
        layout = {}
        for k in kinds:
            title = title_columns(k)
            layout[k.kind] = {"columns": list(dict.fromkeys(plan_cols[k.kind] + title))}
            if title:
                layout[k.kind]["title"] = title          # type-ahead finds a document by these too (a counterparty, a portfolio, a type)
        return {"plugin": "file", "enabled": "${DRISHTI_FILES_ENABLED:true}", "kinds": sorted(k.kind for k in kinds),
                "description": f"Set root (or DRISHTI_FILES_ROOT) to the folder that holds {pack}/<date>/<kind>.jsonl",
                "settings": {"root": "${DRISHTI_FILES_ROOT:${drishti.data.dir:./data}/files}", "domain": pack, "id-field": "id",
                             "layout": layout}}
    return {"plugin": "delta", "enabled": "${DRISHTI_LAKE_ENABLED:true}", "kinds": sorted(k.kind for k in kinds),
            "settings": {"root": "${DRISHTI_DELTA_ROOT:${drishti.data.dir:./data}/delta}", "domain": pack,
                         "layout": {k.kind: {"columns": plan_cols[k.kind], "sort-by": "id", "file-rows": 250000, "row-group-rows": 1000} for k in kinds}}}


def page_paths(plan: Plan, kp: KindPlan) -> list[str]:
    """The plain paths the pages per value of ``kp`` read (group, totals, rows): promoted, they are built from columns, no document read."""
    out: list = []
    for d in plan.kinds:
        spec = d.derived
        if not spec or spec.get("from") != kp.kind:
            continue
        exprs = [spec["group-by"]] + [a.partition(" ")[2] for a in spec["fields"].values()] + list(spec["rows"].values())
        out += [e[2:] for e in exprs if re.fullmatch(r"\$\.[A-Za-z_][A-Za-z0-9_]*", e or "")]
    return list(dict.fromkeys(out))


def title_columns(kp: KindPlan) -> list[str]:
    """What a document's search title shows after its id: the type it is, and the fields that have a page per value (top level only)."""
    out = [m for m in kp.match if "." not in m]
    out += [r["path"] for r in kp.related if "[" not in r["path"] and "." not in r["path"]]
    return list(dict.fromkeys(out))[:4]


def columns_for(kp: KindPlan, n: int = 7) -> list[str]:
    scal = [f.path for f in kp.fields if "." not in f.path and "[" not in f.path and f.path != kp.key and f.role not in ("object", "table", "map", "list")
            and not f.hidden]
    pref = [p for p in kp.strip if p in scal]
    return list(dict.fromkeys(pref + [p for p in scal if p not in pref]))[:n]


_NUM_FMT = re.compile(r"(?i)(money|amount|ccy|usd|price|signed|mtm|notional)")


def form_for(kp: KindPlan, n: int = 10) -> list[dict]:
    """The kind's search form (the form: section), from what the plan knows: the key first (an id), then the pick-list columns by role: a
    status or dimension with known values is a choice, a date a date, a flag yes/no, a number an amount or a plain number, the rest text."""
    by_path = {f.path: f for f in kp.fields}
    out: list[dict] = []
    for path in ([kp.key] if kp.key and "." not in kp.key else []) + [c for c in columns_for(kp, n) if c != kp.key]:
        f = by_path.get(path)
        role = f.role if f else ""
        if path == kp.key or role in ("id", "link"):
            t = "id"
        elif role in ("date", "datetime") or (f and f.type == "string" and f.format in ("date", "date-time")):
            t = "date"
        elif role == "flag" or (f and f.type == "boolean"):
            t = "bool"
        elif f and f.type in ("number", "integer"):
            t = "amount" if _NUM_FMT.search(f.fmt or "") else "number"
        elif role in ("status", "dimension") or (f and f.enum):
            t = "enum"
        else:
            t = "text"
        entry = {"path": path, "label": (f.label if f and f.label else humanize(path)), "type": t}
        if t == "enum" and f and f.enum:
            entry["values"] = [str(v) for v in f.enum][:40]
        out.append(entry)
    return out


def pack_manifest(plan: Plan, kinds_dir_note: str = "") -> dict:
    p = plan.pack
    m: dict = {"pack": p["name"], "version": p.get("version") or "1.0.0", "code": p.get("code") or p["name"][:4].upper(),
               "title": p.get("title") or p["name"], "description": p.get("description") or f"Generated from schemas for {p['name']}.",
               "kinds": [k.kind for k in plan.kinds], "sutras": "sutras", "samples": "samples",
               "mnemonics": {k.mnemonic: {"kind": k.kind, "label": k.title} for k in plan.kinds},
               "columns": {k.kind: columns_for(k) for k in plan.kinds},
               "form": {k.kind: form_for(k) for k in plan.kinds}}      # the search form of each kind (FORM pack)
    fields: dict = {}
    for k in plan.kinds:
        for l in k.links:
            name = l.field.split(".")[-1].replace("[]", "")
            if name in fields and fields[name]["kind"] != l.to:
                plan.warnings.append(f"{k.kind}: the link field '{name}' already points at {fields[name]['kind']}; a link field name means one kind, so '{name}' -> {l.to} was left out")
                continue
            fields[name] = {"kind": l.to, "label": humanize(name.removesuffix("Id").removesuffix("_id") or name)}
    if fields:
        m["graph"] = {"fields": fields}
    by_conn: dict[str, list] = {}
    for k in plan.kinds:
        if k.template in ("file", "delta"):
            by_conn.setdefault(k.connector or f"{p['name']}-store", []).append(k)
    if by_conn:
        # the pack NAMES its connectors (docs/connectors/CONNECTOR_FILES.md); the connection settings are the pack's template:
        # the server writes the site's connector file from it once, and the file is the site's afterwards
        m["connectors"], m["routes"], m["connector-templates"], ing = sorted(by_conn), {}, {}, {}
        for name, ks in sorted(by_conn.items()):
            store = ks[0].template
            m["connector-templates"][name] = connector_block(p["name"], ks, store, {k.kind: list(dict.fromkeys(columns_for(k) + ([k.date] if k.date else []) + page_paths(plan, k))) for k in ks})
            for k in ks:
                m["routes"][k.kind] = name
                if k.key and k.date:
                    ing[k.kind] = {"key": k.key, "date": k.date}
                elif k.key and k.snapshot:
                    ing[k.kind] = {"key": k.key, "snapshot": True}      # no date field: stored under the day of the load
        if ing:
            m["ingest"] = ing
    derived = [k for k in plan.kinds if k.template == "derived" and k.derived]
    if derived:
        # one derived connector builds every page-per-value kind from the documents of the kind it groups (CONNECTOR_FILES.md)
        name = f"{p['name']}-pages"[:60]
        m.setdefault("connectors", [])
        m.setdefault("routes", {})
        m.setdefault("connector-templates", {})
        m["connectors"] = sorted(set(m["connectors"]) | {name})
        settings: dict = {"refresh": "60s"}
        for k in derived:
            d = k.derived
            settings[k.kind] = {"from": d["from"], "group-by": d["group-by"], "id-field": d["id-field"], "members": d["members"],
                                "max-members": d["max-members"], "fields": d["fields"], "rows": d["rows"]}
            m["routes"][k.kind] = name
        m["connector-templates"][name] = {"plugin": "derived", "enabled": True, "kinds": sorted(k.kind for k in derived),
                                          "description": "Pages for each value of a field (a counterparty, a portfolio, an index), built from the pack's own documents",
                                          "settings": settings}
    if getattr(plan, "controls_note", None):
        m["x-controls"] = plan.controls_note
    return m


# ----------------------------------------------------------------------------------------------- the folder

@dataclass
class Built:
    pack_dir: pathlib.Path
    sutras: list = field(default_factory=list)    # [{name, kind, file, yaml, samples:[{name, source}], shown}]
    shown: dict = field(default_factory=dict)
    synthetic: list = field(default_factory=list)
    todo: int = 0


def assemble(plan: Plan, items: list[Item], drafts: dict, pack_dir: pathlib.Path, license_header: str = "", say=print) -> Built:
    """Writes the pack folder. ``drafts`` maps a Sutra name to the auto-designer's YAML for it."""
    import yaml
    missing = drafts_ok(items, drafts)
    if missing:
        raise ValueError("no draft for: " + ", ".join(missing))
    if pack_dir.exists():
        shutil.rmtree(pack_dir)
    built = Built(pack_dir)
    for it in items:
        text, shown = decorate.finalize(drafts[it.name], it.kp, it.sp, plan)
        built.shown.setdefault(it.kp.kind, set()).update(shown)
        f = pack_dir / "sutras" / it.kp.kind / f"{it.name}.v1.sutra.yaml"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
        td = pack_dir / "tests" / it.name
        td.mkdir(parents=True, exist_ok=True)
        # the Sutra's test cases: tests/<sutra>/cases.jsonl, one {case, document} a line (2.9.4, docs/guides/DATA_GUIDE.md)
        (td / "cases.jsonl").write_text("".join(json.dumps({"case": s.name, "document": s.doc}, ensure_ascii=False, separators=(",", ":")) + "\n"
                                                for s in it.samples), encoding="utf-8")
        panels = panel_ids(text)
        expect = "noErrors: true\n" + (f"nonEmpty: [{', '.join(p for p in ('details',) if p in panels)}]\n" if "details" in panels and not it.sp.fallback else "")
        (td / "expect.yaml").write_text(expect, encoding="utf-8")
        built.sutras.append({"name": it.name, "kind": it.kp.kind, "file": str(f.relative_to(pack_dir)), "yaml": text, "where": it.sp.where,
                             "samples": [{"name": s.name, "source": s.source, "document": s.doc} for s in it.samples], "synthetic": it.synthetic})
        if it.synthetic:
            built.synthetic.append(it.name)
    # samples/ catalog
    cat = []
    for kp in plan.kinds:
        if kp.derived or (kp.real and kp.template in ("file", "delta")):
            # its data is loaded into the store (or built from it): samples served beside the real documents would be listed and counted
            # with them (a page per counterparty built from both); the Sutras' own tests keep their samples in tests/
            continue
        lines = []
        for doc, src in catalog_docs(kp, plan):
            kv = doc.get(kp.key) if kp.key else None
            if kv is None:
                continue
            lines.append(json.dumps(doc, ensure_ascii=False, separators=(",", ":")))
            cat.append({"kind": kp.kind, "id": str(kv), "title": str(kv), "subtitle": kp.kind + (" (synthetic sample)" if src == "synthetic" else "")})
        if lines:                                   # samples/<kind>.jsonl: one document a line, in the catalogue's order
            write_jsonl(pack_dir / "samples", kp.kind, lines)
    (pack_dir / "samples").mkdir(exist_ok=True)
    # the catalogue: samples/catalog.jsonl, one entry a line (2.9.4, docs/guides/DATA_GUIDE.md)
    (pack_dir / "samples" / "catalog.jsonl").write_text("".join(json.dumps(e, ensure_ascii=False, separators=(",", ":")) + "\n" for e in cat),
                                                         encoding="utf-8")
    # pack.yaml and About
    man = pack_manifest(plan)
    note = HEADER_NOTE + "".join(f"# {k.kind}: key $.{k.key}" + (f", business date $.{k.date}" if k.date else "") + "\n" for k in plan.kinds)
    (pack_dir / "pack.yaml").write_text(note + plain_yaml(man), encoding="utf-8")
    (pack_dir / "config").mkdir(exist_ok=True)
    (pack_dir / "config" / "about.yaml").write_text(decorate.about_yaml(plan, built.shown), encoding="utf-8")
    from . import bi as BI                    # every level of a deep document as a BI table (config/bi: imported into BI on deploy)
    for kp in plan.kinds:
        if kp.template in ("file", "delta") and not kp.derived:
            for rel, text in BI.files(kp, plan, kp.connector or f"{plan.pack['name']}-store").items():
                f = pack_dir / "config" / "bi" / rel
                f.parent.mkdir(parents=True, exist_ok=True)
                f.write_text(text, encoding="utf-8")
    fmts = pack_formats(plan, [s["yaml"] for s in built.sutras])
    if fmts:
        (pack_dir / "config" / "formats.yaml").write_text(yaml.safe_dump({"formats": fmts}, sort_keys=False), encoding="utf-8")
    built.todo = decorate.todo_count(plan)
    (pack_dir / "README.md").write_text(readme(plan, items, built), encoding="utf-8")
    if license_header:
        for p in pack_dir.rglob("*"):
            if p.suffix in (".yaml", ".md") and p.is_file() and not p.read_text(encoding="utf-8").startswith(license_header[:20]):
                p.write_text(license_header + p.read_text(encoding="utf-8"), encoding="utf-8")
    return built


ANON = ("\n- **Anonymised**: every sample document (in `tests/`, `samples/` and `catalog.jsonl`) was anonymised before it was kept: names, ids "
        "and amounts are replaced consistently (the same value, the same token), dates and short vocabulary (statuses, sides, currencies) are kept. "
        "No value of the source data is in this pack.")
def plain_yaml(doc) -> str:
    """YAML without anchors and aliases (a repeated list is written out again): the server's reader caps aliases, and people read it."""
    import yaml

    class NoAliases(yaml.SafeDumper):
        def ignore_aliases(self, data):
            return True
    return yaml.dump(doc, Dumper=NoAliases, sort_keys=False, width=120, allow_unicode=True)


PACK_FORMATS = {"price4": {"type": "number", "decimals": 4, "grouping": True}}


def pack_formats(plan: Plan, texts: list) -> dict:
    """The formats the generated Sutras use beyond the core ones (config/formats.yaml)."""
    return {name: spec for name, spec in PACK_FORMATS.items() if any(f"'{name}'" in t or f'"{name}"' in t or f": {name}" in t for t in texts)}


def readme(plan: Plan, items: list[Item], built: Built) -> str:
    rows = "\n".join(f"| {k.kind} | `{k.key}` | {k.source or 'sample documents'} | {len(k.sutras)} | {('`' + k.date + '`') if k.date else ''} | "
                     f"{', '.join(f'{l.field} -> {l.to}' for l in k.links)} |" for k in plan.kinds)
    syn = ", ".join(built.synthetic) or "none"
    return f"""# {plan.pack.get('title') or plan.pack['name']}

Generated from JSON Schema by schemakit (`docs/guides/DATA_GUIDE.md`). Nothing here is final: edit it.

| kind | id field | schema | Sutras | business date | links |
|---|---|---|---|---|---|
{rows}

## What was generated

- `pack.yaml`: kinds, mnemonics, `columns` (pick-list columns), `graph.fields` (links between kinds)"""+(", the connectors it names (their connection settings are the pack's connector templates) and routes" if any(k.template in ("file", "delta") for k in plan.kinds) else "")+f""".
- `sutras/<kind>/`: {len(items)} Sutra(s), drafted by auto-design from sample documents and then labelled from the schema (titles, descriptions, formats, links).
- `tests/<sutra>/`: `cases.jsonl`, one case a line, named `sample-N` (real documents), `sample-example-N` (the schema's own examples) or
  `sample-synthetic-N` (generated from the schema: **synthetic**), and `expect.yaml`.
  Sutras tested on synthetic samples only: {syn}.
- `samples/`: documents so the pack opens before any data source is connected.{ANON if plan.settings.get("anonymised") else ""}
- `config/about.yaml`: the *About this page* text from the schema descriptions; {built.todo} field(s) had no description and say `TODO`.

## Next steps

1. `drishti.py pack check` this folder, then `pack bundle`, `pack verify` and `pack deploy` (or Admin -> Packs -> Deploy archive).
2. Open a document in the console and refine the Sutras in the Build workbench.
3. Fill the `TODO` entries of `config/about.yaml` (add `description` to the schema and generate again to keep them in the schema instead).
"""


