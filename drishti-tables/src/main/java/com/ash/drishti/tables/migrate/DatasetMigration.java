/**
 * One BI dataset into the layer's form, key by key (BI_FOUNDATION_2911E.md section 3.1). A {@code rachana: 2} dataset is one table; a
 * {@code rachana: 1} dataset with {@code tables:} (the live samples) is a table per table and a model of its measures (Q19). Every DEL
 * expression goes through {@link Translate}. What the skeleton does not convert yet is refused by name ({@code group:} into a summary
 * table, a pack-generated dataset: regenerated, never migrated).
 */
final class DatasetMigration {

    /** What one dataset gives: tables, at most one model, the expressions changed, and a refusal when it cannot be migrated. */
    record Out(List<TableDef> tables, ModelDef model, List<TablesMigrator.Change> changes, List<String> notes, String refusal) {}

    private static final Set<String> ABOUT = Set.of("id", "title", "description", "owner", "sample", "endorsement", "endorsedBy", "audience", "tags",
            "ai", "layout");

    private final Translate translate;
    private final Map<String, JsonNode> datasets;

    /**
     * @param translate the expression step
     * @param datasets every dataset of the run by name (a derived dataset reads its base's columns)
     */
    DatasetMigration(Translate translate, Map<String, JsonNode> datasets) {
        this.translate = translate;
        this.datasets = datasets;
    }

    Out migrate(JsonNode d) {
        List<TablesMigrator.Change> changes = new ArrayList<>();
        List<String> notes = new ArrayList<>();
        String name = d.path("dataset").asText();
        if (d.has("generated") || name.startsWith("pack.")) {
            return new Out(List.of(), null, changes, notes, "a pack-generated dataset is regenerated by the layer at pack load (section 3.6), never migrated");
        }
        if (d.has("group")) {
            return grouped(d, name, changes, notes);
        }
        if (d.has("tables")) {
            return multi(d, name, changes, notes);
        }
        TableDef t = table(d, name, TableName.ofDataset(name), name, d.path("source"), d.path("columns"), d, changes, notes);
        if (t == null) {
            String why = notes.isEmpty() ? "cannot be migrated" : notes.get(notes.size() - 1);
            return new Out(List.of(), null, changes, notes, why);
        }
        if (d.has("rollups")) {
            notes.add("rollups: move to the table's implicit model (rollups of partial states, P3): kept in the report, converted in the switch step");
        }
        return new Out(List.of(t), null, changes, notes, changes.stream().map(TablesMigrator.Change::refusal).filter(r -> r != null).findFirst().orElse(null));
    }

    /**
     * A grouped dataset ({@code group: { by, columns, grain }}) is two tables (Q13: one way to aggregate into a table): its rows as a table
     * of their own ({@code <name>_rows}), and a summary table under the dataset's name whose rows are that table's implicit model's answer
     * ({@code from: { model: table:<rows>, query }}), one row per {@code by} with each grouped column its aggregate.
     */
    private Out grouped(JsonNode d, String name, List<TablesMigrator.Change> changes, List<String> notes) {
        com.fasterxml.jackson.databind.node.ObjectNode ungrouped = ((com.fasterxml.jackson.databind.node.ObjectNode) d).deepCopy();
        JsonNode g = ungrouped.remove("group");
        String rowsName = TableName.ofDataset(name) + "_rows";
        TableDef base = table(ungrouped, name, rowsName, null, ungrouped.path("source"), ungrouped.path("columns"), ungrouped, changes, notes);
        if (base == null) {
            return new Out(List.of(), null, changes, notes, notes.isEmpty() ? "cannot be migrated" : notes.get(notes.size() - 1));
        }
        String alias = rowsName.substring(rowsName.indexOf('.') + 1);
        List<String> by = new ArrayList<>();
        g.path("by").forEach(x -> by.add(x.asText()));
        Map<String, Object> define = new LinkedHashMap<>();
        Map<String, ColumnDef> columns = new LinkedHashMap<>();
        for (String b : by) {
            ColumnDef c = base.columns().get(b);
            columns.put(b, ColumnDef.ofPath(b, null, c == null ? null : c.type()));
        }
        for (Map.Entry<String, JsonNode> e : g.path("columns").properties()) {
            String col = e.getKey();
            String agg = e.getValue().asText();
            boolean rows = agg.equals("count") && !base.columns().containsKey(col);
            define.put(col, rows ? "count(" + alias + ")" : agg + "(" + alias + "." + col + ")");
            ColumnDef c = base.columns().get(col);
            String type = agg.equals("count") || agg.equals("distinct") ? "integer" : c == null ? "decimal" : c.type();
            columns.put(col, ColumnDef.ofPath(col, null, type));
        }
        Map<String, Object> select = new LinkedHashMap<>();
        select.put("fields", by.stream().map(b -> alias + "." + b).toList());
        select.put("measures", new ArrayList<>(define.keySet()));
        Map<String, Object> query = new LinkedHashMap<>();
        query.put("select", select);
        query.put("define", define);
        TableDef summary = new TableDef(TableName.ofDataset(name), name, base.version(), base.about(),
                new TableDef.Source(null, null, null, null, null, null, null, null, null, "table:" + rowsName, query), null, null, columns, by, null,
                g.path("grain").path("says").asText(null), TableDef.Materialize.ON_LOAD, base.asOf(), base.retention(), base.refresh(),
                base.rules(), base.hiddenFor(), List.of());
        TableDef rowsTable = new TableDef(rowsName, null, base.version(), Map.of("title", "The rows of " + name), base.from(), base.grain(), base.filter(),
                base.columns(), base.keys(), base.keepLatest(), base.says(), TableDef.Materialize.NONE, base.asOf(), base.retention(), base.refresh(),
                base.rules(), base.hiddenFor(), base.tests());
        notes.add("group: its rows are the table " + rowsName + "; the dataset is a summary table of that table's implicit model (Q13)");
        return new Out(List.of(rowsTable, summary), null, changes, notes, changes.stream().map(TablesMigrator.Change::refusal).filter(r -> r != null).findFirst().orElse(null));
    }

    /** A {@code rachana: 1} dataset: one table per table, a model of its measures, hierarchies and relationships (Q19). */
    private Out multi(JsonNode d, String name, List<TablesMigrator.Change> changes, List<String> notes) {
        List<TableDef> tables = new ArrayList<>();
        Map<String, ModelDef.Use> uses = new LinkedHashMap<>();
        Map<String, Object> history = new LinkedHashMap<>();
        for (Map.Entry<String, JsonNode> e : d.path("tables").properties()) {
            String alias = e.getKey();
            JsonNode t = e.getValue();
            String tableName = TableName.ofDataset(name + "-" + alias);
            JsonNode time = t.path("live").path("history");
            if (time.isObject()) {
                history.put(alias, Yaml.MAPPER.convertValue(time, Object.class));
            }
            TableDef def = table(d, name + "." + alias, tableName, null, t.path("source"), t.path("columns"), t, changes, notes);
            if (def == null) {
                return new Out(List.of(), null, changes, notes, notes.isEmpty() ? "cannot be migrated" : notes.get(notes.size() - 1));
            }
            tables.add(def);
            uses.put(alias, new ModelDef.Use(alias, new TableName.Ref(tableName, null), "fact"));
        }
        Set<String> columns = new LinkedHashSet<>();
        Set<String> keys = new LinkedHashSet<>();
        for (TableDef t : tables) {
            String alias = uses.values().stream().filter(u -> u.table().name().equals(t.name())).findFirst().orElseThrow().alias();
            t.columns().keySet().forEach(c -> columns.add(alias + "." + c));
            t.keys().forEach(k -> keys.add(alias + "." + k));
            TableDef.BUILT_INS.forEach(b -> keys.add(alias + "." + b));
        }
        Map<String, ModelDef.Measure> measures = ModelMigration.measures(d.path("measures"), name, columns, keys, translate, changes);
        Map<String, List<String>> hierarchies = new LinkedHashMap<>();
        for (Map.Entry<String, JsonNode> h : d.path("hierarchies").properties()) {
            List<String> levels = new ArrayList<>();
            h.getValue().forEach(x -> levels.add(x.asText()));
            hierarchies.put(h.getKey(), levels);
        }
        Map<String, Object> extras = new LinkedHashMap<>();
        if (!history.isEmpty()) {
            extras.put("history", history.size() == 1 ? history.values().iterator().next() : history);
            notes.add("live history: moved to the model's history: (it samples measures, which are a model's; Q14)");
        }
        ModelDef model = new ModelDef(name, version(d.path("version").asText("1.0.0")), about(d), uses, ModelMigration.relationships(d.path("relationships")),
                measures, hierarchies, ModelMigration.security(withoutMasks(d.path("security")), name, columns, keys, translate, changes), extras);
        notes.add("a rachana: 1 dataset with " + tables.size() + " table(s): the tables and the model " + name + " (Q19)");
        return new Out(tables, model, changes, notes, changes.stream().map(TablesMigrator.Change::refusal).filter(r -> r != null).findFirst().orElse(null));
    }

    private TableDef table(JsonNode d, String item, String tableName, String was, JsonNode source, JsonNode columnsNode, JsonNode timeHolder,
            List<TablesMigrator.Change> changes, List<String> notes) {
        String each = source.path("each").asText(null);
        String grain = each == null ? null : grain(each);
        int depth = grain == null ? 0 : (grain.length() - grain.replace("[*]", "").length()) / 3;
        TableDef.Source from = source(source, d, notes);
        if (from == null) {
            return null;
        }
        Map<String, ColumnDef> columns = new LinkedHashMap<>();
        Map<String, String> paths = new LinkedHashMap<>();
        JsonNode base = from.form() == TableDef.Source.Form.TABLE ? datasets.get(baseName(d.path("extends").asText())) : null;
        if (base != null) {
            base.path("columns").properties().forEach(e -> paths.put(e.getKey(), "$." + e.getKey()));
        }
        Set<String> masked = new LinkedHashSet<>();
        d.path("security").path("masked").forEach(x -> masked.add(x.asText()));
        timeHolder.path("security").path("masked").forEach(x -> masked.add(x.asText()));
        List<String> keys = new ArrayList<>();
        for (Map.Entry<String, JsonNode> e : columnsNode.properties()) {
            String c = e.getKey();
            JsonNode v = e.getValue();
            if (TableDef.BUILT_INS.contains(c)) {
                if (v.path("path").isMissingNode() || v.path("path").asText().equals(c)) {
                    notes.add(c + " is a built-in column of every table (Q12): not declared");
                    continue;
                }
                notes.add(c + " reads " + v.path("path").asText() + " but is the name of a built-in column (Q12): rename it");
                return null;
            }
            String path = v.isValueNode() ? null : v.path("path").asText(null);
            String type = v.isValueNode() ? v.asText() : v.path("type").asText(null);
            if (v.path("expr").isMissingNode() && v.path("python").isMissingNode()) {
                path = path(path == null ? c : path, depth);
                paths.put(c, path);
            }
            Map<String, Object> extras = new LinkedHashMap<>();
            for (String k : ColumnDef.EXTRA_KEYS) {
                if (v.has(k)) {
                    extras.put(k, Yaml.MAPPER.convertValue(v.get(k), Object.class));
                }
            }
            boolean key = v.path("key").asBoolean(false) || "key".equals(v.path("role").asText());
            if (key) {
                keys.add(c);
            }
            JsonNode add = v.path("additive");
            columns.put(c, new ColumnDef(c, path, null, v.has("python") ? Yaml.MAPPER.convertValue(v.get("python"), Object.class) : null, type,
                    text(v, "role"), text(v, "meaning"), text(v, "references"), text(v, "unit"), add.isBoolean() ? add.asBoolean() : null, text(v, "aggregate"),
                    text(v, "format"), key, text(v, "description"), masked.contains(c), strings(v.path("hidden-for")), extras));
        }
        Set<String> neverMissing = new LinkedHashSet<>();
        keys.forEach(k -> neverMissing.add(paths.getOrDefault(k, "$." + k)));
        // calculated columns: columns.X.expr and derive.X.expr, row scope, over the source
        List<Map.Entry<String, JsonNode>> calculated = new ArrayList<>();
        columnsNode.properties().stream().filter(e -> e.getValue().has("expr")).forEach(calculated::add);
        d.path("derive").properties().forEach(calculated::add);
        for (Map.Entry<String, JsonNode> e : calculated) {
            String c = e.getKey();
            JsonNode v = e.getValue();
            String del = v.path("expr").asText();
            Translate.Out o = translate.table(del, ExpressionChecker.Scope.ROW, paths, neverMissing);
            changes.add(new TablesMigrator.Change(item, "columns." + c + ".expr", del, o.text(), o.notes(), o.refusal()));
            JsonNode add = v.path("additive");
            columns.put(c, new ColumnDef(c, null, o.text() == null ? del : o.text(), null, v.path("type").asText(null), text(v, "role"), text(v, "meaning"), null,
                    text(v, "unit"), add.isBoolean() ? add.asBoolean() : null, text(v, "aggregate"), text(v, "format"), false, text(v, "description"),
                    masked.contains(c), List.of(), null));
        }
        String filter = null;
        if (d.has("where") && timeHolder == d) {
            String del = d.path("where").asText();
            Translate.Out o = translate.table(del, ExpressionChecker.Scope.ROW, paths, neverMissing);
            changes.add(new TablesMigrator.Change(item, "filter", del, o.text(), o.notes(), o.refusal()));
            filter = o.text() == null ? del : o.text();
        }
        String keepLatest = null;
        String says = null;
        JsonNode g = timeHolder == d ? d.path("grain") : com.fasterxml.jackson.databind.node.MissingNode.getInstance();
        if (g.isObject()) {
            says = g.path("says").asText(null);
            g.path("keys").forEach(x -> keys.add(x.asText()));
            if (g.has("one-row-per")) {
                g.path("one-row-per").forEach(x -> keys.add(x.asText()));
                if (g.path("one-row-per").isValueNode()) {
                    keys.add(g.path("one-row-per").asText());
                }
            }
            String keep = g.path("keep").asText("");
            if (keep.startsWith("latest by ")) {
                keepLatest = keep.substring("latest by ".length()).strip();
            }
        }
        List<TableDef.Rule> rules = new ArrayList<>();
        JsonNode rows = timeHolder.path("security").path("rows");
        if (rows.isMissingNode()) {
            rows = d.path("security").path("rows");
        }
        int i = 0;
        for (JsonNode r : rows) {
            String del = r.path("where").asText("True");
            Translate.Out o = translate.table(del, ExpressionChecker.Scope.RULE, paths, neverMissing);
            changes.add(new TablesMigrator.Change(item, "rules[" + i++ + "].where", del, o.text(), o.notes(), o.refusal()));
            rules.add(new TableDef.Rule(strings(r.path("role")), o.text() == null ? del : o.text()));
        }
        TableDef.Materialize mat = materialize(timeHolder.path("time").isMissingNode() ? timeHolder : timeHolder.path("time"), from, notes);
        Map<String, Object> refresh = d.has("refresh") && timeHolder == d ? castMap(Yaml.MAPPER.convertValue(d.get("refresh"), Map.class)) : null;
        List<Map<String, Object>> tests = new ArrayList<>();
        if (timeHolder == d) {
            d.path("tests").forEach(x -> tests.add(castMap(Yaml.MAPPER.convertValue(x, Map.class))));
        }
        JsonNode time = timeHolder.path("time");
        return new TableDef(tableName, was, version(d.path("version").asText("1.0.0")), timeHolder == d ? about(d) : Map.of("title", d.path("title").asText(item)),
                from, grain, filter, columns, keys.stream().distinct().toList(), keepLatest, says, mat, time.path("as-of").asText(null),
                time.path("keep").asText(null), refresh, rules, strings(timeHolder.path("security").path("hidden-for")), tests);
    }

    /** A version-1 dataset's security without its masks: those are on its tables' columns now (Q9). */
    private static JsonNode withoutMasks(JsonNode security) {
        if (!(security instanceof com.fasterxml.jackson.databind.node.ObjectNode o)) {
            return security;
        }
        com.fasterxml.jackson.databind.node.ObjectNode copy = o.deepCopy();
        copy.remove("masked");
        return copy.isEmpty() ? com.fasterxml.jackson.databind.node.MissingNode.getInstance() : copy;
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> castMap(Map<?, ?> m) {
        return (Map<String, Object>) m;
    }

    private TableDef.Source source(JsonNode s, JsonNode d, List<String> notes) {
        if (d.has("extends")) {
            String base = baseName(d.path("extends").asText());
            return new TableDef.Source(null, null, null, null, TableName.ofDataset(base), null, null, null, null, null, null);
        }
        if (s.has("python")) {
            return new TableDef.Source(null, null, null, null, null, null, map(s.path("params")), s.path("python").asText(), map(s.path("inputs")), null, null);
        }
        if (s.has("model")) {
            return new TableDef.Source(null, null, null, null, null, null, null, null, null, s.path("model").asText(), map(s.path("query")));
        }
        if (s.has("query")) {
            return new TableDef.Source(null, null, s.path("connector").asText(null), null, null, s.path("query").asText(), map(s.path("params")), null, null, null, null);
        }
        if (s.has("sql")) {
            notes.add("a model SQL source (sql:, DSQL) is a summary table over its model: converted in the switch step");
            return null;
        }
        if (s.has("kind")) {
            return new TableDef.Source(s.path("kind").asText(), s.path("pack").asText(null), s.path("connector").asText(null), null, null, null, null, null, null,
                    null, null);
        }
        notes.add("the dataset has no source this tool knows");
        return null;
    }

    private static TableDef.Materialize materialize(JsonNode time, TableDef.Source from, List<String> notes) {
        String mode = time.isValueNode() ? time.asText() : time.path("mode").asText(null);
        if ("live".equals(mode)) {
            JsonNode live = time.path("live");
            return new TableDef.Materialize(TableDef.Materialize.MODE_LIVE, live.has("rows") ? live.get("rows").asInt() : null, live.path("age").asText(null));
        }
        if ("direct".equals(time.path("storage").asText(null))) {
            return TableDef.Materialize.NONE;
        }
        if ("history".equals(mode)) {
            notes.add("a history dataset's sampling moves to its model's history: (Q14)");
        }
        return from.form() == TableDef.Source.Form.KIND || from.form() == TableDef.Source.Form.TABLE ? TableDef.Materialize.ON_LOAD : TableDef.Materialize.NONE;
    }

    /** {@code LEGS} is {@code $.LEGS[*]}; {@code LEGS[].CASH_FLOWS} is {@code $.LEGS[*].CASH_FLOWS[*]}. */
    static String grain(String each) {
        String g = each.startsWith("$.") ? each.substring(2) : each;
        g = g.replace("[]", "[*]").replace("[*]", "");
        StringBuilder out = new StringBuilder("$");
        for (String part : g.split("\\.")) {
            if (!part.isEmpty()) {
                out.append('.').append(part).append("[*]");
            }
        }
        return out.toString();
    }

    /** A dataset column's path in the layer's form: a root always ({@code $} without a grain, {@code @} under one), dotted indexes as brackets. */
    static String path(String p, int depth) {
        if (p.startsWith("$") || p.startsWith("@") || p.startsWith("^")) {
            return p.replaceAll("\\.(\\d+)(?=\\.|$)", "[$1]");
        }
        String body = p.replaceAll("\\.(\\d+)(?=\\.|$)", "[$1]");
        return (depth > 0 ? "@." : "$.") + body;
    }

    static String baseName(String ref) {
        int at = ref.indexOf('@');
        return at < 0 ? ref : ref.substring(0, at);
    }

    static String version(String v) {
        return v.matches("\\d+") ? v + ".0.0" : v.matches("\\d+\\.\\d+") ? v + ".0" : v;
    }

    private static Map<String, Object> about(JsonNode d) {
        Map<String, Object> out = new LinkedHashMap<>();
        for (Map.Entry<String, JsonNode> e : d.properties()) {
            if (ABOUT.contains(e.getKey())) {
                out.put(e.getKey(), Yaml.MAPPER.convertValue(e.getValue(), Object.class));
            }
        }
        return out;
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> map(JsonNode n) {
        return n == null || !n.isObject() ? null : Yaml.MAPPER.convertValue(n, LinkedHashMap.class);
    }

    private static String text(JsonNode v, String k) {
        return v.isValueNode() ? null : v.path(k).asText(null);
    }

    private static List<String> strings(JsonNode n) {
        List<String> out = new ArrayList<>();
        if (n.isValueNode() && !n.isNull()) {
            out.add(n.asText());
        } else {
            n.forEach(x -> out.add(x.asText()));
        }
        return out;
    }
}
