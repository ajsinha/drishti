package com.ash.drishti.module.runtime;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.List;
import java.util.Locale;
import java.util.Properties;
import java.util.Set;
import java.util.TreeSet;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.jar.JarInputStream;
import java.util.stream.Collectors;

/**
 * The libraries the kernel ships (KERNEL_AND_MODULES.md section 4.4): every jar of the server jar's {@code BOOT-INF/lib}, read from
 * {@value #RESOURCE}, which {@code packaging/drishti-app} generates at build time (one line per jar: {@code group:artifact:version}, the
 * jar's name, its package prefixes). Every module loader asks the kernel first, so the kernel's copy of a library always wins; a module that
 * carries its own copy gets one warning sentence per library, at load (WARN and the module's Health notes) and in {@code module verify}.
 * Without the file (a unit test, a run from the IDE) it knows no library and warns of nothing.
 */
public final class KernelLibraries {

    /** Where the generated list is, on the kernel's class path. */
    public static final String RESOURCE = "META-INF/drishti/kernel-libraries.txt";

    private static final String HEADER = "# The libraries the kernel ships (BOOT-INF/lib of the server jar), generated by packaging/drishti-app; do not edit.\n"
            + "# Each line: group:artifact:version jar-name package-prefixes. A module's own copy of one of these is never used (section 4.4).\n";

    /** One library of the kernel. {@code prefixes}: the packages it has classes in, each with its sub-packages. */
    public record Library(String group, String artifact, String version, String jar, List<String> prefixes) {

        public Library {
            prefixes = List.copyOf(prefixes);
        }

        /** True when a package is one of this library's (or below one). */
        boolean holds(String pkg) {
            for (String p : prefixes) {
                if (pkg.equals(p) || pkg.startsWith(p + ".")) {
                    return true;
                }
            }
            return false;
        }

        String line() {
            return group + ":" + artifact + ":" + version + " " + jar + " " + (prefixes.isEmpty() ? "-" : String.join(",", prefixes));
        }
    }

    /** One library a module carries that the kernel also ships: the module's jar, its copy's version and the kernel's library. */
    public record Overlap(String jar, String artifact, String version, Library kernel) {

        /** The warning: names the module, the library and both versions, and says what to do. */
        public String sentence(String module, String moduleVersion) {
            return module + " " + moduleVersion + " carries " + artifact + " " + version + " (" + jar + "); the kernel's " + kernel.artifact() + " "
                    + kernel.version() + " is used instead. Remove the jar from the module and compile against the kernel's (scope provided).";
        }
    }

    private static final java.util.regex.Pattern ANSI = java.util.regex.Pattern.compile("\u001B\\[[;\\d]*m");

    private static final KernelLibraries NONE = new KernelLibraries(List.of(), false);

    private final List<Library> all;
    private final boolean known;

    private KernelLibraries(List<Library> all, boolean known) {
        this.all = List.copyOf(all);
        this.known = known;
    }

    /** No list: nothing is a kernel library, nothing is warned of. */
    public static KernelLibraries none() {
        return NONE;
    }

    /** The kernel's list from its class path ({@value #RESOURCE}), or {@link #none()} when the class path has none. */
    public static KernelLibraries of(ClassLoader kernel) {
        try {
            Enumeration<URL> all = kernel.getResources(RESOURCE);
            if (!all.hasMoreElements()) {
                return NONE;
            }
            try (InputStream in = all.nextElement().openStream()) {
                return parse(new String(in.readAllBytes(), StandardCharsets.UTF_8));
            }
        } catch (IOException e) {
            throw new UncheckedIOException("reading " + RESOURCE, e);
        }
    }

    /** A list from its text (the generated file's lines; {@code #} comments and blank lines skipped). */
    public static KernelLibraries parse(String text) {
        List<Library> out = new ArrayList<>();
        for (String raw : text.split("\n")) {
            String line = raw.strip();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            String[] f = line.split("\\s+");
            String[] gav = f[0].split(":");
            if (gav.length != 3 || f.length < 2) {
                throw new IllegalArgumentException(RESOURCE + ": not group:artifact:version jar prefixes: " + line);
            }
            List<String> prefixes = f.length < 3 || "-".equals(f[2]) ? List.of() : List.of(f[2].split(","));
            out.add(new Library(gav[0], gav[1], gav[2], f[1], prefixes));
        }
        return new KernelLibraries(out, true);
    }

    /** True when the kernel's list was found (a packaged server, {@code module verify} from its jar). */
    public boolean known() {
        return known;
    }

    /** Every library of the kernel, in the file's order. */
    public List<Library> all() {
        return all;
    }

    /** The overlaps of a module (its {@code java/} and {@code lib/} jars), none for a module without Java or when the list is unknown. */
    public List<Overlap> overlaps(ModuleCandidate c) {
        DmodManifest.JavaPart java = c.manifest().java();
        if (java == null || all.isEmpty()) {
            return List.of();
        }
        List<Overlap> out = new ArrayList<>();
        for (String j : java.classPath()) {
            Path jar = c.dir().resolve(j);
            if (Files.isRegularFile(jar)) {
                out.addAll(overlaps(jar));
            }
        }
        return out;
    }

    /** The warning sentences of a module, one per library it carries that the kernel ships. */
    public List<String> warnings(ModuleCandidate c) {
        return overlaps(c).stream().map(o -> o.sentence(c.manifest().id(), c.manifest().version())).toList();
    }

    /**
     * What one module jar carries of the kernel's libraries: by its Maven coordinates ({@code META-INF/maven/.../pom.properties}, each of a
     * shaded jar), else by its file name; a jar named by neither is compared by the packages of its classes (a renamed or repacked copy).
     * Classes of {@code com.ash.drishti.} are not compared by package: the loader gives a module those of its own jars (section 4.4).
     */
    List<Overlap> overlaps(Path jar) {
        String name = jar.getFileName().toString();
        List<Overlap> out = new ArrayList<>();
        Set<String> packages = new TreeSet<>();
        boolean coordinates = false;
        try (JarFile f = new JarFile(jar.toFile())) {
            for (JarEntry e : java.util.Collections.list(f.entries())) {
                String n = e.getName();
                if (n.startsWith("META-INF/maven/") && n.endsWith("/pom.properties")) {
                    Properties p = new Properties();
                    try (InputStream in = f.getInputStream(e)) {
                        p.load(in);
                    }
                    coordinates = true;
                    Library k = find(p.getProperty("groupId"), p.getProperty("artifactId"));
                    if (k != null) {
                        out.add(new Overlap(name, k.artifact(), p.getProperty("version", "?"), k));
                    }
                } else if (n.endsWith(".class") && !n.startsWith("META-INF/") && n.indexOf('/') > 0 && !n.endsWith("module-info.class")) {
                    packages.add(n.substring(0, n.lastIndexOf('/')).replace('/', '.'));
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("reading " + jar, e);
        }
        if (coordinates) {
            return out;
        }
        String[] nv = nameAndVersion(name);
        Library byName = find(null, nv[0]);
        if (byName != null) {
            return List.of(new Overlap(name, byName.artifact(), nv[1], byName));
        }
        for (Library k : all) {
            if (packages.stream().anyMatch(p -> !p.startsWith("com.ash.drishti.") && k.holds(p))) {
                out.add(new Overlap(name, k.artifact(), nv[1], k));
            }
        }
        return out;
    }

    private Library find(String group, String artifact) {
        for (Library k : all) {
            if (k.artifact().equals(artifact) && (group == null || k.group().equals(group))) {
                return k;
            }
        }
        return null;
    }

    /** {@code jackson-databind-2.17.1.jar} to {@code [jackson-databind, 2.17.1]}; no version: {@code [name, ?]}. */
    static String[] nameAndVersion(String file) {
        String base = file.toLowerCase(Locale.ROOT).endsWith(".jar") ? file.substring(0, file.length() - 4) : file;
        for (int i = 0; i < base.length() - 1; i++) {
            if (base.charAt(i) == '-' && Character.isDigit(base.charAt(i + 1))) {
                return new String[] {base.substring(0, i), base.substring(i + 1)};
            }
        }
        return new String[] {base, "?"};
    }

    // ---- generation (packaging/drishti-app, at build time) ----

    /**
     * The build's two steps, run by {@code exec:java} in {@code packaging/drishti-app}: {@code generate <dependency-list> <out>} writes the
     * file from {@code dependency:list} (runtime scope, absolute file names), the very jars the repackaged server jar holds in
     * {@code BOOT-INF/lib}; {@code check <exec-jar> <file>} fails the build unless the file names exactly the jars of {@code BOOT-INF/lib}.
     */
    public static void main(String[] args) throws IOException {
        if (args.length == 3 && "generate".equals(args[0])) {
            List<Library> libs = fromDependencyList(Files.readAllLines(Path.of(args[1]), StandardCharsets.UTF_8));
            Path out = Path.of(args[2]);
            Files.createDirectories(out.getParent());
            Files.writeString(out, format(libs), StandardCharsets.UTF_8);
            System.out.println("kernel-libraries: " + libs.size() + " libraries -> " + out);
        } else if (args.length == 3 && "check".equals(args[0])) {
            Set<String> listed = parse(Files.readString(Path.of(args[2]), StandardCharsets.UTF_8)).all.stream().map(Library::jar)
                    .collect(Collectors.toCollection(TreeSet::new));
            Set<String> inJar = bootLib(Path.of(args[1]));
            if (!listed.equals(inJar)) {
                Set<String> missing = new TreeSet<>(inJar);
                missing.removeAll(listed);
                Set<String> extra = new TreeSet<>(listed);
                extra.removeAll(inJar);
                throw new IllegalStateException(RESOURCE + " does not match BOOT-INF/lib of " + args[1] + ": not listed " + missing + "; listed but not there "
                        + extra);
            }
            System.out.println("kernel-libraries: " + listed.size() + " libraries, the same as BOOT-INF/lib of " + Path.of(args[1]).getFileName());
        } else {
            throw new IllegalArgumentException("usage: KernelLibraries generate <dependency-list> <out> | check <exec-jar> <kernel-libraries.txt>");
        }
    }

    /** The file's text. */
    public static String format(List<Library> libs) {
        StringBuilder b = new StringBuilder(HEADER);
        libs.stream().sorted(java.util.Comparator.comparing(Library::group).thenComparing(Library::artifact))
                .forEach(l -> b.append(l.line()).append('\n'));
        return b.toString();
    }

    /**
     * The libraries of {@code dependency:list} output ({@code group:artifact:type[:classifier]:version:scope:/abs/file[ -- module x]}): every
     * jar of compile or runtime scope, named as Spring Boot names it in {@code BOOT-INF/lib}, with the package prefixes of its classes.
     */
    static List<Library> fromDependencyList(List<String> lines) throws IOException {
        List<Library> out = new ArrayList<>();
        for (String raw : lines) {
            String line = ANSI.matcher(raw).replaceAll("").strip();      // Maven colours the listing on a terminal
            int module = line.indexOf(" -- ");
            if (module > 0) {
                line = line.substring(0, module).strip();
            }
            String[] f = line.split(":");
            int scope = -1;
            for (int i = 3; i < f.length; i++) {
                if ("compile".equals(f[i]) || "runtime".equals(f[i])) {
                    scope = i;
                    break;
                }
            }
            if (scope < 0 || f.length <= scope + 1 || !"jar".equals(f[2])) {
                continue;
            }
            String group = f[0];
            String artifact = f[1];
            String version = f[scope - 1];
            String classifier = scope == 5 ? f[3] : null;
            Path file = Path.of(String.join(":", java.util.Arrays.copyOfRange(f, scope + 1, f.length)));
            if (starter(file)) {
                continue;               // Spring Boot leaves a starter (no classes, only dependencies) out of BOOT-INF/lib
            }
            String jar = artifact + "-" + version + (classifier == null ? "" : "-" + classifier) + ".jar";
            out.add(new Library(group, artifact, version, jar, prefixes(packagesOf(file))));
        }
        return out;
    }

    /** True for a jar Spring Boot's repackaging leaves out: its manifest says {@code Spring-Boot-Jar-Type: dependencies-starter}. */
    private static boolean starter(Path file) throws IOException {
        if (!Files.isRegularFile(file)) {
            return false;
        }
        try (JarFile j = new JarFile(file.toFile())) {
            java.util.jar.Manifest mf = j.getManifest();
            return mf != null && "dependencies-starter".equals(mf.getMainAttributes().getValue("Spring-Boot-Jar-Type"));
        }
    }

    private static Set<String> packagesOf(Path file) throws IOException {
        Set<String> packages = new TreeSet<>();
        if (Files.isDirectory(file)) {          // a reactor project not yet packaged: its classes folder
            try (var s = Files.walk(file)) {
                s.filter(p -> p.toString().endsWith(".class") && p.getParent() != null && !p.getParent().equals(file))
                        .map(p -> file.relativize(p.getParent()).toString().replace(java.io.File.separatorChar, '.'))
                        .filter(p -> !p.startsWith("META-INF")).forEach(packages::add);
            }
            return packages;
        }
        try (JarInputStream in = new JarInputStream(Files.newInputStream(file))) {
            for (JarEntry e = in.getNextJarEntry(); e != null; e = in.getNextJarEntry()) {
                String n = e.getName();
                if (n.endsWith(".class") && !n.startsWith("META-INF/") && n.indexOf('/') > 0) {
                    packages.add(n.substring(0, n.lastIndexOf('/')).replace('/', '.'));
                }
            }
        }
        return packages;
    }

    /** The fewest prefixes that cover every package: a package below a kept one is covered by it. */
    static List<String> prefixes(Set<String> packages) {
        List<String> kept = new ArrayList<>();
        for (String p : new TreeSet<>(packages)) {
            if (kept.stream().noneMatch(k -> p.equals(k) || p.startsWith(k + "."))) {
                kept.add(p);
            }
        }
        return kept;
    }

    /** The names of the jars in an executable jar's {@code BOOT-INF/lib}. */
    static Set<String> bootLib(Path execJar) throws IOException {
        Set<String> out = new TreeSet<>();
        try (JarFile f = new JarFile(execJar.toFile())) {
            for (JarEntry e : java.util.Collections.list(f.entries())) {
                String n = e.getName();
                // Spring Boot's own jar-mode tools (java -Djarmode=tools) are added by the repackaging, never on the kernel's class path
                if (n.startsWith("BOOT-INF/lib/") && n.endsWith(".jar") && n.indexOf('/', "BOOT-INF/lib/".length()) < 0
                        && !n.startsWith("BOOT-INF/lib/spring-boot-jarmode-")) {
                    out.add(n.substring("BOOT-INF/lib/".length()));
                }
            }
        }
        return out;
    }
}
