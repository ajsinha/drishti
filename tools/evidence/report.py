def cell(claim: str | None, res: dict | None) -> str:
    if claim is None:
        return "proved in the drill (not measured here)"
    if res is None:
        return "not yet run"
    diffs = [d for d in res["differences"] if d["claim"] == claim or (claim == "EV5" and d["claim"] == "EV5")]
    if not diffs:
        return f"no difference ({res['identical']} artefacts identical in all)"
    unlisted = [d for d in diffs if d["class"] == "unlisted"]
    if unlisted:
        return f"**{len(unlisted)} unlisted difference(s)**: " + "; ".join(f"`{d['artefact']}` {d['difference']}" for d in unlisted[:3])
    return f"{len(diffs)} reviewed difference(s)"


def golden_check(capture: Path | None) -> str:
    """The grand total of the captured VaR figures, rounded to whole numbers, against the plan's goldens (EV4)."""
    try:
        cells = json.loads((capture / "figures.json").read_text())[0]["body"]["cells"]["*|*"]["values"]
        got = (f"{round(cells['var()']):,}", f"{round(cells['es()']):,}")
    except (OSError, KeyError, IndexError, TypeError, ValueError):
        return "not measured: the capture holds no VaR and ES grand total."
    ok = got == GOLDENS
    return f"captured grand total on the scratch server's demo bank: 1-day 99.5% VaR **{got[0]}**, ES **{got[1]}**: " + ("equal to the goldens." if ok else f"**not equal** to the goldens {GOLDENS[0]} and {GOLDENS[1]}.")


def build(baseline: Path | None, steps: list) -> str:
    man = json.loads((baseline / "manifest.json").read_text()) if baseline and (baseline / "manifest.json").exists() else None
    lines = [HEADER, "# Products migration evidence", "",
             "What moved when Drishti was migrated onto the Elements and Rachana products, and the proof that nothing a user sees moved except what is listed. "
             "Two classes of proof, never mixed: **exact** (bytes or numbers equal) and **reviewed** (a difference is expected, each one listed with its reason).", ""]
    if man:
        c = man["counts"]
        lines += ["## The baseline", "", f"`{man['label']}` at commit `{man['commit']}`, server jar `{man['jar']}` (SHA-256 `{(man['jarSha256'] or '')[:16]}`): "
                  f"{c['sutras']} Sutras served, {c['viewmodels']} ViewModels, {c['noEntity']} Sutras with no entity to draw, {c['frames']} streams, "
                  f"{c['answers']} API answers, {c['pages']} console pages.", ""]
    head = "| Claim | Proof | Class |" + "".join(f" {name} |" for name, _ in steps)
    lines += ["## The claims", "", head, "|---|---|---|" + "---|" * len(steps)]
    for cid, claim, proof, cls, measured in CLAIMS:
        lines.append(f"| **{cid}** {claim} | {proof} | {cls} |" + "".join(f" {cell(measured, res)} |" for _, res in steps))
    lines += ["", "## Reviewed differences", ""]
    any_rev = False
    for name, res in steps:
        for d in (res or {}).get("differences", []):
            if d["class"] == "reviewed":
                any_rev = True
                lines.append(f"- **{name}**: `{d['artefact']}` `{d['path']}`: {d['reason']}")
    if not any_rev:
        lines.append("None.")
    lines += ["", "## The golden figures (EV4)", "", f"The plan's goldens: 1-day 99.5% VaR **{GOLDENS[0]}**, ES **{GOLDENS[1]}**; " + golden_check(baseline), ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--baseline", help="the baseline capture: a folder or its .tar.gz")
    ap.add_argument("--step", action="append", default=[], help="NAME=compare.json, once per Drishti step")
    ap.add_argument("--steps-file", help="a file of NAME=compare.json lines (the committed list: testing/evidence/steps.txt)")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    steps = []
    listed = [ln for ln in Path(a.steps_file).read_text().splitlines() if ln.strip()] if a.steps_file else []
    for s in listed + a.step:
        name, _, path = s.partition("=")
        steps.append((name, json.loads(Path(path).read_text()) if Path(path).exists() else None))
    import tempfile
    import common
    base = Path(a.baseline) if a.baseline else None
    with tempfile.TemporaryDirectory() as tmp:
        if base and base.is_file():
            base = common.unpack(base, Path(tmp))
        text = build(base, steps) + "\n"
    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out} is stale: run python3 tools/evidence/report.py", file=sys.stderr)
            return 1
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
