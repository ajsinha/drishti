"""The connector files an older release's server generated, as the fixture of the upgrade drill stage (ConnectorUpgradeTest,
docs/connectors/CONNECTOR_FILES.md "Upgrades"): each connector template of the demo packs at a git revision rendered the way that
server wrote it (its header, the template's fields in the server's order, settings flattened to dotted keys, lists as comma text) with
the marker it kept in <data>/connectors/generated/, plus deliberately edited files:

* var-whatif generated by 2.9.3 (before the reporting-currency parameter ccy) and then edited (limits.wait), the file the 2.9.4 drill
  met: it must gain ccy (and every other key the template has) and keep its edit, its reads' id listed as a conflict;
* risk-store with an administrator's own refresh-seconds: kept, everything else the template gained added.

    python3 tools/connector_upgrade_fixture.py --rev 0bcfb7322 --out drishti-server/src/test/resources/connector-upgrade/2.9.4

Writes <out>/connectors/*.yaml, <out>/generated/*.properties and <out>/edits.json (the edited keys per connector). Deterministic.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
PACKS = ("core", "market-data", "trading", "counterparty-risk", "market-risk")
COMPUTE_KEYS = ("reads", "engine", "triggers", "coalesce", "cache", "limits", "history", "incremental")
HEADER = "# Generated at first start from the connector template of pack '{pack}'. Edit it freely: it is never overwritten.\n"


def etag(text: str) -> str:
    """ConnectorFiles.etag: the first 8 bytes of the SHA-256 of the text, as hex."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def show(rev: str, path: str) -> str:
    return subprocess.run(["git", "show", f"{rev}:{path}"], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def scalar(v) -> str:
    """String.valueOf of a YAML value as Java gives it (true, 1.0, 4)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def flatten(prefix: str, settings: dict, out: dict) -> None:
    """PackLoader.flatten: nested keys dotted, a list as comma-separated text."""
    for k, v in settings.items():
        if isinstance(v, dict):
            flatten(f"{prefix}{k}.", v, out)
        elif isinstance(v, list):
            out[f"{prefix}{k}"] = ",".join(scalar(x) for x in v)
        else:
            out[f"{prefix}{k}"] = scalar(v)


def render(pack: str, t: dict) -> str:
    """ConnectorFiles.render of a template, in the server's field order."""
    doc: dict = {"plugin": t["plugin"]}
    reactive = str(t["plugin"]).strip() == "reactive"
    if reactive and t.get("mode") is not None:
        doc["mode"] = t["mode"]
    if t.get("enabled") is not None and scalar(t["enabled"]) != "true":
        doc["enabled"] = t["enabled"]
    if t.get("description"):
        doc["description"] = t["description"]
    kinds = t.get("kinds")
    if kinds:
        doc["kinds"] = kinds
    if reactive:
        for key in COMPUTE_KEYS:
            if t.get(key) is not None:
                doc[key] = t[key]
    flat: dict = {}
    flatten("", t.get("settings") or {}, flat)
    if flat:
        doc["settings"] = flat
    return HEADER.format(pack=pack) + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000)


def marker(text: str, t: dict, rev: str) -> str:
    kinds = t.get("kinds") or []
    names = list(kinds.keys()) if isinstance(kinds, dict) else [str(k) for k in kinds]
    return f"file={etag(text)}\ntemplate={rev}-{etag(yaml.safe_dump(t, sort_keys=True))}\nkinds={','.join(names)}\n"


def templates(rev: str) -> dict:
    """{connector: (pack, template)} of the demo packs at the revision; a later pack's template of the same name wins (more specific)."""
    out = {}
    for p in PACKS:
        m = yaml.safe_load(show(rev, f"config/packs/{p}/pack.yaml")) or {}
        for name, t in (m.get("connectors") or {}).items():
            if isinstance(t, dict) and t.get("plugin"):
                out[name] = (p, t)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--rev", required=True, help="the release whose server generated the files (0bcfb7322 is release 2.9.4)")
    ap.add_argument("--before", default="v2.9.3", help="the release var-whatif was generated by before it was edited (default v2.9.3)")
    ap.add_argument("--out", type=pathlib.Path, required=True)
    a = ap.parse_args(argv)
    out = a.out.resolve()
    shutil.rmtree(out, ignore_errors=True)
    (out / "connectors").mkdir(parents=True)
    (out / "generated").mkdir(parents=True)
    edits: dict = {}
    for name, (pack, t) in sorted(templates(a.rev).items()):
        text = render(pack, t)
        mark = marker(text, t, a.rev)
        if name == "var-whatif":
            old_pack, old = templates(a.before)[name]
            text = render(old_pack, old)
            mark = marker(text, old, a.before)
            doc = yaml.safe_load(text)
            doc.setdefault("limits", {})["wait"] = "45s"                # the administrator's edit
            text = HEADER.format(pack=old_pack) + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000)
            edits[name] = ["limits.wait"]
        elif name == "risk-store":
            doc = yaml.safe_load(text)
            doc["settings"]["refresh-seconds"] = "45"
            text = HEADER.format(pack=pack) + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000)
            edits[name] = ["refresh-seconds"]
        (out / "connectors" / f"{name}.yaml").write_text(text, encoding="utf-8")
        (out / "generated" / f"{name}.properties").write_text(mark, encoding="utf-8")
    (out / "edits.json").write_text(json.dumps({"rev": a.rev, "packs": list(PACKS), "edited": edits}, indent=2) + "\n", encoding="utf-8")
    print(f"{len(list((out / 'connectors').glob('*.yaml')))} connector files from {a.rev} in {out} ({len(edits)} edited)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
