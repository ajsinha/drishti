"""The catalog of every command: docs/guides/COMMAND_CATALOG.md, generated from the packs (codes, mnemonics, examples), their data
contracts (what each kind is, its class, and whether it moves to the compute model) and tools/commands.builtin.yaml (the command line's
own words and forms).

    python3 tools/command_catalog.py            write docs/guides/COMMAND_CATALOG.md
    python3 tools/command_catalog.py --check    fail when it differs from what would be written
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PACKS = ROOT / "config" / "packs"
BUILTIN = Path(__file__).resolve().parent / "commands.builtin.yaml"
OUT = ROOT / "docs" / "guides" / "COMMAND_CATALOG.md"
CLASSES = {"fundamental": "fundamental", "input": "engine input", "drishti-owned": "Drishti's own", "computed": "computed"}


def _cell(text) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _contract_link(path: str) -> str:
    """A replaced-by path as a link when the contract is written (the help links test reads every link), else its name."""
    name = Path(path).name
    return f"[{name}](../contracts/{name})" if (ROOT / path).is_file() else f"`{name}`"


def _example(mnemonic: str, examples: list, contract: dict) -> str:
    """The pack's own example for the mnemonic, else the mnemonic with the example id its contract records."""
    for ex in examples or []:
        cmd = ex[0] if isinstance(ex, (list, tuple)) else str(ex)
        if cmd.split()[:1] == [mnemonic]:
            return f"`{cmd}`"
    key = (contract.get("key") or [None])[0]
    for f in contract.get("fields") or []:
        if f.get("name") == key and f.get("example") not in (None, ""):
            return f"`{mnemonic} {f['example']}`"
    return ""


def _change(contract: dict) -> str:
    if contract.get("status") == "retiring":
        return f"Moves to compute in {contract.get('retiring-in')}: {_contract_link(contract.get('replaced-by', ''))}"
    figures = [f["name"] for f in contract.get("fields") or [] if f.get("retiring-in")]
    if figures:
        release = contract["fields"][[f["name"] for f in contract["fields"]].index(figures[0])]["retiring-in"]
        return f"Figures computed from {release}: {', '.join(f'`{f}`' for f in figures)}"
    return ""


def packs() -> list[dict]:
    """Each pack with a mnemonic: its code, title, description, examples and, per mnemonic, its kind, label and contract."""
    out = []
    for path in sorted(PACKS.glob("*/pack.yaml")):
        pack = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        mnemonics = pack.get("mnemonics") or {}
        if not mnemonics:
            continue
        rows = []
        for code, m in mnemonics.items():
            kind = m.get("kind") if isinstance(m, dict) else m
            cpath = path.parent / "contracts" / f"{kind}.contract.yaml"
            contract = yaml.safe_load(cpath.read_text(encoding="utf-8")) if cpath.is_file() else {}
            rows.append({"code": code, "kind": kind, "label": (m.get("label") if isinstance(m, dict) else "") or contract.get("title", kind),
                         "contract": contract})
        out.append({"name": path.parent.name, "code": pack.get("code", ""), "title": pack.get("title", path.parent.name),
                    "description": pack.get("description", ""), "examples": (pack.get("console") or {}).get("examples") or [],
                    "rows": rows})
    return out


def render() -> str:
    header = (ROOT / "config" / "license-header.txt").read_text(encoding="utf-8").strip()
    builtin = yaml.safe_load(BUILTIN.read_text(encoding="utf-8"))
    all_packs = packs()
    rows = [r for p in all_packs for r in p["rows"]]
    classes = Counter(r["contract"].get("class", "") for r in rows)
    moving = [r for r in rows if r["contract"].get("status") == "retiring"]
    split = [r for r in rows if r["contract"].get("status") != "retiring" and _change(r["contract"])]
    out = ["<!--", *(("  " + line).rstrip() for line in header.splitlines()), "-->",
           "<!-- Generated by tools/command_catalog.py from config/packs/*/pack.yaml, their contracts and tools/commands.builtin.yaml. "
           "Edit those, not this file. -->", "",
           "# The command catalog", "",
           f"Every command of the command line: its own words and forms, the {len(all_packs)} packs' codes, and the {len(rows)} mnemonics "
           "the packs define, each with what it does and an example. A pack's mnemonics work when the pack is switched on "
           "([PACKS.md](PACKS.md)); how to type them is in [USER_GUIDE.md](USER_GUIDE.md).", "",
           "**Data** says what kind of data a command shows ([the data contracts](../contracts/README.md#3-four-kinds-of-data)): "
           "*fundamental* (masters, terms, market and public data, kept as delivered), *engine input* (what upstream engines deliver for "
           "the computed measures), *Drishti's own* (made by Drishti) and *computed* (worked out when asked). **Change** says when a "
           "command moves to the compute model, or when the figures on a record start to be computed instead of stored "
           "([the roadmap](../architecture/IMPLEMENTATION_PLAN.md#the-computed-measures-roadmap-280-to-2120-product-owner-2026-10-25)). "
           "Each mnemonic's fields are in its data contract ([every command's contract](../contracts/packs/README.md)).", "",
           f"In numbers: {classes.get('fundamental', 0)} fundamental, {classes.get('input', 0)} engine input, "
           f"{classes.get('drishti-owned', 0)} Drishti's own and {classes.get('computed', 0)} computed; {len(moving)} move to the compute "
           f"model and {len(split)} keep their record while its figures become computed.", "",
           "## Contents", "", "- [The command line's own forms](#the-command-lines-own-forms)", "- [Reserved words](#reserved-words)",
           "- [Pack codes](#pack-codes)"]
    out += [f"- [{p['title']} (`{p['name']}`)](#{_anchor(p['title'], p['name'])})" for p in all_packs]
    out += ["", "## The command line's own forms", "", "| Form | Example | What it does |", "|---|---|---|"]
    out += [f"| `{_cell(f['form'])}` | `{_cell(f['example'])}` | {_cell(f['does'])} |" for f in builtin["forms"]]
    out += ["", "## Reserved words", "", "No pack may define a mnemonic with these names; they work in any case.", "",
            "| Word | Example | What it does |", "|---|---|---|"]
    out += [f"| `{w['word']}` | `{_cell(w['example'])}` | {_cell(w['does'])} |" for w in builtin["words"]]
    out += ["", "## Pack codes", "", "A pack's code typed alone opens the pack's overview.", "", "| Code | Pack | What it holds |", "|---|---|---|"]
    out += [f"| `{p['code']}` | `{p['name']}` | {_cell(p['description'])} |" for p in all_packs if p["code"]]
    for p in all_packs:
        out += ["", f"## {p['title']} (`{p['name']}`)", "", _cell(p["description"]), "",
                "| Command | Opens | What it does | Example | Data | Change |", "|---|---|---|---|---|---|"]
        for r in p["rows"]:
            c = r["contract"]
            out.append(f"| `{r['code']}` | {_cell(r['label'])} | {_cell(c.get('description', ''))} | {_example(r['code'], p['examples'], c)} | "
                       f"{CLASSES.get(c.get('class', ''), c.get('class', ''))} | {_change(c)} |")
    out += ["", "---", "", "*Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved.",
            "Proprietary and confidential. Unauthorised copying, use or distribution is prohibited.*", ""]
    return "\n".join(out)


def _anchor(title: str, name: str) -> str:
    text = f"{title} ({name})".lower()
    return "".join(ch for ch in text.replace(" ", "-") if ch.isalnum() or ch in "-_")


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description="Write or check docs/guides/COMMAND_CATALOG.md.")
    p.add_argument("--check", action="store_true", help="fail when the catalog differs from what would be written")
    args = p.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/command_catalog.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
