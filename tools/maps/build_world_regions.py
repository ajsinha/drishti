"""Builds the world-regions table: every country's ISO alpha-3 code to its sub-region and continent, from Natural Earth admin-0.

Source   Natural Earth 1:10m Admin 0 - Map Units (public domain, https://www.naturalearthdata.com/), the fields REGION_UN (the continent
         in the UN's five-continent scheme, plus Antarctica) and SUBREGION (the UN-style sub-region), keyed by ADM0_A3: the same codes the
         vendored world map uses. Not the UN Statistics Division's M49 list, whose terms of reuse are not plainly public domain.
Output   compute/drishti-rachana/src/main/resources/world-regions.yaml: the ONE home of the grouping. The server reads it (WorldRegions.java);
         the chart's map reads a table generated from it (tools/elements/build.py: drishti_world-regions.js).
Usage    python3 tools/maps/build_world_regions.py [--cache FILE]

A place that Natural Earth splits across regions (France's and the Netherlands' overseas units, Norway's Antarctic claim) belongs to its
sovereign's home region, in OVERRIDES; the codes the map has that Natural Earth keys differently (ESH, PSE, SSD) follow their pair."""
import argparse
import json
import re
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_map_units.geojson"
ROOT = Path(__file__).resolve().parents[2]
MAPS = ROOT / "drishti-console/web/static/vendor/echarts/maps"
OUT = ROOT / "compute/drishti-rachana/src/main/resources/world-regions.yaml"
OVERRIDES = {"FRA": ("Europe", "Western Europe"), "NOR": ("Europe", "Northern Europe"), "NLD": ("Europe", "Western Europe"), "PRT": ("Europe", "Southern Europe"),
             "NZL": ("Oceania", "Australia and New Zealand"), "UMI": ("Americas", "Northern America"),
             "ATF": ("Africa", "Eastern Africa"), "IOT": ("Africa", "Eastern Africa"), "HMD": ("Oceania", "Australia and New Zealand"), "SGS": ("Americas", "South America")}   # the last four: NE's "Seven seas"
PAIRS = {"ESH": "SAH", "PSE": "PSX", "SSD": "SDS"}          # a code the map uses, the code Natural Earth uses for the same place
CONTINENT = {"Africa": "AFR", "Americas": "AME", "Asia": "ASI", "Europe": "EUR", "Oceania": "OCE", "Antarctica": "ANT"}


HEADER = [ln for ln in (OUT.parent / "formats.yaml").read_text(encoding="utf-8").splitlines()[:13] if ln.startswith("#")]   # the licence header of the neighbouring file


def slug(name: str) -> str:
    return re.sub(r"[^A-Z]+", "-", name.upper()).strip("-")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", help="a downloaded copy of the Natural Earth file")
    a = ap.parse_args()
    raw = Path(a.cache).read_bytes() if a.cache else urllib.request.urlopen(URL, timeout=120).read()
    by: dict[str, set] = {}
    for f in json.loads(raw)["features"]:
        p = f["properties"]
        if p.get("ADM0_A3"):
            by.setdefault(p["ADM0_A3"], set()).add((p.get("REGION_UN"), p.get("SUBREGION")))
    ours = {x["properties"]["iso3"] for x in json.loads((MAPS / "world-countries.json").read_text(encoding="utf-8"))["features"]}
    ours |= {x["iso3"] for x in json.loads((MAPS / "world-points.json").read_text(encoding="utf-8"))}
    table: dict[str, tuple[str, str]] = {}
    for code in sorted(ours):
        if code in OVERRIDES:
            table[code] = OVERRIDES[code]
            continue
        got = by.get(code) or by.get(PAIRS.get(code, ""))
        if not got or len(got) != 1:
            raise SystemExit(f"{code}: Natural Earth gives {got}: add it to OVERRIDES")
        table[code] = next(iter(got))
    subs: dict[str, dict] = {}
    for code, (cont, sub) in sorted(table.items()):
        if cont not in CONTINENT:
            cont = "Antarctica" if cont == "Antarctica" else cont
        s = subs.setdefault(sub, {"name": sub, "continent": "CT-" + CONTINENT[cont], "countries": []})
        s["countries"].append(code)
    lines = HEADER + ["# World regions: every country (ISO 3166 alpha-3 as the map and the data name it) in one sub-region, every sub-region in one continent.",
             "# The ONE home of the grouping: the server reads it (WorldRegions.java), the chart's map reads a table generated from it by",
             "# tools/elements/build.py. GENERATED by tools/maps/build_world_regions.py from Natural Earth admin-0 (public domain): do not edit.",
             "# Codes: CT-<ABC> a continent, SR-<NAME> a sub-region, so a region's code never clashes with a country's.",
             "source: Natural Earth admin-0 map units, fields REGION_UN and SUBREGION (public domain)", "continents:"]
    for name, k in CONTINENT.items():
        lines.append(f"  CT-{k}: {name}")
    lines.append("subregions:")
    for name, s in sorted(subs.items(), key=lambda kv: (kv[1]["continent"], kv[0])):
        lines.append(f"  SR-{slug(name)}:")
        lines.append(f"    name: {name}")
        lines.append(f"    continent: {s['continent']}")
        lines.append("    countries: [" + ", ".join(s["countries"]) + "]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(table)} countries, {len(subs)} sub-regions")


if __name__ == "__main__":
    main()
