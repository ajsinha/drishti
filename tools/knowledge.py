"""The Knowledge pages' glossaries, generated from one data file, docs/knowledge/glossary.yaml, so the pages and the console's
WHAT <term> never drift apart.

Each Knowledge page (docs/knowledge/<domain>.md) holds its domain's terms between the markers ``<!-- glossary:start -->`` and
``<!-- glossary:end -->``; the Knowledge home (docs/knowledge/README.md) holds every term, A to Z, with the page it is on.

    python3 tools/knowledge.py            write the Glossary sections
    python3 tools/knowledge.py --check    fail when a page differs from what would be written, or the glossary is invalid
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "docs" / "knowledge"
GLOSSARY = DIR / "glossary.yaml"
HOME = DIR / "README.md"
START = "<!-- glossary:start (generated by tools/knowledge.py from docs/knowledge/glossary.yaml: edit that file, not this section) -->"
END = "<!-- glossary:end -->"
_MARKED = re.compile(r"<!-- glossary:start[^>]*-->.*?<!-- glossary:end -->", re.S)
FIELDS = {"term", "name", "synonyms", "domain", "meaning", "command", "cli"}


def anchor(term: str) -> str:
    """An entry's anchor: ``term-`` and the term in lower case, each run of other characters one hyphen (``P&L vector``: ``term-p-l-vector``).
    The console's WHAT (drishti-console/core/knowledge.py) makes the same."""
    return "term-" + re.sub(r"[^a-z0-9]+", "-", term.lower()).strip("-")


def load(path: Path = GLOSSARY) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def problems(data: dict) -> list[str]:
    """What is wrong with the glossary: unknown fields or domains, a missing meaning, a word two entries both answer to."""
    bad, seen = [], {}
    domains = data.get("domains") or {}
    for d, info in domains.items():
        if not (DIR / info["page"]).is_file():
            bad.append(f"domain {d}: page {info['page']} does not exist")
    for e in data.get("terms") or []:
        name = e.get("term", "?")
        if set(e) - FIELDS:
            bad.append(f"{name}: unknown fields {sorted(set(e) - FIELDS)}")
        if e.get("domain") not in domains:
            bad.append(f"{name}: unknown domain {e.get('domain')}")
        if not str(e.get("meaning", "")).strip():
            bad.append(f"{name}: no meaning")
        if re.search(r"<[^`]*>", re.sub(r"`[^`]*`", "", str(e.get("meaning", "")))):
            bad.append(f"{name}: a <placeholder> outside `backticks` in its meaning (Markdown would read it as HTML)")
        for word in words(e):
            if word in seen and seen[word] != name:
                bad.append(f"'{word}' names both {seen[word]} and {name}")
            seen.setdefault(word, name)
    return bad


def words(entry: dict) -> list[str]:
    """Every way a reader may type an entry, normalised: the term, its name and its synonyms (lower case, single spaces)."""
    found = [entry.get("term", ""), entry.get("name", "")] + list(entry.get("synonyms") or [])
    out = []
    for w in found:
        w = " ".join(str(w).lower().split())
        if w and w not in out:
            out.append(w)
    return out


def _cell(text) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _shows(e: dict) -> str:
    out = []
    if e.get("command"):
        out.append(f"`{_cell(e['command'])} <GO>`")
    if e.get("cli"):
        out.append(f"`{_cell(e['cli'])}`")
    return " · ".join(out)


def _title(e: dict) -> str:
    return f"**{_cell(e['term'])}**" + (f" ({_cell(e['name'])})" if e.get("name") else "")


def domain_section(data: dict, domain: str) -> str:
    """A page's Glossary section: its terms in the file's order, each with its anchor, meaning and the command that shows it."""
    rows = [e for e in data["terms"] if e["domain"] == domain]
    out = [START, "", f"{len(rows)} terms. Type `WHAT <term>` on the command line to open any of them (`WHAT PFE`).", "",
           "| Term | Meaning | See it in Drishti |", "|---|---|---|"]
    out += [f'| <a id="{anchor(e["term"])}"></a>{_title(e)} | {_cell(e["meaning"])} | {_shows(e)} |' for e in rows]
    return "\n".join(out + ["", END])


def home_section(data: dict) -> str:
    """The home page's index: every term A to Z with the page that explains it."""
    domains = data["domains"]
    rows = sorted(data["terms"], key=lambda e: e["term"].lower())
    out = [START, "", f"{len(rows)} terms in {len(domains)} pages. `WHAT <term>` opens any of them.", "",
           "| Term | Meaning | Page |", "|---|---|---|"]
    for e in rows:
        d = domains[e["domain"]]
        out.append(f"| [{_cell(e['term'])}]({d['page']}#{anchor(e['term'])})" + (f" ({_cell(e['name'])})" if e.get("name") else "")
                   + f" | {_cell(e['meaning'])} | [{d['title']}]({d['page']}) |")
    return "\n".join(out + ["", END])


def rendered(data: dict) -> dict[Path, str]:
    """Every page the glossary writes into, with its new text (pages without the markers are left alone and reported)."""
    out = {}
    targets = [(HOME, home_section(data))] + [(DIR / info["page"], domain_section(data, d)) for d, info in data["domains"].items()]
    for path, section in targets:
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        if not _MARKED.search(text):
            raise SystemExit(f"{path.relative_to(ROOT)} has no glossary markers ({START[:24]}... {END})")
        out[path] = _MARKED.sub(lambda _m: section, text, count=1)
    return out


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description="Write or check the Knowledge pages' Glossary sections from docs/knowledge/glossary.yaml.")
    p.add_argument("--check", action="store_true", help="fail when a page differs from what would be written, or the glossary is invalid")
    args = p.parse_args(argv)
    data = load()
    bad = problems(data)
    if bad:
        print("docs/knowledge/glossary.yaml:\n  " + "\n  ".join(bad), file=sys.stderr)
        return 1
    pages = rendered(data)
    stale = [path for path, text in pages.items() if path.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            print("stale: " + ", ".join(str(s.relative_to(ROOT)) for s in stale) + ": run python3 tools/knowledge.py", file=sys.stderr)
            return 1
        print(f"{len(pages)} Knowledge pages are current ({len(data['terms'])} terms)")
        return 0
    for path in stale:
        path.write_text(pages[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"{len(pages)} Knowledge pages, {len(data['terms'])} terms")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
