"""The copy-paste detector's pieces, and the ratchet itself: marked static, so the gate runs it (tools/drill.sh, gate_checks)."""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import duplicates as d  # noqa: E402

pytestmark = pytest.mark.static

XML = """<pmd-cpd xmlns="https://pmd-code.org/schema/cpd-report">
<duplication lines="3" tokens="120"><file path="{root}/a.java" line="1" endline="3"/><file path="{root}/b.java" line="5" endline="7"/></duplication>
<duplication lines="2" tokens="101"><file path="{root}/a.java" line="2" endline="3"/><file path="{root}/c.java" line="1" endline="2"/></duplication>
</pmd-cpd>"""


@pytest.mark.parametrize("path", [
    "drishti-engine/src/test/java/A.java", "drishti-console/tests/x.py", "tools/test_x.py", "drishti-it/src/main/java/A.java",
    "drishti-console/web/static/vendor/x/y.js", "drishti-console/web/static/render/1.2.0/a.js", "drishti-console/web/embed/a.js",
    "a/b.min.js", "docs/guides/examples/connector/src/main/java/A.java", "drishti-console/web/static/elements/drishti-grid/drishti_harness.js",
])
def test_excluded_paths(path: str) -> None:
    assert not d.counted(path, "")


@pytest.mark.parametrize("path", [
    "drishti-engine/src/main/java/A.java", "drishti-console/core/x.py", "tools/varcli.py", "drishti-console/web/static/js/drishti_x.js",
    "drishti-console/web/static/elements/drishti-grid/src/a.js", "drishti-console/web/static/render/2.0.0/a.js", "drishti-console/plugins/banking/static/js/a.js",
])
def test_counted_paths(path: str) -> None:
    assert d.counted(path, "// ordinary head")


def test_generated_head_is_excluded() -> None:
    assert not d.counted("drishti-console/core/x.py", "# Generated by tools/make.py: do not edit\n")


def test_report_parsed_and_lines_counted_once() -> None:
    groups = d.parse_report("java", XML.format(root=d.ROOT))
    assert [g.places[0][0] for g in groups] == ["a.java", "a.java"] and groups[0].weight == 3
    # a.java lines 1-3 (overlap counted once) + b.java 5-7 + c.java 1-2
    assert d.duplicated_lines(groups) == 8


def test_ratchet_compare_and_lowered() -> None:
    assert d.compare({"java": 10}, {"java": 10}) == []
    assert "11" in d.compare({"java": 11}, {"java": 10})[0]
    assert d.compare({"new": 1}, {}) != []
    assert d.lowered({"java": 5, "python": 9}, {"java": 6, "python": 7}) == {"java": 5, "python": 7}


def test_baseline_written_keeps_comments(tmp_path: Path) -> None:
    f = tmp_path / "b.txt"
    f.write_text("# why\njava 3\n", encoding="utf-8")
    d.write_baseline({"java": 2}, f)
    assert f.read_text(encoding="utf-8") == "# why\njava 2\n" and d.read_baseline(f) == {"java": 2}


def test_ratchet_on_this_tree() -> None:
    today, _ = d.measure()
    assert d.compare(today, d.read_baseline()) == [], "copy-paste grew: python3 tools/duplicates.py --report names the groups; fold the copy"
