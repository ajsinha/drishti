"""The Help addresses of the pack guides that were merged into feature guides (i7k), written into the console's help.yaml ``moved:``.

    python3 tools/docs/pack_guide_moves.py            write the rows between the markers of drishti-console/config/help.yaml
    python3 tools/docs/pack_guide_moves.py --check    fail when they differ

A pack's About drawer links ``/help/<pack>`` (the ``guide:`` of its about.yaml). The pack guides are gone; ``tools/docs/moved.yaml`` says
where each went, so the row ``<pack>: <the Help address of that home>`` is made from it, never listed by hand. A guide that was deleted
outright has no row (its about.yaml has no ``guide:``; tools/test_pack_guides.py holds that). The Help address of a document is its
``doc:`` entry in the console's help.yaml, else the slug made from its path (core/guides.py), else a module page (``module-<id>-<n>``).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
HELP = ROOT / "drishti-console" / "config" / "help.yaml"
BEGIN = "  # >>> pack guides (generated by tools/docs/pack_guide_moves.py; do not edit by hand)"
END = "  # <<< pack guides"


def _doc_slugs(data: dict) -> dict[str, str]:
    """docs-relative document path -> the slug the catalogue lists it under."""
    out: dict[str, str] = {}
    for sec in data.get("sections") or []:
        for grp in sec.get("groups") or []:
            for g in grp.get("guides") or []:
                for x in [g, *(g.get("children") or [])]:
                    if x.get("doc") and x.get("slug"):
                        out.setdefault(str(x["doc"]).replace("../", ""), str(x["slug"]))
    return out


def _module_page(to: str) -> str | None:
    """modules/<m>/docs/<file> -> ``module-<section>-<n>`` from that module's docs/help.yaml (the page's place in its section)."""
    m = re.match(r"modules/([^/]+)/docs/(.+)$", to)
    hf = ROOT / "modules" / m.group(1) / "docs" / "help.yaml" if m else None
    if not m or not hf.is_file():
        return None
    for s in (yaml.safe_load(hf.read_text(encoding="utf-8")) or {}).get("sections") or []:
        for i, p in enumerate(s.get("pages") or []):
            if str(p.get("file")) == m.group(2):
                module = m.group(1)
                return f"module-{module}-{i + 1}" if s["id"] == module else f"module-{module}-{s['id']}-{i + 1}"
    return None


def rows() -> dict[str, str]:
    data = yaml.safe_load(HELP.read_text(encoding="utf-8")) or {}
    docs = _doc_slugs(data)
    out: dict[str, str] = {}
    for r in (yaml.safe_load((ROOT / "tools" / "docs" / "moved.yaml").read_text(encoding="utf-8")) or {}).get("moved") or []:
        m = re.search(r"/guides/([a-z0-9-]+)\.md$", r["from"])
        if not m or not r.get("to") or not re.match(r"(modules|config/packs|examples/packs)/", r["from"]):
            continue
        to = r["to"]
        slug = docs.get(to.removeprefix("docs/")) if to.startswith("docs/") else None
        slug = slug or _module_page(to) or re.sub(r"[^a-z0-9]+", "-", str(Path(to).with_suffix("")).lower()).strip("-")
        out.setdefault(m.group(1), slug)
    return dict(sorted(out.items()))


def block() -> str:
    return "\n".join([BEGIN, *[f"  {k}: {v}" for k, v in rows().items()], END]) + "\n"


def current() -> str:
    text = HELP.read_text(encoding="utf-8")
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END) + 1
        return text[:a] + block() + text[b:]
    at = text.index("moved:\n") + len("moved:\n")
    return text[:at] + block() + text[at:]


def main(argv: list[str]) -> int:
    new = current()
    if "--check" in argv:
        if new != HELP.read_text(encoding="utf-8"):
            print("drishti-console/config/help.yaml: the pack-guide moved: rows are stale; run python3 tools/docs/pack_guide_moves.py")
            return 1
        return 0
    HELP.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
