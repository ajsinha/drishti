RULES = [(re.compile(p + r"\Z"), c, lane, t, tool) for p, c, lane, t, tool in R]


def tracked() -> list[str]:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "*.md"], check=True, capture_output=True, text=True).stdout
    return sorted(x for x in out.splitlines() if x)


def classify(path: str) -> tuple[str, str, str, str] | None:
    """(class, lane, target, tool) of a path by the first rule that matches, or None."""
    for rx, cls, lane, target, tool in RULES:
        if rx.match(path):
            return cls, lane, target.replace("{name}", path.rsplit("/", 1)[-1]), tool
    return None


def gone() -> list[str]:
    """Paths the manifest names that are no longer tracked: a document merged, moved or deleted by the consolidation keeps its row, so
    moved.yaml and the merge audit still know it."""
    if not CORPUS.exists():
        return []
    have = set(tracked())
    rows = yaml.safe_load(CORPUS.read_text(encoding="utf-8")).get("files") or []
    return [r["path"] for r in rows if r["path"] not in have and r["class"] in ("merge", "delete", "move", "rename")]


def build(paths: list[str] | None = None) -> tuple[list[tuple], list[str]]:
    rows, unmatched = [], []
    for p in paths if paths is not None else sorted(set(tracked()) | set(gone())):
        c = classify(p)
        (rows.append((p,) + c) if c else unmatched.append(p))
    return rows, unmatched


def corpus_text(rows: list[tuple]) -> str:
    out = [HEADER, "# class: record keep generate merge delete rename move connector note notdoc\n", "files:\n"]
    for p, cls, lane, target, tool in rows:
        extra = (f", tool: {tool!r}" if cls == "generate" and tool else "")
        out.append(f"  - {{path: {p!r}, class: {cls}, lane: {lane}{extra}}}\n")
    return "".join(out)


def moved_text(rows: list[tuple]) -> str:
    out = [HEADER, "# old path -> new home. `to` is empty for a deletion (git keeps the history); `how` says why.\n"
           "# Lanes append rows (anchor-level moves) below the marker line; the rows above it are rewritten by --write, never the ones below.\n", "moved:\n"]
    for p, cls, lane, target, tool in rows:
        if cls in ("merge", "rename", "move"):
            dest = target
            if cls == "merge" and not dest:
                dest = "config/about.yaml of the pack (intro:)"
            out.append(f"  - {{from: {p!r}, to: {dest!r}, how: {cls}}}\n")
        elif cls == "delete":
            why = tool or "deleted outright"
            out.append(f"  - {{from: {p!r}, to: '', how: delete, note: {why!r}}}\n")
    out.append(MARK + "\n")
    return "".join(out)


def lane_rows() -> str:
    """What follows the marker in the existing moved.yaml (the rows the lanes appended)."""
    if not MOVED.exists():
        return ""
    t = MOVED.read_text(encoding="utf-8")
    return t.split(MARK + "\n", 1)[1] if (MARK + "\n") in t else ""


def counts(rows: list[tuple]) -> dict[str, int]:
    n: dict[str, int] = {}
    for r in rows:
        n[r[1]] = n.get(r[1], 0) + 1
    return n


def main(argv: list[str]) -> int:
    rows, unmatched = build()
    if unmatched:
        print("[FAIL] no rule matches:", *unmatched, sep="\n  ")
        return 1
    if "--write" in argv:
        CORPUS.write_text(corpus_text(rows), encoding="utf-8", newline="\n")
        MOVED.write_text(moved_text(rows) + lane_rows(), encoding="utf-8", newline="\n")
    if "--check" in argv:
        bad = [CORPUS] if not CORPUS.exists() or CORPUS.read_text(encoding="utf-8") != corpus_text(rows) else []
        if not MOVED.exists() or not MOVED.read_text(encoding="utf-8").startswith(moved_text(rows)):
            bad.append(MOVED)
        if bad:
            print("[FAIL] out of date (run tools/docs/corpus.py --write):", *[str(b.relative_to(ROOT)) for b in bad], sep="\n  ")
            return 1
    print(f"{len(rows)} files:", ", ".join(f"{k} {v}" for k, v in sorted(counts(rows).items())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
