"""The connector reference (docs/reference/CONNECTORS.md), generated from the plugin READMEs' front matter.

    python3 tools/docs/connector_reference.py            write docs/reference/CONNECTORS.md
    python3 tools/docs/connector_reference.py --check    fail when the page differs from what would be written

Each plugin's README.md (plugins/<plugin>/README.md) is the one home of its connector: its YAML front matter (the README standard:
connector, category, summary, capabilities, settings, auth, licence, windows, doc) and its sections (what it reads, settings, data
structure, examples, troubleshooting). This page repeats nothing by hand: one table of every connector, then per connector its summary,
capabilities, setting keys, authentication, licence and Windows notes, each linking to the README for the rest. A README without front
matter, or front matter without a connector name, fails.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
PLUGINS = ROOT / "plugins"
PAGE = ROOT / "docs" / "reference" / "CONNECTORS.md"
FRONT = re.compile(r"^---\n(.*?)\n---\n", re.S | re.M)
HEADER = """<!--
  Project Drishti · Any data. Any domain. One grammar.
  Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved.
  PROPRIETARY AND CONFIDENTIAL. See the LICENSE file in the root of this repository.
-->
<!-- Generated by tools/docs/connector_reference.py from the plugin READMEs' front matter: edit the READMEs, not this page. -->
"""


def plugins(root: Path = PLUGINS) -> list[tuple[str, dict]]:
    """(plugin folder, front matter) of every plugin README, in connector order."""
    out = []
    for readme in sorted(root.glob("*/README.md")):
        m = FRONT.search(readme.read_text(encoding="utf-8"))
        if not m:
            raise SystemExit(f"connector_reference: {readme.relative_to(ROOT)} has no front matter")
        fm = yaml.safe_load(m.group(1)) or {}
        if not fm.get("connector"):
            raise SystemExit(f"connector_reference: {readme.relative_to(ROOT)} names no connector")
        out.append((readme.parent.name, fm))
    return sorted(out, key=lambda x: x[1]["connector"])


def _cell(s) -> str:
    return " ".join(str(s or "").split()).replace("|", "\\|")


def _anchor(name: str) -> str:
    return re.sub(r"[^\w\- ]", "", f"The {name} connector".lower()).replace(" ", "-")


def render(items: list[tuple[str, dict]]) -> str:
    out = [HEADER, "# Connector reference", "",
           f"Every connector the {len(items)} plugins provide, from the front matter of each plugin's README (the one home of a connector: what it "
           "reads, every setting with its meaning, the data structure, examples and troubleshooting). A connector is switched on by a file "
           "in `config/connectors/`; what such a file holds and how packs suggest one is in the [Data guide](../guides/DATA_GUIDE.md).", "",
           "| Connector | Plugin | What it does | Capabilities |", "|---|---|---|---|"]
    for folder, fm in items:
        out.append(f"| [`{fm['connector']}`](#{_anchor(fm['connector'])}) | [`{folder}`](../../plugins/{folder}/README.md) | "
                   f"{_cell(fm.get('summary'))} | {', '.join(fm.get('capabilities') or []) or '—'} |")
    out.append("")
    for folder, fm in items:
        out += [f"## The {fm['connector']} connector", "", _cell(fm.get("summary")), ""]
        rows = [["Plugin", f"[`plugins/{folder}`](../../plugins/{folder}/README.md) (its README: settings explained, data structure, examples)"],
                ["Capabilities", ", ".join(f"`{c}`" for c in fm.get("capabilities") or []) or "—"],
                ["Setting keys", ", ".join(f"`{s}`" for s in fm.get("settings") or []) or "—"],
                ["Authentication", _cell(fm.get("auth")) or "—"],
                ["Licence", _cell(fm.get("licence")) or "—"],
                ["Windows", _cell(fm.get("windows")) or "—"]]
        out += ["| | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in rows] + [""]
    out += ["---", "", "*Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved.",
            "Proprietary and confidential. Unauthorised copying, use or distribution is prohibited.*", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when docs/reference/CONNECTORS.md is stale")
    a = ap.parse_args(argv)
    text = render(plugins())
    if a.check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != text:
            print("connector reference is stale: run python3 tools/docs/connector_reference.py", file=sys.stderr)
            return 1
        print("docs/reference/CONNECTORS.md is current")
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
