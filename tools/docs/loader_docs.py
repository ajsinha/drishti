"""The loaders' READMEs as read-only Help pages ("Loading data daily").

    python3 tools/docs/loader_docs.py            write docs/loaders/<package>.md from tools/loaders/<package>/README.md
    python3 tools/docs/loader_docs.py --check    fail when a copy differs from what it would write

The README beside each loader stays the one source (an operator reads it next to the code). The copy is the same text with its
relative links moved so they resolve from docs/loaders/: another loader's README becomes its copy, a document under docs/ its
place from here. tools/loaders/README.md becomes docs/loaders/index.md. Every package with a README gets a copy, so a new loader
appears in Help once its README exists (and the Help group lists it: drishti-console/tests/test_help_loaders.py).
"""
from __future__ import annotations

import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "tools" / "loaders"
OUT = ROOT / "docs" / "loaders"
LINK = re.compile(r"\]\(([^)\s#]+)(#[^)\s]*)?\)")


def packages() -> list[str]:
    """The loader packages that have a README (tools/loaders/<package>/README.md), in name order."""
    return sorted(p.parent.name for p in SRC.glob("*/README.md"))


def copy_name(package: str | None) -> str:
    return "index.md" if package is None else f"{package}.md"


def _target(link: str, package: str | None) -> str:
    """One link of the README at tools/loaders[/<package>] moved to where docs/loaders/ reaches the same thing."""
    if re.match(r"[a-z][a-z0-9+.-]*:|/", link):
        return link
    here = "tools/loaders" + (f"/{package}" if package else "")
    dest = posixpath.normpath(posixpath.join(here, link))
    m = re.fullmatch(r"tools/loaders/(?:([^/]+)/)?README\.md", dest)
    if m:
        return copy_name(m.group(1))
    if dest.startswith("docs/"):
        return posixpath.relpath(dest, "docs/loaders")
    return posixpath.relpath(dest, "docs/loaders")


def render(package: str | None) -> str:
    path = SRC / (f"{package}/README.md" if package else "README.md")
    text = path.read_text(encoding="utf-8")
    text = LINK.sub(lambda m: "](" + _target(m.group(1), package) + (m.group(2) or "") + ")", text)
    rel = path.relative_to(ROOT).as_posix()
    note = f"<!-- generated by tools/docs/loader_docs.py from {rel}: edit that file, not this copy -->\n"
    end = text.find("-->")
    if text.startswith("<!--") and end > 0:                      # the licence header first, then the note
        return text[:end + 4].rstrip("\n") + "\n" + note + text[end + 3:].lstrip("\n").join(["\n", ""])
    return note + text


def wanted() -> dict[Path, str]:
    out = {OUT / copy_name(None): render(None)}
    for p in packages():
        out[OUT / copy_name(p)] = render(p)
    return out


def main(argv: list[str]) -> int:
    want = wanted()
    if "--check" in argv:
        stale = [str(f.relative_to(ROOT)) for f, t in want.items() if not f.is_file() or f.read_text(encoding="utf-8") != t]
        stale += [str(f.relative_to(ROOT)) + " (no loader README)" for f in OUT.glob("*.md") if f not in want]
        if stale:
            print("the loader Help pages are out of date; run python3 tools/docs/loader_docs.py:\n  " + "\n  ".join(stale))
            return 1
        print(f"{len(want)} loader Help pages up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for f, t in want.items():
        f.write_text(t, encoding="utf-8")
    for f in OUT.glob("*.md"):
        if f not in want:
            f.unlink()
    print(f"wrote {len(want)} loader Help pages in docs/loaders")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
