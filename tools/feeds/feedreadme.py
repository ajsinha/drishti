"""Each data feed's README, generated beside its feed file (``config/feeds/<feed>.md``) from the feed file and the contracts of the
kinds it loads (docs/guides/EXTERNAL_DATA.md): the source, the licence and its use, the lake and the schedule, how to run it, and per
dataset its data contract (the table, the key, every field with its type and meaning) with a JSON example of one row built from the
contract's examples. Nothing is written by hand: edit the feed file or the pack's contract and run this again.

    python3 tools/feeds/feedreadme.py            write config/feeds/<feed>.md for every feed file
    python3 tools/feeds/feedreadme.py --check    exit 1 naming each README that is missing or differs (a test runs it)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import feedbase as FB  # noqa: E402

ROOT = FB.ROOT
HEADER = """<!--
  Project Drishti · Any data. Any domain. One grammar.
  Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved.
  PROPRIETARY AND CONFIDENTIAL. See the LICENSE file in the root of this repository.
-->
<!-- Generated by tools/feeds/feedreadme.py from config/feeds/{feed}.yaml and the packs' contracts. Edit those, not this file. -->
"""


def _where(pack: str) -> str:
    """A pack's folder as the repository names it: config/packs/<domain>/<pack>."""
    d = FB.K.pack_dir(pack)
    return d.relative_to(ROOT).as_posix() if d.is_relative_to(ROOT) else d.as_posix()


def contract(pack: str, kind: str) -> dict:
    import yaml
    f = FB.K.pack_dir(pack) / "contracts" / f"{kind}.contract.yaml"
    return (yaml.safe_load(f.read_text(encoding="utf-8")) or {}) if f.is_file() else {}


def example(c: dict) -> dict:
    """One row from the contract's top-level fields' examples (a field without an example is left out)."""
    out = {}
    for f in c.get("fields") or []:
        name = str(f.get("name") or "")
        if not name or "." in name or "[" in name or "example" not in f:
            continue
        out[name] = f["example"]
    return out


def _cell(text) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def render(spec: FB.FeedSpec) -> str:
    lic = spec.licence
    use = "**internal only**" if lic.internal_only else {"allowed": "redistributable", "attribution": "redistributable with attribution"}.get(
        lic.redistribution, lic.redistribution)
    out = [HEADER.format(feed=spec.name), f"# The {spec.name} feed", "", spec.title + ".", ""]
    if spec.description:
        out += [" ".join(spec.description.split()), ""]
    out += ["| | |", "|---|---|",
            f"| Source | {_cell(spec.provider)} ({spec.url}) |",
            f"| Licence | [{_cell(lic.name)}]({lic.url}): {use} |"]
    if lic.attribution:
        out.append(f"| Attribution | {_cell(lic.attribution)} |")
    if lic.notes:
        out.append(f"| Notes | {_cell(lic.notes)} |")
    out += [f"| Lake | `{spec.lake}` (load route `{spec.load}`) |",
            f"| Schedule | {spec.schedule_days} at {spec.schedule_at} (local time){'' if spec.enabled else '; **off** as shipped (`enabled: false`)'} |",
            f"| Pull | `{spec.impl}` (tools/feeds/sources/{spec.impl.rpartition('.')[0]}.py); {spec.pause:g} s between requests, "
            f"{spec.retries} retries |"]
    if spec.keys:
        out.append("| Keys | " + ", ".join(f"`{k}` from `${{{v}}}`" + (" (optional)" if k in spec.optional_keys else "")
                                         for k, v in spec.keys.items()) + " |")
    out += ["", "## Run it", "", "```bash",
            f"python3 tools/drishti.py feed run {spec.name} --dry-run      # what it would fetch and load; changes nothing",
            f"python3 tools/drishti.py feed run {spec.name}                # pull today, write data/datafeeds/{spec.name}/<date>/, load into {spec.lake}",
            f"python3 tools/drishti.py feed status {spec.name}             # its last runs"]
    if spec.snapshot:
        out.append(f"python3 tools/drishti.py feed run {spec.name} --snapshot     # refresh the committed demo snapshot instead"
                   + (" (with --internal-ok)" if lic.internal_only else ""))
    out += ["```", "", "Daily: `python3 tools/drishti.py feed schedule --cron` (or `--systemd`, `--windows`). The guide: "
            "[EXTERNAL_DATA.md](../../docs/guides/EXTERNAL_DATA.md).", "", "## Data contract", ""]
    for ds in spec.datasets.values():
        c = contract(ds.pack, ds.kind)
        out += [f"### {ds.name}", "",
                f"Pack `{ds.pack}`, kind `{ds.kind}`" + (f" ({_cell(c.get('title'))})" if c.get("title") else "") + f", table `{ds.table}`"
                + (f", key `{ds.key}`" if ds.key else "") + "; files `data/datafeeds/" + spec.name + f"/<date>/{ds.table}.<date>.jsonl.gz`, "
                + ("each row under the run's business date." if ds.dated == "run" else "each row under the business date the source gives it."), ""]
        if ds.description:
            out += [_cell(ds.description)[:1].upper() + _cell(ds.description)[1:] + ".", ""]
        fields = [f for f in c.get("fields") or [] if f.get("name")]
        if not fields:
            out += [f"No contract yet: `{_where(ds.pack)}/contracts/{ds.kind}.contract.yaml` (`drishti.py contract bootstrap {ds.kind}`).", ""]
            continue
        out += ["| Field | Type | Presence | Meaning |", "|---|---|---|---|"]
        out += [f"| `{f['name']}` | {_cell(f.get('type'))} | {_cell(f.get('presence'))} | {_cell(f.get('description'))} |" for f in fields]
        ex = example(c)
        if ex:
            out += ["", "One row (JSON Lines: one object a line; the values are the contract's examples):", "", "```json",
                    json.dumps(ex, ensure_ascii=False), "```"]
        out += ["", f"The contract: `{_where(ds.pack)}/contracts/{ds.kind}.contract.yaml` "
                f"([{ds.pack}](../../docs/contracts/packs/{ds.pack}.md)).", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="feedreadme", description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail naming each README that is missing or differs")
    ap.add_argument("--config", help="the feed files' folder (default config/feeds)")
    a = ap.parse_args(argv)
    folder = Path(a.config) if a.config else FB.CONFIG
    bad = []
    specs = FB.all_specs(folder)
    for spec in specs:
        f = folder / f"{spec.name}.md"
        text = render(spec)
        if a.check:
            if not f.is_file() or f.read_text(encoding="utf-8") != text:
                bad.append(str(f))
        else:
            f.write_text(text, encoding="utf-8")
    stale = sorted(p for p in folder.glob("*.md") if p.stem not in {s.name for s in specs})
    if a.check:
        bad += [f"{p} (no feed file {p.stem}.yaml)" for p in stale]
        if bad:
            print("feed READMEs out of date; run python3 tools/feeds/feedreadme.py:\n  " + "\n  ".join(bad))
            return 1
        print(f"{len(specs)} feed READMEs are current")
        return 0
    for p in stale:
        p.unlink()
    print(f"wrote {len(specs)} feed READMEs in {folder}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
