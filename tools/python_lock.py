"""Writes a lock file for a compute pool's locked environment (docs/guides/NOTEBOOK_GUIDE.md section 4): every package pinned to one
version with the sha256 of each of its distribution files, so ``pip install --require-hashes --no-deps`` installs exactly these on Linux
and on Windows. Nothing is resolved: the list given is the whole environment, transitive packages included.

    python tools/python_lock.py config/compute/locks/python.in --out config/compute/locks/python.lock

The input is one ``name==version`` per line (``#`` comments, kept as the lock's header). The hashes are read from the Python package
index's JSON API (``--index``, default https://pypi.org/pypi); run it on a machine that may reach it, and commit the lock.
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.request


def read(path: str) -> tuple[list[str], list[tuple[str, str]]]:
    """The input's leading comment lines and its pins."""
    head, out = [], []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            if raw.startswith("#") and not out:
                head.append(raw.rstrip("\n"))
                continue
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            name, sep, version = line.partition("==")
            if not sep or not name.strip() or not version.strip():
                raise SystemExit(f"{path}: '{line}' is not name==version")
            out.append((name.strip(), version.strip()))
    return head, out


def hashes(index: str, name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"{index.rstrip('/')}/{name}/{version}/json", timeout=60) as r:   # noqa: S310 - the index named by the caller
        data = json.load(r)
    found = sorted({u["digests"]["sha256"] for u in data.get("urls") or [] if u.get("digests", {}).get("sha256")})
    if not found:
        raise SystemExit(f"{name}=={version}: the index lists no files")
    return found


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="python_lock.py", description=__doc__.split("\n\n")[0])
    p.add_argument("pins", help="a file of name==version lines")
    p.add_argument("--out", required=True, help="the lock file to write")
    p.add_argument("--index", default="https://pypi.org/pypi", help="the index's JSON API")
    a = p.parse_args(argv)
    head, pins = read(a.pins)
    lines = head + ["#", "# Generated by tools/python_lock.py from " + a.pins.replace("\\", "/").rsplit("/", 1)[-1]
                    + ": each package and the sha256 of each of its files. Never edit this file: edit the .in file and run the tool again."]
    for name, version in pins:
        hs = hashes(a.index, name, version)
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
