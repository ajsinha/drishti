"""The copy-paste detector and its ratchet. PMD's CPD (tokens, not text; comments and whitespace do not count) over Java, JavaScript
and Python, at one minimum size for all three: 100 tokens, about 10 to 15 lines, long enough that a run of imports or a small
boiler-plate block is not a finding and short enough that a copied method is.

    python3 tools/duplicates.py                 # the ratchet: fails if any language has more duplicated lines than the baseline
    python3 tools/duplicates.py --report [N]    # the N biggest duplicate groups of all languages (default 15), then the totals
    python3 tools/duplicates.py --write         # lowers the baseline to today's figures; it never raises one

Duplicated lines of a language = every line of a counted file that lies in any copy, each line once. The baseline
(tools/cpd/baseline.txt) has one line per language and is lowered, never raised, in the change that removes the duplication.

Counted: authored product and tool code. Not counted: tests, generated files, static/vendor, the frozen render/1.2.0, web/embed, the
self-contained examples and docs, drishti-it, drishti-testkit, drishti-benchmarks. The tool resolves PMD through tools/cpd/pom.xml, which
is outside the root build (the first run downloads it; nothing that ships depends on it).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

from javacmd import java_cmd

ROOT = Path(__file__).resolve().parent.parent
POM = ROOT / "tools" / "cpd" / "pom.xml"
BASELINE = ROOT / "tools" / "cpd" / "baseline.txt"
CLASSPATH = ROOT / "tools" / "cpd" / "target" / "classpath.txt"
MIN_TOKENS = 100
LANGUAGES = {"java": (".java",), "ecmascript": (".js", ".mjs"), "python": (".py",)}
LABEL = {"java": "java", "ecmascript": "javascript", "python": "python"}
EXCLUDED = re.compile(
    r"(^|/)(tests?|target|node_modules|__pycache__|vendor|generated|docs|examples)/"
    r"|/src/test/|^(testing|external_lib|data)/"
    r"|/static/render/1\.2\.0/|(^|/)web/embed/"
    r"|(^|/)(test_[^/]*|[^/]*_test|conftest)\.py$|\.min\.js$|\.test\.m?js$|(^|/)drishti_harness\.js$"
)
GENERATED = re.compile(r"(?i)\b(do not edit|auto-?generated|generated by|@generated)\b")


@dataclass
class Group:
    """One set of identical token runs: its language, length and the places it occurs."""

    language: str
    tokens: int
    lines: int
    places: list[tuple[str, int, int]]

    @property
    def weight(self) -> int:
        """Lines that folding the group would remove: every copy but one."""
        return self.lines * (len(self.places) - 1)


def counted(path: str, head: str) -> bool:
    """Whether the detector reads this repository-relative file, given its first lines."""
    return not EXCLUDED.search(path) and not GENERATED.search(head)


def source_files() -> dict[str, list[str]]:
    """The counted files per language, sorted: tracked and new ones of the working tree."""
    out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                         cwd=ROOT, check=True, capture_output=True, text=True).stdout.split("\n")
    files: dict[str, list[str]] = {lang: [] for lang in LANGUAGES}
    for rel in sorted(p for p in out if p):
        lang = next((la for la, exts in LANGUAGES.items() if rel.endswith(exts)), None)
        if lang is None or not (ROOT / rel).is_file():
            continue
        with open(ROOT / rel, encoding="utf-8", errors="replace") as fh:
            head = "".join(fh.readline() for _ in range(25))
        if counted(rel, head):
            files[lang].append(rel)
    return files


def classpath() -> str:
    """PMD's class path, resolved once by Maven and cached under the git-ignored target folder."""
    if not CLASSPATH.is_file() or CLASSPATH.stat().st_mtime < POM.stat().st_mtime:
        CLASSPATH.parent.mkdir(exist_ok=True)
        subprocess.run(["mvn", "-q", "-f", str(POM), "dependency:build-classpath", f"-Dmdep.outputFile={CLASSPATH}"],
                       check=True, capture_output=True, text=True)
    return CLASSPATH.read_text(encoding="utf-8").strip()


def run_cpd(language: str, files: list[str]) -> list[Group]:
    """Runs CPD over the files and returns its groups."""
    with tempfile.TemporaryDirectory() as tmp:
        lst = Path(tmp) / "files.txt"
        lst.write_text("\n".join(str(ROOT / f) for f in files), encoding="utf-8")
        cmd = java_cmd("java", ["-Xmx3g", "-cp", classpath(), "net.sourceforge.pmd.cli.PmdCli", "cpd", "--language", language,
               "--minimum-tokens", str(MIN_TOKENS), "--file-list", str(lst), "--format", "xml", "--no-fail-on-violation",
               "--no-fail-on-error", "--encoding", "UTF-8"], tmp=tmp)
        if language == "java":
            cmd.append("--ignore-annotations")
        done = subprocess.run(cmd, capture_output=True, text=True)
    if done.returncode != 0 or "<pmd-cpd" not in done.stdout:
        raise RuntimeError(f"CPD failed for {language} (exit {done.returncode}): {done.stderr[-2000:]}")
    return parse_report(language, done.stdout)


def parse_report(language: str, xml: str) -> list[Group]:
    """The groups of one CPD XML report, paths made repository-relative."""
    ns = {"c": "https://pmd-code.org/schema/cpd-report"}
    prefix = str(ROOT) + "/"
    groups = []
    for dup in ET.fromstring(xml).findall("c:duplication", ns):
        places = [(f.get("path", "").removeprefix(prefix), int(f.get("line", 0)), int(f.get("endline", 0)))
                  for f in dup.findall("c:file", ns)]
        groups.append(Group(language, int(dup.get("tokens", 0)), int(dup.get("lines", 0)), places))
    return groups


def duplicated_lines(groups: list[Group]) -> int:
    """Lines lying in any copy, each line of each file once."""
    seen: set[tuple[str, int]] = set()
    for g in groups:
        for path, first, last in g.places:
            seen.update((path, n) for n in range(first, last + 1))
    return len(seen)


def measure() -> tuple[dict[str, int], list[Group]]:
    """Today's duplicated lines per language label, and all groups."""
    groups: list[Group] = []
    totals: dict[str, int] = {}
    for lang, files in source_files().items():
        found = run_cpd(lang, files)
        totals[LABEL[lang]] = duplicated_lines(found)
        groups += found
    return totals, groups


def read_baseline(path: Path = BASELINE) -> dict[str, int]:
    """The committed baseline: ``language lines`` per line; # starts a comment."""
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            name, value = line.split()
            out[name] = int(value)
    return out


def compare(today: dict[str, int], baseline: dict[str, int]) -> list[str]:
    """The ratchet: one message per language above its baseline (or missing from it)."""
    return [f"{k}: {v} duplicated lines, the baseline allows {baseline.get(k, 0)}" for k, v in today.items() if v > baseline.get(k, 0)]


def lowered(today: dict[str, int], baseline: dict[str, int]) -> dict[str, int]:
    """The new baseline: each language at today's figure or the old one, whichever is lower."""
    return {k: min(v, today.get(k, v)) for k, v in baseline.items()}


def write_baseline(values: dict[str, int], path: Path = BASELINE) -> None:
    """Rewrites the figures, keeping the comments."""
    comments = [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.startswith("#")] if path.exists() else []
    path.write_text("\n".join(comments + [f"{k} {v}" for k, v in values.items()]) + "\n", encoding="utf-8")


def report(groups: list[Group], top: int) -> None:
    """Prints the biggest groups, by the lines that folding each would remove."""
    for i, g in enumerate(sorted(groups, key=lambda x: (-x.weight, x.places))[:top], 1):
        print(f"{i:3}. {LABEL[g.language]}  {g.lines} lines x {len(g.places)} copies ({g.tokens} tokens)")
        for path, first, last in g.places:
            print(f"       {path}:{first}-{last}")


def main() -> int:
    """Command line: see the module's docstring."""
    ap = argparse.ArgumentParser(description="copy-paste detector and ratchet")
    ap.add_argument("--report", nargs="?", type=int, const=15, default=None, metavar="N")
    ap.add_argument("--write", action="store_true", help="lower the baseline to today's figures")
    a = ap.parse_args()
    today, groups = measure()
    if a.report is not None:
        report(groups, a.report)
    baseline = read_baseline()
    print("duplicated lines:", ", ".join(f"{k} {v} (baseline {baseline.get(k, 0)})" for k, v in today.items()))
    if a.write:
        write_baseline(lowered(today, baseline))
        return 0
    bad = compare(today, baseline)
    for msg in bad:
        print(f"duplicates: {msg}: fold the copy (tools/duplicates.py --report names them)", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
