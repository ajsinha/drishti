def build_parser(add_help: bool = True) -> argparse.ArgumentParser:
    p = PFJ.build_parser(add_help)
    p.description = __doc__.split("\n\n")[0]
    p.epilog = __doc__.split("\n\n", 1)[1]
    g = p.add_argument_group("module, binding and deployment")
    g.add_argument("--allow-shared-kinds", action="store_true", help="keep kinds another product module provides (only for servers without it)")
    g.add_argument("--dry-run", action="store_true", help="read every record and print the plan (kinds, combinations -> Sutras, id check, dates, binding); write nothing")
    g.add_argument("--connector", help="bind the kinds to this existing connector (config/connectors/<name>.yaml) instead of a new file connector")
    g.add_argument("--files-root", help="the file connector's root (default: the input folder's parent when it is laid out <domain>/<date>/<kind>.jsonl, "
                                        "else the data folder's files store)")
    g.add_argument("--load", action="store_true", help="write the documents into the files store (<files root>/<name>/<date>/<kind>.jsonl) for the file connector")
    g.add_argument("--site", type=pathlib.Path, help="the site's config folder holding bindings.yaml and connectors/ (default: config)")
    g.add_argument("--no-binding", action="store_true", help="write no binding and no connector file (the site binds the kinds later, Admin -> Data bindings)")
    g.add_argument("--dist", type=pathlib.Path, help="where the .dmod is written (default dist/)")
    g.add_argument("--publisher", default="local", help="publisher id in module.yaml (default local)")
    g.add_argument("--deploy", action="store_true", help="install the .dmod: into --modules-dir (one node), or with --server upload and plan it (a cluster)")
    g.add_argument("--modules-dir", type=pathlib.Path, help="the server's modules folder (drishti.modules.path; default $DRISHTI_MODULES_PATH, else <data folder>/modules)")
    g.add_argument("--reason", help="--deploy on a cluster: why (kept in the audit log)")
    g.add_argument("--tool", help="the module tool jar (default kernel/drishti-module-runtime/target/drishti-module-tool.jar)")
    g.add_argument("--cycles", type=int, default=2, help="load/unload cycles of check C15 (default 2)")
    g.add_argument("--workers", type=int, default=max(1, min(8, (os.cpu_count() or 2) // 3)),
                   help="processes reading the files, a file each (default: a third of the cores, at most 8); every record is read either way")
    p.set_defaults(infer=True)
    return p


def claimed_kinds() -> dict[str, str]:
    """kind -> the product module that provides it (modules/*/{dmod,src/dmod}/module.yaml `provides: kinds:`)."""
    import yaml
    out: dict[str, str] = {}
    for f in sorted(ROOT.glob("modules/*/dmod/module.yaml")) + sorted(ROOT.glob("modules/*/src/dmod/module.yaml")):
        try:
            m = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        except (OSError, yaml.YAMLError):
            continue
        for kinds in ((m.get("provides") or {}).get("kinds") or {}).values():
            for k in kinds or []:
                out.setdefault(str(k), str(m.get("id") or f.parts[-3]))
    return out


def laid_out(inputs) -> tuple[pathlib.Path, str] | None:
    """(root, domain) when the one input folder is already the file connector's layout: <domain>/<yyyy-MM-dd>/<kind>.jsonl."""
    if len(inputs) != 1 or not pathlib.Path(inputs[0]).is_dir():
        return None
    d = pathlib.Path(inputs[0]).resolve()
    days = [x for x in d.iterdir() if x.is_dir() and DATE_DIR.match(x.name)]
    if days and all(f.suffix == ".jsonl" for x in days for f in x.iterdir() if f.is_file()):
        return d.parent, d.name
    return None


def binding_plan(a, an) -> dict:
    kinds = sorted(an.prof.kinds)
    if a.no_binding:
        return {"kinds": kinds, "connector": None}
    if a.connector:
        return {"kinds": kinds, "connector": a.connector, "file": None}
    lo = laid_out(a.inputs) if not a.files_root else None
    root, domain = (str(lo[0]), lo[1]) if lo else (a.files_root or FILES_ROOT, a.name)
    if "${" not in root:                                # a ${...} placeholder is the server's to resolve (it is not a path)
        root = str(pathlib.Path(root).resolve())      # the server resolves a relative root against its own working folder
    return {"kinds": kinds, "connector": f"{a.name}-files", "file": f"connectors/{a.name}-files.yaml", "root": root, "domain": domain,
            "in-place": bool(lo)}


def say_binding(b: dict, a, say=print) -> None:
    if not b["connector"]:
        say("\nbinding: none (--no-binding); bind the kinds in Admin -> Data bindings")
        return
    say(f"\nbinding (config/bindings.yaml): {', '.join(b['kinds'])} -> read: [{b['connector']}]")
    if b.get("file"):
        say(f"  connector {b['connector']} (config/{b['file']}): plugin file, root {b['root']}, domain {b['domain']}"
            + (" (the input folder, read in place)" if b["in-place"] else ("" if a.load else "; fill it with --load (or drishti.py data ingest)")))


def write_yaml(path: pathlib.Path, data, head: str = HEADER) -> None:
    import yaml
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(head + yaml.safe_dump(data, sort_keys=False, width=120, allow_unicode=True), encoding="utf-8")


def write_module(a, an, mod: pathlib.Path, pack: pathlib.Path) -> dict:
    """The module around the pack: module.yaml, data/needs.yaml, console/plugin.yaml and docs/."""
    import yaml
    m = yaml.safe_load((pack / "pack.yaml").read_text(encoding="utf-8"))
    mn = m["mnemonics"]
    title = a.title or a.name
    kinds = sorted(an.prof.kinds)
    manifest = {"format": 1, "id": a.name, "version": a.version, "title": title,
                "about": a.description or f"{title}: {', '.join(kinds)} from JSON Lines", "domain": a.pack_domain if a.pack_domain != "core" else a.name,
                "publisher": {"id": a.publisher, "name": a.publisher}, "licence": {"feature": a.name},
                "kernel": ">=0.2 <1.0", "rachana": ">=1.0", "contracts": ">=1.0", "plugin-api": ">=2.0", "elements": ">=1.4 <2",
                "provides": {"kinds": {a.name: kinds}}, "packs": {"folder": "packs", "list": [a.name]}, "data": {"needs": "data/needs.yaml"},
                "console": {"plugin": "console/plugin.yaml", "menus": []}, "functions": sorted(mn),
                "docs": {"readme": "docs/README.md", "help": "docs/help.yaml", "domains": [], "guides": ["docs/guide.md"], "tutorials": ["docs/tutorial.md"]},
                "resources": {"memory-mb": 64}}
    write_yaml(mod / "module.yaml", manifest)
    write_yaml(mod / "data" / "needs.yaml", {"needs": [{"kind": k, "contract": ">=1.0 <2", "required": True} for k in kinds]})
    routes = [{"id": code.lower(), "path": f"/{a.name}/{v['kind']}/{{id}}", "sutra": f"{a.name}/{v['kind']}", "function": code, "title": v["label"]}
              for code, v in sorted(mn.items())]
    write_yaml(mod / "console" / "plugin.yaml", {"format": 2, "module": a.name, "title": title, "routes": routes})
    p = an.prof
    rows = "\n".join(f"| `{code}` | `{v['kind']}` | {p.kinds[v['kind']].rows:,} | {sum(1 for g in an.groups if g.kind == v['kind'])} |" for code, v in sorted(mn.items()))
    docs = mod / "docs"
    docs.mkdir(parents=True, exist_ok=True)
    (docs / "README.md").write_text(f"""---
# Project Drishti · Any data. Any domain. One grammar.
# Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved.
module: {a.name}
title: {json.dumps(title)}
domain: {manifest['domain']}
summary: {json.dumps(manifest['about'])}
packs: [{a.name}]
generated-by: drishti.py pack new
---

# {title}

A content module (no code) generated by `drishti.py pack new` from {p.rows:,} rows in {p.files} file(s), every row read. Its pack
`packs/{a.name}` holds the kinds, their contracts, one Sutra per kind or per discriminator combination, samples and tests.

| Function | Kind | Rows read | Sutras |
|---|---|---|---|
{rows}

| Part | Where in the package |
|---|---|
| The pack: kinds, contracts, Sutras, samples, tests | `packs/{a.name}` |
| Pages | `console/plugin.yaml`: one Sutra page per function under `/m/{a.name}/` |
| Data it needs | `data/needs.yaml`: every kind, bound by the site (`config/bindings.yaml`, Admin -> Data bindings) |
| Help | `docs/help.yaml`: the [guide](guide.md) and the [tutorial](tutorial.md) |

The module carries no connector: the site binds each kind to its own connectors.
""", encoding="utf-8")
    (docs / "guide.md").write_text(MD_HEADER + f"""# {title}: guide

Each kind's page is drawn by the Sutra whose `where` matches the document's discriminator values (`{', '.join(sorted({f for v in an.match.values() for f in v})) or 'none'}`);
the fields, their types and presence are in `packs/{a.name}/contracts/`. Edit a Sutra in Build -> Sutra workbench, then run
`drishti.py pack check packs/{a.name}` and pack the module again (`drishti.py module pack`).
""", encoding="utf-8")
    first = sorted(mn)[0]
    (docs / "tutorial.md").write_text(MD_HEADER + f"""# {title}: tutorial

1. Open the console and type `{first} <GO>` with an id from the samples (`packs/{a.name}/samples/catalog.jsonl`).
2. The page is the Sutra of that document's combination; Explain shows which Sutra matched and why.
3. Change the Sutra, then `drishti.py pack check packs/{a.name}`; pack and deploy the module again (`drishti.py pack new ... --deploy`
   regenerates; `drishti.py pack regenerate` keeps your edits).
""", encoding="utf-8")
    write_yaml(docs / "help.yaml", {"sections": [{"id": a.name, "title": title, "pages": [{"title": f"{title}: guide", "file": "guide.md"},
                                                                                       {"title": f"{title}: tutorial", "file": "tutorial.md"}]}]})
    return manifest


def write_binding(a, b: dict, an, site: pathlib.Path, say=print) -> None:
    """One read binding per kind in the site's bindings.yaml (kept whole, the previous file as bindings.yaml.bak), and the file connector."""
    import yaml
    if not b["connector"]:
        return
    if b.get("file"):
        layout = {k: {"columns": list(dict.fromkeys(an.match[k] + PFJ.scalar_columns(an.prof.kinds[k].head, an.keys[k])))} for k in b["kinds"]}
        settings = {"root": b["root"], "domain": b["domain"], "layout": layout}
        keys = {an.keys[k] for k in b["kinds"]}
        if b["in-place"] and len(keys) == 1:
            settings["id-field"] = keys.pop()
        write_yaml(site / b["file"], {"plugin": "file", "kinds": b["kinds"], "description": f"{a.name}: JSON Lines files (drishti.py pack new)",
                                      "settings": settings})
        say(f"wrote {site / b['file']}")
    f = site / "bindings.yaml"
    doc = (yaml.safe_load(f.read_text(encoding="utf-8")) if f.is_file() else None) or {"format": 1}
    if f.is_file():
        shutil.copyfile(f, f.with_name("bindings.yaml.bak"))
    binds = doc.setdefault("bindings", {}) or {}
    doc["bindings"] = binds
    for k in b["kinds"]:
        binds[k] = {"read": [b["connector"]]}
    tmp = f.with_name("bindings.yaml.tmp")
    write_yaml(tmp, doc, "# The site's data bindings (docs/guides/DATA_LAKE_GUIDE.md, \"Data bindings\"). Changed from Admin -> Data bindings or this file.\n")
    os.replace(tmp, f)
    say(f"bound {len(b['kinds'])} kind(s) to {b['connector']} in {f}")


def load_files(a, an, b: dict, cli, say=print) -> int:
    """--load: the documents into the files store the connector reads (drishti.py data ingest --store files)."""
    root = b["root"]
    if "${" in root:
        root = str(pathlib.Path(os.environ.get("DRISHTI_FILES_ROOT") or pathlib.Path(os.environ.get("DRISHTI_DATA_DIR") or ROOT / "data") / "files"))
    args = ["data", "ingest", "--from", *map(str, a.inputs), "--domain", b["domain"], "--store", "files", "--root", root,
            "--key", ",".join(f"{k}={v}" for k, v in an.keys.items())]
    if an.dates:
        args += ["--date", ",".join(f"{k}={v}" for k, v in an.dates.items())]
    if getattr(a, "kind", None):
        args += ["--kind", a.kind]
    if getattr(a, "recursive", False):
        args.append("--recursive")
    if getattr(a, "kind_prefix", None):
        args += ["--kind-prefix", a.kind_prefix]
    sys.stdout.flush()
    say("\n== " + " ".join(["drishti.py", *args]))
    return cli.main(args)


def module_tool(cli, a, *args: str) -> int:
    sys.stdout.flush()
    java = cli.find_java(getattr(a, "java", None))
    with cli.cli_tmp() as tmp:
        return subprocess.run(cli.java_cmd(java, ["-jar", cli.find_module_tool(a.tool), *args], tmp=tmp), cwd=ROOT).returncode


def modules_dir(a) -> pathlib.Path:
    if a.modules_dir:
        return a.modules_dir.resolve()
    if os.environ.get("DRISHTI_MODULES_PATH"):
        return pathlib.Path(os.environ["DRISHTI_MODULES_PATH"]).resolve()
    return (pathlib.Path(os.environ.get("DRISHTI_DATA_DIR") or ROOT / "data") / "modules").resolve()


def run(a, cli, say=print) -> int:
    t0 = time.monotonic()
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", a.name):
        raise cli.CliError("--name is lower-case letters, digits and '-'", 2)
    if a.deploy and getattr(a, "server", None) and not a.reason:
        raise cli.CliError("--deploy on a cluster (--server) needs --reason", 2)
    mod = (a.out or ROOT / "modules" / a.name).resolve()
    if not a.dry_run and mod.exists() and any(mod.iterdir()) and not a.force:
        raise cli.CliError(f"{mod} exists; pass --force to replace it", 2)
    an = PFJ.analyse(a, say)
    PFJ.print_plan(an, say)
    clash = {k: m for k, m in claimed_kinds().items() if k in an.prof.kinds}
    if clash:
        say("\nkinds other modules provide (a server with that module refuses this one, \"kind ... is claimed\"): "
            + ", ".join(f"{k} ({m})" for k, m in sorted(clash.items())) + f"; rename them with --kind-prefix {a.name}-")
    b = binding_plan(a, an)
    say_binding(b, a, say)
    say(f"\nmodule {a.name} {a.version}: {mod} -> {(a.dist or ROOT / 'dist').resolve() / f'{a.name}-{a.version}.dmod'}")
    if a.dry_run:
        say(f"dry run: nothing written ({time.monotonic() - t0:.1f} s)")
        return 0
    if clash and not a.allow_shared_kinds:
        raise cli.CliError(f"kinds {', '.join(sorted(clash))} are provided by other modules: give --kind-prefix {a.name}- (or --allow-shared-kinds for "
                           "a server without those modules)", 2)
    if not an.groups:
        raise cli.CliError("nothing to generate: no combination has --min-docs documents", 1)
    a.jar, a.java = cli.find_jar(a.jar), cli.find_java(a.java)
    if mod.exists():
        shutil.rmtree(mod)
    pack = mod / "packs" / a.name
    a.out, a.force = pack, True
    rc = PFJ.run(a, say, an)
    write_module(a, an, mod, pack)
    if b["connector"]:
        write_binding(a, b, an, (a.site or ROOT / "config").resolve(), say)
        if a.load and b.get("file") and not b["in-place"] and load_files(a, an, b, cli, say):
            return 1
    dist = (a.dist or ROOT / "dist").resolve()
    say("\n== module pack")
    if module_tool(cli, a, "pack", str(mod), "--out", str(dist)):
        return 1
    dmod = dist / f"{a.name}-{a.version}.dmod"
    say("\n== module check")
    chk = module_tool(cli, a, "check", str(dmod), "--cycles", str(a.cycles))
    say(f"\n{'checked' if not chk else 'CHECKS FAILED'}: {dmod} ({time.monotonic() - t0:.1f} s in all; sutra lint/test {'passed' if not rc else 'FAILED'})")
    if rc or chk:
        return 1
    if a.deploy:
        if getattr(a, "server", None) and not a.modules_dir:
            return cli.main(["module", "deploy", str(dmod), "--reason", a.reason or "pack new", *(["--server", a.server] if a.server else [])])
        target = modules_dir(a)
        target.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(dmod, target / dmod.name)
        say(f"deployed: {target / dmod.name} (auto-deploy checks, installs and loads it; Admin -> Modules shows it)")
    return 0
