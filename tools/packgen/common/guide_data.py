"""The two sections every pack guide ends with (the product owner's request of 2026-10-26: data contract, data retrieval and details
for all packs), generated so they cannot drift:

  ## Data contracts    every kind of the pack from config/packs/<pack>/contracts/*.contract.yaml: class, key, grain, storage, and every
                       column (type, key, presence, unit, example or values, link, meaning), nested lists too
  ## Data retrieval    per kind, where its data comes from: an external source (licence, internal-only flag, the refresh script with an
                       example), a generator of synthetic data, or a Drishti engine; how it reaches the lake, how to check it, offline

Each pack generator appends ``sections(pack_dir)`` to the guide it writes (tools/packgen/banking/make_docs.py, tools/packgen/common/
packbuild.py for world-economy, tools/packgen/us_equities/make.py, tools/packgen/gleif/make.py). The two packs without a guide
generator are kept here:

    python3 tools/packgen/common/guide_data.py            write compute-demo's guide and help entry, and the generated block of the
                                                          hand-written news-and-markets guide
    python3 tools/packgen/common/guide_data.py --check    fail if they differ from what would be written

The contracts' own pages (docs/contracts/packs/<pack>.md, tools/contracts.py docs) are generated from the same files and point here.
Where the data comes from is config: tools/packgen/common/data_retrieval.yaml. The External data page (docs/guides/PUBLIC_DATA.md)
documents every external source at length.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
PACKS = ROOT / "config" / "packs"
SPEC = Path(__file__).resolve().parent / "data_retrieval.yaml"
TESTDATA = ROOT / "data" / "testdata" / "testdata.yaml"
EXTERNAL_PAGE = "[External data](../../../../docs/guides/PUBLIC_DATA.md)"
CONTRACTS_PAGE = "../../../../docs/contracts/packs/{pack}.md"
BEGIN = "<!-- data-sections: generated by tools/packgen/common/guide_data.py from the contracts and data_retrieval.yaml; edit those, not this block -->"
END = "<!-- /data-sections -->"
HEADER = "\n".join((ROOT / "docs" / "guides" / "RACHANA_REFERENCE.md").read_text(encoding="utf-8").splitlines()[:15])


def _cell(s) -> str:
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def table(head: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows] + [""]


def spec() -> dict:
    return yaml.safe_load(SPEC.read_text(encoding="utf-8"))


def contracts(pack_dir: Path) -> list[dict]:
    """The pack's contracts, in the order of its manifest's kinds (then any other)."""
    found = {}
    for f in sorted((pack_dir / "contracts").glob("*.contract.yaml")):
        c = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        c["_file"] = f.name
        found[c.get("kind")] = c
    order = (yaml.safe_load((pack_dir / "pack.yaml").read_text(encoding="utf-8")) or {}).get("kinds") or [] if (pack_dir / "pack.yaml").is_file() else []
    return [found[k] for k in order if k in found] + [c for k, c in found.items() if k not in order]


def _testdata() -> dict[str, list[dict]]:
    """data/testdata/testdata.yaml's datasets by kind (a kind may have several: the trading pack's trade has one a booking system)."""
    if not TESTDATA.is_file():
        return {}
    out: dict[str, list[dict]] = {}
    for d in (yaml.safe_load(TESTDATA.read_text(encoding="utf-8")) or {}).get("datasets") or []:
        if isinstance(d, dict) and d.get("kind"):
            out.setdefault(d["kind"], []).append(d)
    return out


def _anchor(c: dict) -> str:
    import re
    return re.sub(r"[^\w\- ]", "", f"{c['mnemonic']}: {c['title']} ({c['kind']})".lower()).replace(" ", "-")


def _example(x: dict) -> str:
    if x.get("enum"):
        return ", ".join(f"`{e}`" for e in x["enum"])
    ex = x.get("example")
    if ex in (None, ""):
        return f"pattern `{x['pattern']}`" if x.get("pattern") else ""
    return f"`{ex}`" + (f" (pattern `{x['pattern']}`)" if x.get("pattern") else "")


def _fields(fs: list[dict], key: set[str]) -> list[str]:
    return table(["Column", "Type", "Key", "Presence", "Unit", "Example or values", "Link", "Meaning"], [[
        f"`{x['name']}`", x.get("type", ""), "key" if x["name"] in key else "", x.get("presence", "") + (f" (retiring in {x['retiring-in']})" if x.get("retiring-in") else ""),
        x.get("unit", ""), _example(x), f"`{x['link']}`" if x.get("link") else "",
        (x.get("description") or "—") + (f" *{x['note']}*" if x.get("note") else "")] for x in fs])


def contracts_section(pack: str, items: list[dict]) -> list[str]:
    if not items:
        return []
    page = CONTRACTS_PAGE.format(pack=pack)
    out = ["## Data contracts", "",
           f"Every kind of the pack has a data contract: a YAML file beside the pack (`config/packs/{pack}/contracts/<kind>.contract.yaml`, "
           "checked against `tools/contracts.schema.json`) that says what one record is, its key, how it is stored and dated, and every "
           "column. This section is generated from those files; the same files give the contract pages "
           f"([docs/contracts/packs/{pack}.md]({page}), with each kind's validation rules and the points still to review). Check them "
           "against the pack and its data with `python3 tools/contracts.py check` (or `drishti.py contract check`); show one with "
           "`python3 tools/contracts.py show <MNEMONIC>`.", ""]
    out += table(["Command", "Kind", "Class", "Key", "Grain", "Columns"], [[
        f"`{c['mnemonic']}`", f"`{c['kind']}`", c.get("class", ""), ", ".join(f"`{k}`" for k in c.get("key") or []) or "—", c.get("grain", ""),
        str(len(c.get("fields") or []) + sum(len(v) for v in (c.get("nested") or {}).values()))] for c in items])
    out += ["*Class*: **fundamental** data is delivered by a source system and stored; **input** is stored data an engine reads; "
            "**computed** is worked out by Drishti when asked and never stored by a source; **drishti-owned** is kept by Drishti itself.", ""]
    for c in items:
        st = c.get("storage") or {}
        key = set(c.get("key") or [])
        out += [f"### {c['mnemonic']}: {c['title']} (`{c['kind']}`)", "", " ".join(str(c.get("description", "")).split()), ""]
        facts = [f"**Class** {c.get('class')}" + (f", retiring in {c['retiring-in']}" if c.get("status") == "retiring" else ""),
                 f"**Key** {', '.join(f'`{k}`' for k in c.get('key') or []) or '—'}",
                 f"**Dated by** `{c.get('dated-by')}`",
                 f"**Cadence** {(c.get('cadence') or {}).get('frequency', '')}",
                 f"**Stored by** connector `{st.get('connector')}` (plugin `{st.get('plugin')}`)" + (f", table `{st['table']}`" if st.get("table") else "")]
        if c.get("id-pattern"):
            facts.append("**Ids** " + ", ".join(f"`{p}`" for p in c["id-pattern"]))
        out += [" · ".join(facts) + ".", "", f"**Grain:** {c.get('grain', '')} **Contract:** `contracts/{c['_file']}` "
                f"([full contract page]({page}#{_anchor(c)})).", ""]
        out += _fields(c.get("fields") or [], key)
        for path, fs in (c.get("nested") or {}).items():
            out += [f"Nested `{path}`:", ""] + _fields(fs, set())
        if c.get("links"):
            out += ["**Links:** " + ", ".join(f"`{x['field']}` → `{x['kind']}`" for x in c["links"]) + ".", ""]
        if c.get("notes"):
            out += [f"- {' '.join(str(n).split())}" for n in c["notes"]] + [""]
    return out


def _ext(s: dict, ids: list[str]) -> list[str]:
    return [f"{s['external'][i]['title']} ({s['external'][i]['licence']}" + ("; **internal only**" if s["external"][i].get("internal") else "") + ")"
            for i in ids]


def _origin(s: dict, pack: str, c: dict) -> dict:
    p = (s["packs"].get(pack) or {})
    return (p.get("kinds") or {}).get(c["kind"]) or p.get("default") or {}


def retrieval_section(pack: str, items: list[dict]) -> list[str]:
    if not items:
        return []
    s, td = spec(), _testdata()
    out = ["## Data retrieval", "",
           "Where each kind's data comes from, how it reaches the lake and how to check it. Three origins: **external** data, fetched "
           "from a public source by the pack's refresh script (each source, its licence and worked examples on the "
           f"{EXTERNAL_PAGE} help page); **synthetic** test data (or hand-written reference data), written by a generator with "
           "fictitious names; **computed** by a "
           "Drishti engine when it is asked, never stored by a source.", ""]
    rows, used_ext, used_gen = [], [], []
    for c in items:
        st = c.get("storage") or {}
        o = _origin(s, pack, c)
        conn = st.get("connector")
        if c.get("class") in ("computed", "drishti-owned"):
            guide = s["engines"].get(conn, "")
            how = " ".join(str(c.get("source", "")).split())
            for lead in ("computed by Drishti: ", "Drishti "):
                how = how[len(lead):] if how.startswith(lead) else how
            origin = "computed by Drishti: " + how + (f"; see {guide}" if guide else "")
            lake = "nothing to load: computed from its inputs when asked" if st.get("plugin") in ("reactive", "derived", "var-positions") else \
                f"published by the server to `{st.get('table', '').replace('<root>/', '<data>/delta/')}`"
        elif o.get("external"):
            used_ext += [i for i in o["external"] if i not in used_ext]
            origin = "external: " + "; ".join(_ext(s, o["external"]))
            scripts = sorted({s["external"][i]["script"] for i in o["external"]})
            origin += " — refreshed by " + ", ".join(f"`{x}`" for x in scripts)
            lake = None
        else:
            gen = s["generators"][o["generator"]]
            used_gen += [g for g in (o["generator"], o.get("also")) if g and g not in used_gen]
            origin = f"{gen.get('label', 'synthetic')}: `{gen['run']}`" + (f" (and `{s['generators'][o['also']]['run']}` for samples/)" if o.get("also") else "")
            if o.get("official"):
                used_ext += [i for i in o["official"] if i not in used_ext]
                origin += "; official public data optional: " + "; ".join(_ext(s, o["official"])) + \
                          " (`tools/publicdata/official_market_data.py`, to the data folder; read live by the feed connectors, off as shipped)"
            lake = None
        if lake is None:
            d = (td.get(c["kind"]) or [None])[0]
            folders = [x["folder"] for x in td.get(c["kind"]) or [] if x.get("folder")]
            if folders:
                lake = ", ".join(f"`data/testdata/{f}/`" for f in folders) + " → `lake demo` → connector " + \
                       ", ".join(f"`{x.get('connector')}`" for x in td[c["kind"]] if x.get("folder"))
                if conn and conn not in {x.get("connector") for x in td[c["kind"]]}:
                    lake += f"; live through connector `{conn}` (plugin `{st.get('plugin')}`) when it is switched on (off as shipped)"
            elif d and d.get("samples"):
                lake = f"`{d['samples']}/` → `lake demo` → connector `{d.get('connector')}`"
            elif st.get("test-data"):
                lake = ", ".join(f"`{x}/`" for x in st["test-data"]) + f" → connector `{conn}`"
            else:
                lake = f"read live by connector `{conn}` (plugin `{st.get('plugin')}`) when it is switched on; nothing is committed"
        rows.append([f"`{c['mnemonic']}`", f"`{c['kind']}`", origin, lake])
    out += table(["Command", "Kind", "Origin", "How it reaches Drishti"], rows)
    if used_ext:
        out += ["### External sources", ""]
        out += table(["Source", "Where", "Licence", "Internal only", "Refresh"], [[
            e["title"], e["url"], e["licence"], "**yes**" if e.get("internal") else "no",
            f"`python3 {e['script']} refresh {e['source']}`" if e["script"].startswith("tools/publicdata/") else f"`{e['script']}` {e['source']}"]
            for e in (s["external"][i] for i in used_ext)])
        internal = [s["external"][i]["title"] for i in used_ext if s["external"][i].get("internal")]
        if internal:
            out += ["**Internal only:** " + "; ".join(internal) + ". The terms restrict reuse or forbid redistribution: the data is for "
                    "internal demonstrations only, never written into a committed folder without `--internal-ok`, and must be raised with "
                    "the owner before any client or external use.", ""]
        scripts = sorted({s["external"][i]["script"] for i in used_ext if s["external"][i]["script"] in s["scripts"]})
        for sc in scripts:
            info = s["scripts"][sc]
            ex = [["status", "each source: licence, internal only or not, last refreshed (offline)"],
                  ["refresh --dry-run", "what would be fetched and written; changes nothing"]] + info["examples"]
            w = max(len(f"python3 {sc} {e[0]}") for e in ex) + 2
            out += ["```bash"] + [f"python3 {sc} {e[0]}".ljust(w) + f"# {e[1]}" for e in ex] + ["```", "",
                    f"The same through the wrappers: `tools/publicdata/{info['wrapper']}.sh status` on Linux and macOS, "
                    f"`.\\tools\\windows\\publicdata-{info['wrapper']}.ps1 status` on Windows (every argument is passed on).", ""]
    if used_gen:
        out += ["### Generators", ""]
        out += table(["Generator", "Writes", "Check"], [[f"`{s['generators'][g]['run']}`", s["generators"][g]["what"],
                                                         f"`{s['generators'][g]['check']}`" if s["generators"][g].get("check") else "—"] for g in used_gen])
    out += ["### Into the lake, checking, offline", "",
            "- **The lake.** `python3 tools/drishti.py lake demo` reads `data/testdata/testdata.yaml` and writes every dataset (test data, "
            "the packs' samples and the committed public-data snapshots) into `<data>/delta/<domain>/<kind>/`, where the pack's Delta "
            "connector serves it; a computed kind needs nothing loaded. `lake build` loads your own large JSON exports the same way "
            "([Tools](../../../../docs/guides/TOOLS.md)).",
            "- **Checking.** `python3 tools/contracts.py check` compares every contract with the pack and its data; each generator's "
            "`--check` (above) fails when the committed files differ from what it would write; in the console, `<MNEMONIC> <GO>` lists "
            "a kind and the pack's code opens its overview with the count of each kind.",
            "- **Offline.** Everything committed works without a network: the test data, the samples and the public-data snapshots are in "
            "the repository and `lake demo` reads only them. A refresh script runs offline from its download cache (`--offline`); a "
            "connector that reaches the internet (news, yfinance, the public-data feeds) is off as shipped and never starts on a machine "
            "configured offline (`drishti.offline.plugins`).", ""]
    return out


def sections(pack_dir: Path) -> list[str]:
    """Both sections for the pack in ``pack_dir`` (nothing when it has no contracts, as the retired example packs)."""
    pack_dir = Path(pack_dir)
    items = contracts(pack_dir)
    pack = pack_dir.name
    return contracts_section(pack, items) + retrieval_section(pack, items)


# -- the two packs without a guide generator ------------------------------------------------------------------------------------

def _compute_demo() -> dict[Path, str]:
    d = PACKS / "compute-demo"
    m = yaml.safe_load((d / "pack.yaml").read_text(encoding="utf-8"))
    gen = "<!-- Generated by tools/packgen/common/guide_data.py. Edit the generator, pack.yaml or the contracts, not this file. -->"
    lines = [HEADER, gen, f"# {m['title']} pack", "", " ".join(m["description"].split()), "",
             f"**Code:** `{m['code']}` · **Kinds:** {len(m['kinds'])} · enable it with `DRISHTI_PACKS=compute-demo` (a sample pack; "
             "`drishti.packs.samples` hides it from business users).", "", "## Using it", ""]
    lines += table(["Type", "Shows"], [[f"`{e[0]} <GO>`", e[1]] for e in (m.get("console") or {}).get("examples") or []])
    lines += table(["Command", "Kind", "Opens"], [[f"`{code}`", f"`{v['kind']}`", v.get("label", "")] for code, v in m["mnemonics"].items()])
    lines += ["A book's page asks both engines for the sum of its strips' paths: the Python engine runs in the compute pool `sample` "
              "(`config/compute/compute.yaml`), the Java twin in the server; each panel shows its own progress and state. Parameters ride "
              "on the id (`BOOK-FX~delay-ms=50`). How reactive connectors work: "
              "[REACTIVE_CONNECTORS.md](../../../../docs/architecture/REACTIVE_CONNECTORS.md).", ""]
    lines += sections(d)
    help_yaml = yaml.safe_dump({"guides": [{"slug": "compute-demo", "category": "packs", "title": "Compute demo pack", "icon": "cpu",
                                            "file": "guides/compute-demo.md",
                                            "summary": "Reactive connectors on synthetic P&L strips: a book's path computed by a Python and a Java "
                                                       "engine; the data contract of every kind and where its data comes from."}]},
                               sort_keys=False, allow_unicode=True, width=160)
    yhead = "\n".join("#" + (" " + x if x.strip() else "") for x in HEADER.splitlines()[1:14])
    return {d / "guides" / "compute-demo.md": "\n".join(lines).rstrip() + "\n",
            d / "config" / "help.yaml": f"{yhead}\n\n# {gen[5:-4]}\n{help_yaml}"}


def _block(path: Path, pack_dir: Path) -> str:
    """A hand-written guide with the generated block at its end (between BEGIN and END), replaced in place."""
    text = path.read_text(encoding="utf-8")
    body = "\n".join([BEGIN] + sections(pack_dir) + [END])
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        return head + body + rest.split(END, 1)[1]
    return text.rstrip() + "\n\n" + body + "\n"


def files() -> dict[Path, str]:
    out = _compute_demo()
    nm = PACKS / "news-and-markets" / "guides" / "news-and-markets.md"
    out[nm] = _block(nm, nm.parents[1])
    return out


def main(argv: list[str]) -> int:
    want = files()
    if "--check" in argv:
        stale = [str(f.relative_to(ROOT)) for f, t in want.items() if not f.is_file() or f.read_text(encoding="utf-8") != t]
        if stale:
            print(f"pack guides out of date; run tools/packgen/common/guide_data.py: {stale}")
            return 1
        print(f"{len(want)} files up to date")
        return 0
    for f, t in want.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(t, encoding="utf-8")
    print(f"wrote {len(want)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
