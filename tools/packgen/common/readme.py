"""The README standard for packs and connectors (docs/guides/PACK_DEVELOPER_GUIDE.md and
docs/connectors/CONNECTOR_DEVELOPER_GUIDE.md, "The README standard").

Every pack (``config/packs/<pack>/README.md``), every connector type (``plugins/drishti-plugin-<x>/README.md``, the built-ins in
``docs/connectors/types/<type>/README.md``) and every folder of connector templates (``config/connectors.examples/<x>/README.md``)
has a README: the licence comment, a YAML front matter (for AI and the console), then fixed ``## `` sections.

    split(text)                      (front matter dict, markdown body) of a README
    sections(body)                   {"What it is": text, ...} by ``## `` headings
    problems_pack(path, kinds)       what is wrong with a pack README (empty list: it follows the standard)
    problems_connector(path)         the same for a connector type or template README
    render_pack(pack_dir, ...)       a pack's README from pack.yaml, its samples, its Sutras and a hand-written intro

A pack's README is generated: its generator (or ``tools/packgen/readme.py <pack>`` for a pack without one) calls render_pack and
writes the result; ``--check`` compares. The hand-written part is the intro, ``tools/packgen/<generator>/readme/<pack>.intro.md``
(or ``tools/packgen/intros/<pack>.intro.md``): a front matter (summary, sources with licences, notes on fields) and a ``## `` text
per section it adds to (``What it is`` at least).
"""
from __future__ import annotations

import json
import re
from collections import OrderedDict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
PACKGEN = ROOT / "tools" / "packgen"

PACK_KEYS = ["pack", "version", "summary", "kinds", "commands", "depends-on", "sources", "refresh"]
PACK_SECTIONS = ["What it is", "Data structures", "Screens and commands", "Data sources and licences", "Enabling and dependencies",
                 "Refreshing the data", "See also"]
CONNECTOR_KEYS = ["connector", "category", "summary", "capabilities", "settings", "auth", "licence", "windows", "doc"]
TEMPLATE_KEYS = ["template", "category", "summary", "connectors", "files", "doc"]
CONNECTOR_SECTIONS = ["What it reads", "Settings", "Data structure", "Examples", "Troubleshooting", "See also"]
CAPABILITIES = {"fetch", "search", "subscribe", "history", "reverse-lookup", "bulk-scan", "write"}
CATEGORIES = {"plugin", "built-in", "template"}

_COMMENT = re.compile(r"\A(?:\s*<!--.*?-->)*\s*", re.S)


def licence_comment() -> str:
    """The HTML-comment licence header every markdown file of the repository starts with."""
    lines = (ROOT / "docs" / "guides" / "RACHANA_REFERENCE.md").read_text(encoding="utf-8").splitlines()
    return "\n".join(lines[:lines.index("-->") + 1])


def split(text: str) -> tuple[dict | None, str]:
    """The front matter (None when there is none or it is not a YAML mapping) and the markdown after it. Leading HTML comments
    (the licence, a "generated by" line) come before the front matter and are skipped."""
    rest = text[_COMMENT.match(text).end():]
    if not rest.startswith("---\n"):
        return None, rest
    end = rest.find("\n---\n", 3)
    if end < 0:
        return None, rest
    try:
        meta = yaml.safe_load(rest[4:end])
    except yaml.YAMLError:
        return None, rest[end + 5:]
    return (meta if isinstance(meta, dict) else None), rest[end + 5:]


def sections(body: str) -> "OrderedDict[str, str]":
    """``## `` sections of a markdown body, in order: title to text (up to the next ``## ``; ``### `` stays inside)."""
    out: OrderedDict[str, str] = OrderedDict()
    cur, buf, fence = None, [], False
    for line in body.splitlines():
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith("## "):
            if cur is not None:
                out[cur] = "\n".join(buf).strip()
            cur, buf = line[3:].strip(), []
        elif cur is not None:
            buf.append(line)
    if cur is not None:
        out[cur] = "\n".join(buf).strip()
    return out


def _missing(meta: dict, keys: list[str]) -> list[str]:
    return [f"front matter has no '{k}'" for k in keys if k not in meta or meta[k] in (None, "", [])]


def _sections_ok(body: str, wanted: list[str]) -> list[str]:
    have = sections(body)
    out = [f"no '## {s}' section" for s in wanted if s not in have]
    out += [f"section '{s}' is empty" for s in wanted if s in have and not have[s].strip()]
    return out


def problems_pack(path: Path, kinds: list[str]) -> list[str]:
    """What keeps a pack README from the standard: the file, the front matter, the sections, and every kind the pack owns
    described under Data structures (a ``### `kind` `` heading)."""
    if not path.is_file():
        return ["no README.md"]
    meta, body = split(path.read_text(encoding="utf-8"))
    if meta is None:
        return ["no valid YAML front matter"]
    out = _missing(meta, PACK_KEYS) + _sections_ok(body, PACK_SECTIONS)
    if "pack" in meta and meta["pack"] != path.parent.name:
        out.append(f"front matter names pack '{meta['pack']}', the folder is '{path.parent.name}'")
    data = sections(body).get("Data structures", "")
    headed = set(re.findall(r"^### `([^`]+)`", data, re.M))
    out += [f"kind '{k}' is missing from Data structures" for k in kinds if k not in headed]
    if sorted(meta.get("kinds") or []) != sorted(kinds):
        out.append("front matter kinds differ from pack.yaml")
    return out


def problems_connector(path: Path) -> list[str]:
    """What keeps a connector type or template README from the standard."""
    if not path.is_file():
        return ["no README.md"]
    meta, body = split(path.read_text(encoding="utf-8"))
    if meta is None:
        return ["no valid YAML front matter"]
    template = meta.get("category") == "template"
    out = _missing(meta, TEMPLATE_KEYS if template else CONNECTOR_KEYS) + _sections_ok(body, CONNECTOR_SECTIONS)
    if meta.get("category") not in CATEGORIES:
        out.append(f"category must be one of {sorted(CATEGORIES)}")
    if not template:
        bad = set(meta.get("capabilities") or []) - CAPABILITIES
        if bad:
            out.append(f"unknown capabilities {sorted(bad)} (known: {sorted(CAPABILITIES)})")
    doc = meta.get("doc")
    if doc and not (ROOT / doc).is_file():
        out.append(f"doc '{doc}' does not exist")
    return out


