PUBLICDATA = {"market-data": "official_market_data.py"}


def find_intro(pack: str) -> Path | None:
    """The hand-written intro of a pack: under its generator (``tools/packgen/<gen>/readme/``) or ``tools/packgen/intros/``."""
    hits = sorted(PACKGEN.glob(f"*/readme/{pack}.intro.md")) + sorted(PACKGEN.glob(f"intros/{pack}.intro.md"))
    return hits[0] if hits else None


class _Files:
    """A pack folder's files, from a generator's in-memory output first (what it is about to write) and the disk second."""

    def __init__(self, pack_dir: Path, files: dict | None):
        self.dir = pack_dir
        self.mem = {Path(k).resolve(): v for k, v in (files or {}).items()}

    def text(self, rel: str) -> str | None:
        p = (self.dir / rel).resolve()
        if p in self.mem:
            return self.mem[p]
        return p.read_text(encoding="utf-8") if p.is_file() else None

    def glob(self, pattern: str) -> list[str]:
        names = {str(p.relative_to(self.dir)) for p in self.dir.glob(pattern) if p.is_file()}
        names |= {str(p.relative_to(self.dir.resolve())) for p in self.mem if p.is_relative_to(self.dir.resolve())
                  and p.relative_to(self.dir.resolve()).match(pattern)}
        return sorted(names)


MAX_RECORDS = 4000          # documents read per kind for the field tables
MAX_TOP = 70                # top-level fields listed per kind
MAX_NESTED = 24             # nested structures listed per kind
MAX_SUB = 40                # fields listed per nested structure


def _type(v) -> str:
    if isinstance(v, bool):
        return "boolean"
    if isinstance(v, int):
        return "integer"
    if isinstance(v, float):
        return "number"
    if isinstance(v, str):
        if not v:
            return "null"
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", v):
            return "date"
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}T[0-9:.]+(Z|[+-]\d\d:?\d\d)?", v):
            return "timestamp"
        return "string"
    if isinstance(v, list):
        if v and all(isinstance(x, dict) for x in v):
            return "list of objects"
        if v:
            return "list of " + _type(v[0]) + "s"
        return "list"
    if isinstance(v, dict):
        return "object"
    return "null"


def _types(types) -> str:
    t = list(types)
    if "number" in t and "integer" in t:
        t.remove("integer")
    if "date" in t and "timestamp" in t:
        t.remove("date")
    return " or ".join(t) or "null"


def _glossary(about: dict, kind: str) -> dict[str, str]:
    """Field to meaning from a pack's about.yaml (config/about.yaml): a kind's glossary, its entries naming a vocabulary term
    with ``use:``. Paths come as ``LEGS.CASH_FLOWS``; nested ones are keyed as the tables write them (``LEGS[].CASH_FLOWS``)."""
    vocab = about.get("vocabulary") or {}
    out = {}
    for f, g in (((about.get("kinds") or {}).get(kind) or {}).get("glossary") or {}).items():
        if not isinstance(g, dict):
            continue
        if g.get("use"):
            g = {**(vocab.get(g["use"]) or {}), **{k: v for k, v in g.items() if k != "use"}}
        text = " ".join(str(g.get("means") or g.get("term") or "").split())
        if g.get("unit") and text:
            text += f" ({g['unit']})"
        if text:
            out[f] = text
    return out


def _example(v) -> str:
    if isinstance(v, (dict, list)) or v is None or v == "":
        return ""
    s = json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else v
    s = s.replace("|", "/").replace("\n", " ")
    return "`" + (s[:40] + "…" if len(s) > 41 else s) + "`"


class _Shape:
    """Fields seen over a kind's documents: path to {types, example, count}; nested lists and objects by path."""

    def __init__(self):
        self.n = 0
        self.top: OrderedDict[str, dict] = OrderedDict()
        self.nested: OrderedDict[str, OrderedDict[str, dict]] = OrderedDict()

    def add(self, doc: dict) -> None:
        self.n += 1
        self._walk(doc, "", self.top, 0)

    def _walk(self, obj: dict, path: str, into: dict, depth: int) -> None:
        for k, v in obj.items():
            if k == "_meta":
                continue
            f = into.setdefault(k, {"types": OrderedDict(), "example": "", "count": 0})
            f["count"] += 1
            t = _type(v)
            if t != "null" and not (t == "list" and f["types"]):
                f["types"][t] = 1
            if not f["example"]:
                f["example"] = _example(v)
            if depth >= 3:
                continue
            sub = None
            if isinstance(v, list) and v and all(isinstance(x, dict) for x in v):
                sub = f"{path}{k}[]"
                items = v[:50]
            elif isinstance(v, dict) and v:
                sub = f"{path}{k}"
                items = [v]
            if sub:
                fields = self.nested.setdefault(sub, OrderedDict())
                for item in items:
                    self._walk(item, sub + ".", fields, depth + 1)


def _shape(files: _Files, kind: str) -> _Shape:
    s = _Shape()
    for name in files.glob(f"samples/{kind}.jsonl") + files.glob(f"samples/{kind}.part-*.jsonl"):
        for line in (files.text(name) or "").splitlines():
            if s.n >= MAX_RECORDS:
                return s
            if line.strip():
                s.add(json.loads(line))
    if not s.n:
        for name in files.glob(f"samples/{kind}/*.json")[:MAX_RECORDS]:
            s.add(json.loads(files.text(name)))
    return s


def _sutras(files: _Files) -> list[dict]:
    out = []
    for name in files.glob("sutras/**/*.sutra.yaml") + files.glob("sutras/*.sutra.yaml"):
        try:
            y = yaml.safe_load(files.text(name)) or {}
        except yaml.YAMLError:
            continue
        if isinstance(y, dict) and isinstance(y.get("match"), dict):
            out.append({"file": name, "sutra": y.get("sutra") or Path(name).name.split(".")[0], "kind": y["match"].get("kind"),
                        "description": (y.get("description") or (y.get("doc") or {}).get("summary") or "").strip(), "doc": y})
    return sorted({s["file"]: s for s in out}.values(), key=lambda s: s["file"])


_BIND = re.compile(r"^[$@]\.([A-Za-z_][A-Za-z0-9_.]*)$")


def _labels(node, rows: str = "", into: dict | None = None) -> dict:
    """Field path to label from a Sutra: ``{label, bind: $.X}`` pairs, and ``@.Y`` columns of a table over ``rows: $.X`` (X[].Y)."""
    into = {} if into is None else into
    if isinstance(node, dict):
        here = rows
        r = node.get("rows")
        if isinstance(r, str) and _BIND.match(r.strip()):
            here = _BIND.match(r.strip()).group(1).replace(".", "[].") + "[]"
        b, lab = node.get("bind"), node.get("label")
        if isinstance(b, str) and isinstance(lab, str) and _BIND.match(b.strip()):
            name = _BIND.match(b.strip()).group(1)
            path = (here + "." + name) if b.strip().startswith("@") and here else name
            into.setdefault(path, lab)
        for v in node.values():
            _labels(v, here, into)
    elif isinstance(node, list):
        for v in node:
            _labels(v, rows, into)
    return into


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def _table(head: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows] + [""]


def _env(text: str) -> list[str]:
    return sorted(set(re.findall(r"\$\{([A-Z][A-Z0-9_]*)(?::[^}]*)?\}", text)))


def _first_sentence(text: str) -> str:
    text = " ".join((text or "").split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text)[:240]


def _ancestors(packs_dir: Path, manifest: dict, seen: set | None = None) -> list[dict]:
    """The manifests of the packs a pack extends or requires, farthest first (read from the disk beside it)."""
    seen = set() if seen is None else seen
    out = []
    for name in (manifest.get("extends") or []) + (manifest.get("requires") or []):
        f = packs_dir / name / "pack.yaml"
        if name in seen or not f.is_file():
            continue
        seen.add(name)
        parent = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        out += _ancestors(packs_dir, parent, seen) + [parent]
    return out


def render_pack(pack_dir: Path, generator: str | None = None, files: dict | None = None, intro: Path | None = None) -> str:
    """A pack's README.md. ``files``: {path: text} a generator is about to write (pack.yaml, samples), read before the disk."""
    pack_dir = Path(pack_dir)
    F = _Files(pack_dir, files)
    m = yaml.safe_load(F.text("pack.yaml")) or {}
    name = m.get("pack") or pack_dir.name
    intro = intro or find_intro(name)
    imeta, ibody = split(intro.read_text(encoding="utf-8")) if intro and intro.is_file() else ({}, "")
    imeta = imeta or {}
    isec = sections(ibody)
    generator = generator or imeta.get("generator") or f"tools/packgen/readme.py {name}"
    kinds = list(m.get("kinds") or [])
    mnemonics = {code: v for code, v in (m.get("mnemonics") or {}).items() if isinstance(v, dict)}
    code_of = {v.get("kind"): code for code, v in mnemonics.items()}
    graph = m.get("graph") or {}
    links = {}
    for parent in _ancestors(pack_dir.parent, m):        # the graph fields of the packs it builds on, then its own
        links.update({f: v for f, v in ((parent.get("graph") or {}).get("fields") or {}).items() if isinstance(v, dict)})
    links.update({f: v for f, v in (graph.get("fields") or {}).items() if isinstance(v, dict)})
    patterns: dict[str, list[str]] = {}
    for p in graph.get("id-patterns") or []:
        patterns.setdefault(p.get("kind"), []).append(p.get("pattern"))
    cat_lines = F.text("samples/catalog.jsonl")                 # one entry a line (2.9.4); else the older catalog.json array
    catalog = [json.loads(t) for t in cat_lines.splitlines() if t.strip()] if cat_lines else json.loads(F.text("samples/catalog.json") or "[]")
    example_id: dict[str, str] = {}
    for e in catalog:
        example_id.setdefault(e.get("kind"), str(e.get("id")))
    sutras = _sutras(F)
    about = yaml.safe_load(F.text(m.get("about") or "config/about.yaml") or "{}") or {}
    connectors = m.get("connectors") or {}
    routes = m.get("routes") or {}
    notes = imeta.get("fields") or {}
    publicdata = ROOT / "tools" / "publicdata" / (PUBLICDATA.get(name) or name.replace("-", "_") + ".py")
    refresh = imeta.get("refresh") or (str(publicdata.relative_to(ROOT)) if publicdata.is_file() else generator)
    packs = [p for p in (m.get("extends") or []) + (m.get("requires") or []) if p]
    own = set(connectors)
    settings = _env(yaml.safe_dump(connectors))
    sources = imeta.get("sources") or []
    summary = imeta.get("summary") or _first_sentence(m.get("description", ""))

    front = dict([
        ("pack", name), ("version", str(m.get("version", ""))), ("code", m.get("code")), ("title", m.get("title")),
        ("summary", summary), ("kinds", kinds),
        ("commands", dict([(c, v.get("kind")) for c, v in mnemonics.items()] + ([(m["code"], "pack overview")] if m.get("code") else []))),
        ("depends-on", dict([("packs", packs), ("connectors", sorted(own | set(routes.values()))),
                                    ("plugins", sorted({c.get("plugin") for c in connectors.values() if isinstance(c, dict) and c.get("plugin")})),
                                    ("settings", settings)])),
        ("sources", sources), ("refresh", refresh), ("generated-by", generator),
    ])
    out = [licence_comment(), f"<!-- Generated by {generator}. Edit the intro ({intro.relative_to(ROOT) if intro else 'none'}), "
                              f"pack.yaml or the generator, not this file. -->",
           "---", yaml.safe_dump(dict(front), sort_keys=False, allow_unicode=True, width=1000).rstrip(), "---",
           f"# The {name} pack", "", f"*{m.get('title', name)}* · version {m.get('version', '')} · code `{m.get('code', '')}`", ""]

    out += ["## What it is", "", isec.get("What it is") or " ".join((m.get("description") or "").split()), ""]

    # -- data structures
    out += ["## Data structures", "", isec.get("Data structures", "Every kind the pack owns, read from its manifest, its samples and its "
            "Sutras: how its ids look, its fields (type, an example, what it means), its nested lists and the fields that link to "
            "other kinds. A path `A[].B` is field `B` of every element of list `A`."), ""]
    for kind in kinds:
        shape = _shape(F, kind)
        ks = [s for s in sutras if s["kind"] == kind]
        labels: dict[str, str] = {}
        for s in ks:
            _labels(s["doc"], "", labels)
        kn = notes.get(kind) or {}
        about_kind = (about.get("kinds") or {}).get(kind) or {}
        glossary = _glossary(about, kind)
        for path in list(glossary):                       # LEGS.CASH_FLOWS is written LEGS[].CASH_FLOWS where LEGS is a list
            parts, cur = path.split("."), ""
            for i, part in enumerate(parts[:-1]):
                cur = (cur + "." if cur else "") + part
                if cur + "[]" in shape.nested:
                    cur += "[]"
            if len(parts) > 1:
                glossary[cur + "." + parts[-1]] = glossary[path]
        conn = routes.get(kind)
        out += [f"### `{kind}`", ""]
        what = kn.get("_") if isinstance(kn, dict) and kn.get("_") else None
        label = (mnemonics.get(code_of.get(kind)) or {}).get("label")
        bits = [f"**{label}**" if label else None, f"mnemonic `{code_of[kind]}`" if kind in code_of else None,
                f"read through connector `{conn}`" if conn else None]
        out += [" · ".join(b for b in bits if b) + ".", ""] if any(bits) else []
        if what:
            out += [what, ""]
        elif about_kind.get("title") and about_kind.get("title") != label:
            out += [f"About: {about_kind['title']}.", ""]
        eid = example_id.get(kind)
        id_field = None
        if shape.n and eid:
            first = None
            for nm in F.glob(f"samples/{kind}.jsonl") + F.glob(f"samples/{kind}.part-*.jsonl"):
                first = json.loads((F.text(nm) or "{}").splitlines()[0])
                break
            id_field = next((k for k, v in (first or {}).items() if str(v) == eid), None)
        idl = []
        if id_field:
            idl.append(f"field `{id_field}`")
        if patterns.get(kind):
            idl.append("pattern " + ", ".join(f"`{p}`" for p in patterns[kind]))
        if eid:
            idl.append(f"for example `{eid}`")
        out += [("**Id:** " + "; ".join(idl) + ".") if idl else "**Id:** set by its connector (no samples ship).", ""]
        if shape.n:
            rows = []
            for f, v in list(shape.top.items())[:MAX_TOP]:
                desc = (kn.get(f) if isinstance(kn, dict) and kn.get(f) else glossary.get(f) or labels.get(f, ""))
                if not desc and f == id_field:
                    desc = "The document's id"
                elif not desc and ("object" in v["types"] or "list of objects" in v["types"]):
                    desc = "Nested: see below"
                if f in links:
                    desc = (desc + "; " if desc else "") + f"link to `{links[f].get('kind')}`"
                share = "" if v["count"] == shape.n else f" (in {round(100 * v['count'] / shape.n)}%)"
                rows.append([f"`{f}`", _types(v["types"]), v["example"], (desc or "—") + share])
            out += [f"Fields, from {shape.n} sample document{'s' if shape.n != 1 else ''}:", ""]
            out += _table(["Field", "Type", "Example", "Description"], rows)
            if len(shape.top) > MAX_TOP:
                out += [f"…and {len(shape.top) - MAX_TOP} more fields (see the samples).", ""]
            if shape.nested:
                out += ["Nested structures:", ""]
                nrows = []
                for path, fields in list(shape.nested.items())[:MAX_NESTED]:
                    names = list(fields)
                    listed = ", ".join(f"`{n}` ({_types(fields[n]['types'])})" + (f": {glossary[path + '.' + n]}" if glossary.get(path + '.' + n) else "")
                                       for n in names[:MAX_SUB])
                    nrows.append([f"`{path}`", listed + (f", …{len(names) - MAX_SUB} more" if len(names) > MAX_SUB else "")])
                out += _table(["Path", "Fields"], nrows)
                if len(shape.nested) > MAX_NESTED:
                    out += [f"…and {len(shape.nested) - MAX_NESTED} more nested structures.", ""]
        else:
            seen = sorted(labels.items())
            src = connectors.get(conn) or {}
            how = f"its connector `{conn}` (plugin `{src.get('plugin')}`)" if conn and src else f"its connector `{conn}`" if conn else "its connector"
            out += [f"No samples ship: documents are read live from {how}."
                    + (" The fields its screens show:" if seen else ""), ""]
            if seen:
                out += _table(["Field", "Shown as"], [[f"`{f}`", lab] for f, lab in seen[:MAX_TOP]])
        lk = sorted({f for f in links if f in shape.top or f in labels})
        if lk:
            out += ["Links: " + ", ".join(f"`{f}` → `{links[f].get('kind')}`" for f in lk) + ".", ""]
    # -- screens and commands
    out += ["## Screens and commands", ""]
    if isec.get("Screens and commands"):
        out += [isec["Screens and commands"], ""]
    rows = [[f"`{c}`", f"`{v.get('kind')}`", v.get("label", "")] for c, v in mnemonics.items()]
    if m.get("code"):
        rows.append([f"`{m['code']}`", "—", "The pack's overview: its kinds, how many each holds, an example of each"])
    out += _table(["Command", "Kind", "Opens"], rows)
    ex = (m.get("console") or {}).get("examples") or []
    if ex:
        out += ["Examples:", ""] + _table(["Type", "Shows"], [[f"`{e[0]}`", e[1] if len(e) > 1 else ""] for e in ex if e])
    if sutras:
        out += ["Screens (Sutras):", ""] + _table(["Sutra", "Kind", "What it shows"], [[f"`{s['sutra']}`", f"`{s['kind']}`", _first_sentence(s["description"])] for s in sutras])
    # -- sources
    out += ["## Data sources and licences", ""]
    if isec.get("Data sources and licences"):
        out += [isec["Data sources and licences"], ""]
    if sources:
        out += _table(["Source", "Licence", "Internal only", "Used for"], [[s.get("name", ""), s.get("licence", ""), "yes" if s.get("internal-only") else "no",
                                                                           s.get("used-for", "")] for s in sources])
    guide_files = [g.get("file") for g in (yaml.safe_load(F.text("config/help.yaml") or "{}") or {}).get("guides") or [] if g.get("file")]
    if F.glob("contracts/*.contract.yaml"):
        where = f"[{guide_files[0]}]({guide_files[0]})" if guide_files else "the pack's guide"
        out += [f"Every kind's data contract (each column: type, key, example, links) and where its data comes from (an external source and "
                f"its refresh script, a generator of synthetic data, or a Drishti engine) are in the guide, {where}: *Data contracts* and "
                "*Data retrieval*.", ""]
    ext = [s for s in sources if (s.get("name") or "").strip() and not str(s.get("licence", "")).startswith("Proprietary")]
    if ext:
        out += ["External data: " + "; ".join(f"{s['name']}" + (" (**internal only**)" if s.get("internal-only") else "") for s in ext) +
                ". Each source's URL, licence, refresh script and worked examples (Linux and Windows) are on the External data help page, "
                "[docs/guides/PUBLIC_DATA.md](../../../docs/guides/PUBLIC_DATA.md).", ""]
    # -- enabling
    out += ["## Enabling and dependencies", ""]
    if isec.get("Enabling and dependencies"):
        out += [isec["Enabling and dependencies"], ""]
    out += [("Builds on the packs " + ", ".join(f"`{p}`" for p in packs) + ".") if packs else "Builds on no other pack.", ""]
    if m.get("sample"):
        out += ["A sample pack: Admin → Packs can hide it from business users (`drishti.packs.samples`).", ""]
    if connectors:
        crow = []
        for c, d in connectors.items():
            d = d if isinstance(d, dict) else {}
            crow.append([f"`{c}`", f"`{d.get('plugin', '')}`", ", ".join(f"`{k}`" for k in d.get("kinds") or []), f"`{d.get('enabled')}`" if d.get("enabled") is not None else "on"])
        out += ["The connectors it brings (written once to `config/connectors/<name>.yaml`, then the site's own):", ""]
        out += _table(["Connector", "Plugin", "Kinds", "Enabled"], crow)
    foreign = sorted(set(routes.values()) - own)
    if foreign:
        out += ["Routes to connectors it does not bring: " + ", ".join(f"`{c}`" for c in foreign) + ".", ""]
    if settings:
        out += ["Settings (environment variables) its connectors read: " + ", ".join(f"`{s}`" for s in settings) + ".", ""]
    # -- refresh
    out += ["## Refreshing the data", ""]
    if isec.get("Refreshing the data"):
        out += [isec["Refreshing the data"], ""]
    if publicdata.is_file():
        out += [f"`python3 {publicdata.relative_to(ROOT)} status` lists the external sources, their licences and when each was last refreshed "
                "(offline); `refresh --dry-run` shows what a refresh would fetch and write, changing nothing; `refresh` fetches, writes and "
                "checks. The External data help page (docs/guides/PUBLIC_DATA.md) has worked examples for Linux and Windows.", ""]
    out += [f"The pack's files are written by `{generator}`; its `--check` fails when the committed files differ from what it would write.", ""]
    # -- see also
    out += ["## See also", ""]
    help_y = yaml.safe_load(F.text("config/help.yaml") or "{}") or {}
    for g in help_y.get("guides") or []:
        out.append(f"- [{g.get('title')}]({g.get('file')}): {g.get('summary', '')}".rstrip(": "))
    if isec.get("See also"):
        out.append(isec["See also"])
    out += ["- [Packs](../../../docs/guides/PACK_DEVELOPER_GUIDE.md#part-v-domain-packs-the-packs-that-ship-turning-them-on-who-sees-which) and the [pack developer's guide](../../../docs/guides/PACK_DEVELOPER_GUIDE.md) "
            "(the README standard).", ""]
    return "\n".join(out).rstrip() + "\n"
