def add_var_kinds(m: dict) -> None:
    """The VaR engine's kinds (var_kinds.py) in the market-risk manifest: kinds, mnemonics, ids, links, badges, the risk-store's tables
    (with the P&L vector columns) and routes, the var-positions connector (the positions Drishti derives, served from the engine), and
    two examples."""
    store = m["connectors"]["risk-store"]
    store["settings"] = {**store["settings"], "layout": {**store["settings"].get("layout", {}), **VK.LAYOUT}}
    for k, (mnem, label, pattern, _id) in VK.KINDS.items():
        m["kinds"].append(k)
        m["mnemonics"][mnem] = {"kind": k, "label": label}
        m["graph"]["id-patterns"].append({"pattern": pattern, "kind": k})
        connector = VK.SERVED_BY.get(k, "risk-store")
        if connector == "risk-store":
            store["kinds"].append(k)
        m["routes"][k] = connector
        if k in VK.BADGES:
            m["graph"]["badges"][k] = VK.BADGES[k]
    m["connectors"].update(VK.CONNECTORS)
    m["graph"]["fields"] = dict(sorted({**m["graph"]["fields"], **{f: {"kind": k, "label": lab} for f, (k, lab) in VK.FIELDS.items()}}.items()))


def body_of(src: Path) -> str:
    """A hand-written source without its own licence header (the generator writes one)."""
    lines = src.read_text(encoding="utf-8").split("\n")
    while lines and (lines[0].startswith("#") or not lines[0].strip()):
        lines.pop(0)
    return "\n".join(lines)


class _Plain(yaml.SafeDumper):
    """Writes a value shared by several connectors (the trade systems' one layout) in full each time: no YAML anchors or aliases,
    which a reader may refuse or not resolve."""

    def ignore_aliases(self, data):
        return True


KEPT = Path(__file__).parent / "kept"


def kept(name: str) -> str:
    """The pack's hand-kept sections (``kept/<pack>.yaml``: ``history:``, ``ingest:``), appended to its manifest as written, comments
    and all: top-level sections the taxonomy does not say, edited there and never lost when the manifest is written again."""
    src = KEPT / f"{name}.yaml"
    if not src.is_file():
        return ""
    text = src.read_text(encoding="utf-8")
    text = (text.split("\n\n", 1)[1] if text.startswith("#") and "\n\n" in text else text).strip("\n")   # without its licence header
    top = {k for k in (yaml.safe_load(text) or {})}
    clash = top & set(manifest(name))
    if clash:
        raise SystemExit(f"{src}: {sorted(clash)} are generated; keep only sections the generator does not write")
    return "\n" + text + "\n"


def files() -> dict[Path, str]:
    out = {}
    for name in layout.PACKS:
        body = yaml.dump(manifest(name), Dumper=_Plain, sort_keys=False, allow_unicode=True, width=140)
        out[PACKS / name / "pack.yaml"] = f"{HEADER}\n\n{GENERATED}\n# {layout.PACKS[name]['title']} pack for Drishti.\n{body}{kept(name)}"
        out[PACKS / name / "config" / "formats.yaml"] = (f"{HEADER}\n\n{GENERATED}\n# Number formats the banking packs share.\n"
                                                         + yaml.safe_dump({"formats": FORMATS}, sort_keys=False))
        about_dir = Path(__file__).parent / "about"          # hand-written about text: see docs/architecture/CONTEXT_HELP.md
        for src in sorted(about_dir.glob(f"{name}.yaml")) + sorted(about_dir.glob(f"{name}.*.yaml")):
            lang = src.name[len(name) + 1:-5]                # "" for the English file, else the language of the overlay
            target = "about.yaml" if not lang else f"about.{lang}.yaml"
            what = "what the pack's kinds mean" if not lang else f"the {lang} translation overlay of about.yaml"
            out[PACKS / name / "config" / target] = (f"{HEADER}\n\n{GENERATED}\n# About this page: {what}.\n" + body_of(src))
        for file, title, description, kinds, code in calc_snippets.SNIPPETS.get(name, []):
            meta = f"# title: {title}\n# description: {description}\n# kinds: {', '.join(kinds)}\n"
            note = f"# Generated by tools/packgen/banking/make_packs.py from snippets/{name}/{file} there. Edit that source, not this file."
            out[PACKS / name / "python" / file] = f"{HEADER}\n\n{note}\n{meta}\n{code}"
        if name == "core":   # every banking pack requires core, so its vocabulary covers them all
            out[PACKS / name / "config" / "semantics.yaml"] = (f"{HEADER}\n\n{GENERATED}\n# How banking field names read as labels.\n"
                                                               + yaml.safe_dump({"acronyms": ACRONYMS, "labels": {"TRADE_ID": "Trade", "MTM": "MTM (USD)"}},
                                                                                sort_keys=False, width=140))
    return out


def orphans(want: dict[Path, str]) -> list[Path]:
    """Snippet files under config/packs/<pack>/python/ that no longer have a source (renamed or removed)."""
    return sorted(f for name in layout.PACKS for f in (PACKS / name / "python").glob("*.py") if f not in want)


def main() -> None:
    layout.check([k.kind for k in T.KINDS] + ["trade"])
    want = files()
    if "--check" in sys.argv:
        stale = [str(f) for f, t in want.items() if not f.exists() or f.read_text(encoding="utf-8") != t]
        stale += [f"{f} (no source)" for f in orphans(want)]
        if stale:
            raise SystemExit(f"pack manifests out of date; run make_packs.py: {stale[:5]}")
        snippets = sum(len(v) for v in calc_snippets.SNIPPETS.values())
        print(f"{len(layout.PACKS)} pack manifests up to date ({snippets} Calc snippets)")
        return
    for f in orphans(want):
        f.unlink()
    for f, t in want.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(t, encoding="utf-8")
    print(f"wrote {len(layout.PACKS)} pack manifests: {', '.join(layout.PACKS)}")


