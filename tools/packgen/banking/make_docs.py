def files() -> dict[Path, str]:
    docs = make_data.build()
    out = {}
    for pack, guides in GUIDES.items():
        entries = []
        for slug, title, summary, icon, fn in guides:
            body = fn(pack, docs) if fn else {"banking-data-model": model, "market-data-catalogue": lambda: market(docs),
                                              "trading-products": lambda: products(docs)}[slug]()
            out[PACKS / pack / "guides" / f"{slug}.md"] = body.rstrip() + "\n"
            entries.append({"slug": slug, "category": "packs", "title": title, "icon": icon, "file": f"guides/{slug}.md", "summary": summary})
        help_yaml = yaml.safe_dump({"guides": entries}, sort_keys=False, allow_unicode=True, width=160)
        out[PACKS / pack / "config" / "help.yaml"] = "\n".join("#" + (" " + x if x.strip() else "") for x in HEADER.splitlines()[1:14]) + \
            f"\n\n# {GENERATED[5:-4]}\n{help_yaml}"
        out[PACKS / pack / "README.md"] = README.render_pack(PACKS / pack, files=out)
    return out


def main() -> None:
    want = files()
    if "--check" in sys.argv:
        stale = [str(f) for f, t in want.items() if not f.exists() or f.read_text(encoding="utf-8") != t]
        if stale:
            raise SystemExit(f"banking pack docs out of date; run make_docs.py: {stale[:3]}")
        print(f"{len(want)} banking doc files up to date")
        return
    for f, t in want.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(t, encoding="utf-8")
    print(f"wrote {len(want)} files: {sum(1 for f in want if f.suffix == '.md')} guides for {len(GUIDES)} packs")


if __name__ == "__main__":
    main()
