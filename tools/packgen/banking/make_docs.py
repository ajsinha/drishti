def products(docs: dict) -> str:
    lines = [HEADER, GENERATED, "# Trading products", "",
             f"The trading pack covers **{len(T.PRODUCTS)} products** in ten asset classes. Each has its own Sutra, matched on the trade's "
             "`PRODUCT_TYPE`, laid out as a deal screen (ticket, legs side by side with their flows and resets, events, payments); Calypso "
             "and Murex book them. The table says what each product is in the model the samples were generated from: its terms, schedule, "
             "the market data it is valued with and its risk measures (the valuation is market-risk's trade valuation, `TVAL`). "
             "`TRD PRODUCT_TYPE=<product type> <GO>` lists the trades in one product.", ""]
    by = defaultdict(list)
    for p in T.PRODUCTS:
        by[p.asset].append(p)
    lines += table(["Asset class", "Products"], [[a, len(ps)] for a, ps in by.items()])
    for a, ps in by.items():
        lines += [f"## {a}", ""]
        rows = []
        for p in ps:
            rows.append([p.name, f"`{p.code}`", p.family, p.schedule or "—", ", ".join(f"`{k}`" for _, k, _ in p.md) or "—",
                         ", ".join(S.RISK_LABELS[r] for r in p.risk) or "—"])
        lines += table(["Product", "PRODUCT_TYPE", "Family", "Schedule", "Market data", "Risk"], rows)
        for p in ps:
            lines += [f"**{p.name}** (`{p.code}`): {p.desc} Terms: " + ", ".join(f"`{f.name}` ({f.label})" for f in p.terms) + ".", ""]
    return "\n".join(lines)


def market(docs: dict) -> str:
    lines = [HEADER, GENERATED, "# Market-data catalogue", "",
             "The market-data kinds and how trades use them. Trades link to market data through their market-data fields "
             "(`discountCurve`, `fxVolSurface`, …), which is how F8 impact on a curve finds every trade valued with it. "
             "`<mnemonic> <GO>` lists every object of a kind, and `<mnemonic> <id> <GO>` opens one.", ""]
    for k in layout.PACKS["market-data"]["kinds"]["market"]:
        s = SPEC[k]
        lines += [f"## {s.label} (`{k}`)", "", s.desc, "", f"**Mnemonic:** `{s.mnemonic}` · **Identifiers:** `{shown_prefix(s)}…` · **Id field:** `{s.id_field}`", ""]
        fs = fields_of(s)
        if fs:
            lines += ["**Fields its Sutra reads:** " + ", ".join(f"`{f}`" for f in fs) + ".", ""]
    lines += ["## How products select market data", ""]
    rows = sorted({(f, k, sel) for p in T.PRODUCTS for f, k, sel in p.md})
    lines += table(["Trade field", "Kind", "Selected by"], [[f"`{f}`", f"`{k}`", f"`{sel}`"] for f, k, sel in rows])
    return "\n".join(lines)


def model() -> str:
    lines = [HEADER, GENERATED, "# The banking data model", "",
             "How the five banking packs' entities refer to each other. Every arrow is a reference field in a document, so each is a "
             "link in the view, a hop for F7, and a path for F8 impact.", "",
             "```text",
             "legal entity ─► desk ─► book ─► trade ◄─ trader",
             "                                 │",
             "counterparty ─► agreement ─► CSA  ├─► netting set ─► exposure (computed), CVA, SA-CCR, collateral, margin calls",
             "      │                          │        └─► credit limit (per counterparty), SIMM",
             "      └─► group, credit curve    └─► market data: curves, surfaces, spots, equities, credit, inflation, commodities",
             "desk ─► VaR ─► stress results ◄─ stress scenario        book ─► FRTB sensitivities, P&L explain",
             "```", "", "## Every reference field", ""]
    rows = []
    for f, (kind, label) in sorted(T.graph_fields().items()):
        rows.append([f"`{f}`", label, f"`{kind}`", f"`{layout.pack_of(kind)}`", f"`{layout.domain_of(kind)}`"])
    lines += table(["Field", "Label", "Opens kind", "Pack", "Data domain"], rows)
    lines += ["## Packs and data domains", ""]
    rows = [[f"`{n}`", ", ".join(f"`{r}`" for r in p["requires"]) or "—", ", ".join(f"`{d}`" for d in p["kinds"])] for n, p in layout.PACKS.items()]
    lines += table(["Pack", "Extends", "Reads domains"], rows)
    return "\n".join(lines)


