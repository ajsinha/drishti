def load(a, n: dict, cli, say=print) -> int:
    """--load: the native records into the table with SOURCE_SYSTEM stamped (data ingest --store delta)."""
    lake = a.lake or (pathlib.Path(os.environ["DRISHTI_DELTA_ROOT"]) if os.environ.get("DRISHTI_DELTA_ROOT") else None)
    if lake is None:
        raise SystemExit("--load needs --lake <the lake's Delta root> (or DRISHTI_DELTA_ROOT)")
    domain, table = n["table"].split(".", 1)
    with tempfile.TemporaryDirectory(dir=os.environ.get("TMPDIR")) as tmp:
        files = []
        for f in SM.files_of(a.inputs):
            stem = re.sub(r"\.(jsonl|ndjson)(\.gz)?$", "", f.name)
            out = pathlib.Path(tmp) / f"{stem}.jsonl"
            with SM.open_text(f) as src, open(out, "w", encoding="utf-8") as dst:
                for line in src:
                    if line.strip():
                        doc = json.loads(line)
                        doc["SOURCE_SYSTEM"] = n["system"]
                        dst.write(json.dumps(doc, separators=(",", ":")) + "\n")
            files.append(out)
        first = (n["contract"].get("key") or [None])[0]
        key = next((r["from"] for r in (getattr(a, "_map", None) or {}).get("fields", []) if r["to"] == first and r.get("from")), None)
        args = ["data", "ingest", *sum((["--from", str(f)] for f in files), []), "--domain", domain, "--kind", table, "--store", "delta",
                "--lake", str(lake), "--columns", "SOURCE_SYSTEM", *(["--key", key] if key else [])]
        say("\n== " + " ".join(["drishti.py", *args]))
        sys.stdout.flush()
        return cli.main(args)


def required(a, cli, n: dict, dist: pathlib.Path) -> list[str]:
    """`--with` for the check: the module this one requires (the kind's: modules/<pack>), packed beside it, so the runtime checks load both."""
    import module_from_jsonl as MFJ
    src = ROOT / "modules" / n["pack"]
    if not (src / "module.yaml").is_file():
        return []
    out = dist / "requires"
    out.mkdir(parents=True, exist_ok=True)
    if MFJ.module_tool(cli, a, "pack", str(src), "--out", str(out)):
        return []
    found = sorted(out.glob(f"{n['pack']}-*.dmod"))
    return ["--with", str(found[-1])] if found else []


def run(a, cli, say=print) -> int:
    import module_from_jsonl as MFJ
    t0 = time.monotonic()
    n = names(a)
    say(f"reading every record of {len(SM.files_of(a.inputs))} file(s) ...")
    prof = SM.scan(a.inputs, say)
    if not prof["rows"]:
        raise SystemExit("no records in the files")
    m = SM.propose(prof, n["kind"], n["system"])
    if a.map_edits:
        m = SM.edit(m, json.loads(pathlib.Path(a.map_edits).read_text(encoding="utf-8")))
    a._map = m
    say_map(m, say)
    if a.map_out:
        a.map_out.parent.mkdir(parents=True, exist_ok=True)
        a.map_out.write_text(json.dumps(m, default=str), encoding="utf-8")
    mod = (a.out or ROOT / "modules" / n["name"]).resolve()
    say(f"\nmodule {n['name']} {a.version}: {mod}; the kind {n['kind']} of {n['pack']}; "
        + (f"the shared table {n['table']} with where: SOURCE_SYSTEM = '{n['system']}'" if n["shared"] else f"its own table {n['table']}"))
    if a.dry_run:
        say(f"dry run: nothing written ({time.monotonic() - t0:.1f} s)")
        return 0
    if mod.exists() and any(mod.iterdir()) and not a.force:
        raise SystemExit(f"{mod} exists; pass --force to replace it")
    write_module(a, n, m, mod, say)
    if a.load and load(a, n, cli, say):
        return 1
    dist = (a.dist or ROOT / "dist").resolve()
    say("\n== module pack")
    if MFJ.module_tool(cli, a, "pack", str(mod), "--out", str(dist)):
        return 1
    dmod = dist / f"{n['name']}-{a.version}.dmod"
    say("\n== module check")
    chk = MFJ.module_tool(cli, a, "check", str(dmod), "--cycles", str(a.cycles), *required(a, cli, n, dist))
    say(f"\n{'checked' if not chk else 'CHECKS FAILED'}: {dmod} ({time.monotonic() - t0:.1f} s in all)")
    if chk:
        return 1
    if a.deploy:
        if getattr(a, "server", None) and not a.modules_dir:
            return cli.main(["module", "deploy", str(dmod), "--reason", a.reason or "pack new --source-for", *(["--server", a.server] if a.server else [])])
        target = MFJ.modules_dir(a)
        target.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(dmod, target / dmod.name)
        say(f"deployed: {target / dmod.name} (auto-deploy checks, installs and loads it; Admin -> Modules shows it)")
    return 0
