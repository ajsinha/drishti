def col(t, required=False, many=False):
    c = {"type": t}
    if required:
        c["required"] = True
    if many:
        c["many"] = True
    return c


def rowset(cols, required=True):
    p = {"role": "data", "type": "rowset"}
    if required:
        p["required"] = True
    p["shape"] = cols
    return p


def chip(name, title, category, tags, purpose, pins_in, pins_out, pin_text, behaviour, defaults, limits, not_for, a11y, panel, example,
         version=1, compatible=None, chip_limits=None):
    """A chip document: header, manual, pins, body (one panel)."""
    doc = {"rachana": 1, "chip": name, "version": version, "title": title, "category": category, "tags": tags}
    if compatible:
        doc["compatible-with"] = compatible
    doc["manual"] = {"purpose": purpose, "pins": pin_text, "behaviour": behaviour, "defaults": defaults, "limits": limits,
                     "examples": [example], "not-for": not_for, "accessibility": a11y}
    doc["pins"] = {"in": pins_in, "out": pins_out} if pins_out else {"in": pins_in}
    if chip_limits:
        doc["limits"] = chip_limits
    doc["body"] = {"panels": [panel]}
    return doc


def board_example(title, chip_ref, pins_in, pins_out, model=False):
    """A board fragment wiring the chip: its data pin supplied and mapped, its 'selected' or filter out pin traced to a second chip."""
    inst = {"use": chip_ref}
    maps = {}
    for pin, decl in pins_in.items():
        if decl.get("role") != "data":
            continue
        if decl["type"] == "rowset":
            for c, cd in decl.get("shape", {}).items():
                src = (MODEL_MAP if model else CONNECTOR_MAP).get(c)
                if src is None:
                    src = c.upper().replace("-", "_")
                if cd.get("many") and not isinstance(src, list):
                    src = [src]
                if not cd.get("many") and isinstance(src, list):
                    src = src[0]
                maps[f"{pin}.{c}"] = src
        elif decl["type"] == "document":
            for c in ("id", "title"):
                maps[f"{pin}.{c}"] = {"id": "TRADE_ID", "title": "DEAL_NUMBER"}[c]
    has_data = any(d.get("role") == "data" for d in pins_in.values())
    if has_data:
        if model:
            dims = [v for k, v in maps.items() if isinstance(v, str) and "." in v]
            meas = sorted({m for v in maps.values() for m in (v if isinstance(v, list) else [v]) if "." not in m})
            inst["supply"] = {"model": "trading-risk", "query": {"measures": meas, "dimensions": dims}}
        else:
            doc_pin = any(d["type"] == "document" for d in pins_in.values() if d.get("role") == "data")
            inst["supply"] = {"connector": "trading/trade" if doc_pin else "trading/trade-search"}
        inst["map"] = maps
    board = {"chips": {"c": inst}}
    if "selected" in pins_out and pins_out["selected"]["type"] in ("id", "dimension"):
        board["chips"]["detail"] = {"use": "entity-card@1", "supply": {"connector": "trading/trade"}, "map": {"doc.id": "TRADE_ID", "doc.title": "DEAL_NUMBER"}}
        board["traces"] = [{"from": "c.selected", "to": "detail.id"}]
    elif "filter-out" in pins_out:
        board["chips"]["trades"] = {"use": "filterable-table@2", "supply": {"connector": "trading/trade-search"},
                                    "map": {"rows.id": "TRADE_ID", "rows.label": "COUNTERPARTY_NAME"}}
        board["traces"] = [{"from": "c.filter-out", "to": "trades.filter"}]
    elif "period" in pins_out:
        board["chips"]["trades"] = {"use": "filterable-table@2", "supply": {"connector": "trading/trade-search"},
                                    "map": {"rows.id": "TRADE_ID", "rows.date": "TRADE_DATE"}}
        board["traces"] = [{"from": "c.from", "to": "trades.date-from"}, {"from": "c.to", "to": "trades.date-to"}]
    return {"title": title, "board": yaml.safe_dump(board, sort_keys=False, default_flow_style=None, width=140)}


