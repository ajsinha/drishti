package com.ash.drishti.bicompute.rachana;

import com.ash.drishti.rachana.el.Functions;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The generated list of every function (Help → Rachana reference, "Every function, generated from the registries"), from the two
 * registries: Rachana's function table ({@link Functions#catalogue()}) and the pivot engine's functions registered into it
 * ({@link EngineFunctions}). Written between its two markers in {@code docs/guides/RACHANA_REFERENCE.md}; {@code FunctionCataloguePageTest}
 * fails when the committed part differs from what the registries give (regenerate it with {@code -Ddrishti.functions.write=true} on that
 * test, or by running this class with the file's path), and when a function is missing from the reviewed function catalogue, the
 * chapter of the same document (between its own markers) with each function's example and Excel and SAS names.
 */
public final class FunctionCataloguePage {

    /** The document, from the repository's root: the Rachana reference holds the catalogue and the generated list. */
    public static final String FILE = "docs/guides/RACHANA_REFERENCE.md";

    /** The generated part's markers. */
    public static final String BEGIN = "<!-- functions: generated by FunctionCataloguePage from the registries; do not edit by hand -->";
    public static final String END = "<!-- functions: end -->";

    /** The reviewed catalogue's markers (its sections are {@code ### F<n>.}). */
    public static final String CATALOGUE_BEGIN = "<!-- function catalogue: begin -->";
    public static final String CATALOGUE_END = "<!-- function catalogue: end -->";

    static final Map<String, String> FAMILIES = new LinkedHashMap<>();

    static {
        FAMILIES.put("aggregates", "Aggregates: the pivot engine's (many values to one; a pivot cell runs the same function)");
        FAMILIES.put("measures", "Measures: the pivot engine's functions of a measure (filter context, time, windows, balances, currency)");
        FAMILIES.put("math", "Math (scalars)");
        FAMILIES.put("logic", "Logic (scalars)");
        FAMILIES.put("text", "Text (scalars)");
        FAMILIES.put("dates", "Dates, on the bank's calendars (scalars)");
        FAMILIES.put("lists", "Lists (Excel's dynamic arrays and MATLAB's list functions, over [*])");
        FAMILIES.put("statistics", "Distributions and test statistics (scalars)");
        FAMILIES.put("finance", "Finance on given flows (scalars)");
    }

    private FunctionCataloguePage() {}

    /** The generated part's text (between the markers). */
    public static String markdown() {
        List<Functions.Entry> all = Functions.catalogue();
        StringBuilder b = new StringBuilder();
        b.append("*Generated from the registries (Rachana's function table and the pivot engine's functions registered into it) by ")
                .append("`FunctionCataloguePage`; do not edit by hand. ").append(all.size()).append(" functions, each under its one name. ")
                .append("Each function's example, its Excel and SAS equivalents and its rules are in ")
                .append("[the function catalogue](#the-function-catalogue); the grammar is in [Functions](#functions).*\n\n");
        b.append("**Runs:** **R** Rachana (a scalar, one value from values); **E** the pivot engine (`drishti-bicompute`), the same ")
                .append("implementation a pivot cell runs. Where the engine is not on the class path an **E** function is refused with ")
                .append("the reason, never computed another way. **Form:** *mergeable* (a total combines partial results exactly), ")
                .append("*holistic* (it needs the values), *measure* (a figure from its own engine, never summed).\n\n");
        for (Map.Entry<String, String> family : FAMILIES.entrySet()) {
            List<Functions.Entry> rows = all.stream().filter(e -> family.getKey().equals(e.family())).toList();
            if (rows.isEmpty()) {
                continue;
            }
            b.append("### ").append(family.getValue()).append("\n\n");
            if ("aggregates".equals(family.getKey()) || "measures".equals(family.getKey())) {
                b.append("| Function | Arguments | Form | Means | Runs | Source |\n|---|---|---|---|---|---|\n");
                for (Functions.Entry e : rows) {
                    b.append("| `").append(e.name()).append("` | ").append(cell(e.args())).append(" | ").append(cell(e.form())).append(" | ")
                            .append(cell(e.description())).append(" | ").append(e.runs()).append(" | ").append(e.source()).append(" |\n");
                }
            } else {
                b.append("| Function | Runs | Source |\n|---|---|---|\n");
                for (Functions.Entry e : rows) {
                    b.append("| `").append(e.name()).append("` | ").append(e.runs()).append(" | ").append(e.source()).append(" |\n");
                }
            }
            b.append('\n');
        }
        b.append("### Shares, ranks and windows: the pivot engine's, over an answer's cells\n\n");
        b.append("A pivot value written around an aggregate: the aggregate is computed as any other, then shown from the finished figures ")
                .append("of the answer's cells (a total is never broken; no rows are read again). Pivot values only: a list in Rachana has ")
                .append("no rows and columns.\n\n");
        b.append("| Function | Arguments | Means | Example | Excel | SAS | Runs | Source |\n|---|---|---|---|---|---|---|---|\n");
        for (com.ash.drishti.kernel.api.pivot.Windows.Info w : com.ash.drishti.kernel.api.pivot.Windows.FUNCTIONS) {
            b.append("| `").append(w.name()).append("` | ").append(cell(w.args())).append(" | ").append(cell(w.description())).append(" | `")
                    .append(cell(w.example())).append("` | ").append(cell(w.excel())).append(" | ").append(cell(w.sas())).append(" | E | ")
                    .append(EngineFunctions.SOURCE).append(" |\n");
        }
        b.append('\n');
        b.append("### Old spellings (read for existing Sutras, never offered)\n\n| Old | Write instead |\n|---|---|\n");
        Functions.oldSpellings().forEach((old, one) -> b.append("| `").append(old).append("` | `").append(one).append("` |\n"));
        return b.append('\n').toString();
    }

    private static String cell(String s) {
        return s == null || s.isEmpty() ? "" : s.replace("|", "\\|");
    }

    /** The document with its generated part replaced by what the registries give now. */
    public static String splice(String document) {
        int b = document.indexOf(BEGIN);
        int e = document.indexOf(END);
        if (b < 0 || e < b) {
            throw new IllegalStateException(FILE + " has no generated part (" + BEGIN + " ... " + END + ")");
        }
        return document.substring(0, b + BEGIN.length()) + "\n" + markdown() + document.substring(e);
    }

    /** The lines of the reviewed catalogue: between its markers. */
    public static List<String> catalogue(String document) {
        int b = document.indexOf(CATALOGUE_BEGIN);
        int e = document.indexOf(CATALOGUE_END);
        if (b < 0 || e < b) {
            throw new IllegalStateException(FILE + " has no function catalogue (" + CATALOGUE_BEGIN + " ... " + CATALOGUE_END + ")");
        }
        return document.substring(b + CATALOGUE_BEGIN.length(), e).lines().toList();
    }

    /** Writes the generated part into the document at the path given (the repository's {@value #FILE}), run from the repository's root. */
    public static void main(String[] args) throws IOException {
        Path out = Path.of(args.length > 0 ? args[0] : FILE);
        Files.writeString(out, splice(Files.readString(out, StandardCharsets.UTF_8)), StandardCharsets.UTF_8);
    }
}
