/**
 * The upgrade drill stage (CONNECTOR_FILES.md, "Upgrades"): a server started on the connector files the previous release's server
 * generated (the fixture {@code connector-upgrade/2.9.4}, written by {@code tools/connector_upgrade_fixture.py} from release 2.9.4's
 * pack templates, with the markers it kept) upgrades them before it answers:
 * <ul>
 *   <li>every file nobody edited is the current pack template, byte for byte, stamped (and the file before is kept beside it);</li>
 *   <li>the edited files keep their edits and gain everything else the template has, at any depth: var-whatif, generated by 2.9.3 and
 *       edited, gains {@code ccy} (the 2.9.4 drill's DRS-5205), its other differences listed as conflicts; <i>use the pack's value</i>
 *       resolves one;</li>
 *   <li>the computed kinds answer on the upgraded files: var-result, var-whatif with {@code ccy}, exposure-result.</li>
 * </ul>
 */
@SpringBootTest(properties = {"drishti.rachana.hot-reload=false", "drishti.packs.enabled=market-risk,counterparty-risk",
        "drishti.sources.plugins.demo.enabled=false",
        "drishti.sources.connectors-dir=target/connector-upgrade/connectors", "drishti.data.dir=target/connector-upgrade/data",
        "drishti.var.official.on-start=false", "drishti.ccr.exposure.official.on-start=false", "drishti.ccr.exposure.close-grace-seconds=0",
        "drishti.var.threads=2", "drishti.var.tier.close-grace-seconds=0",
        "drishti.identity.database-url=jdbc:sqlite:target/identity-${random.uuid}/identity.db"})
@AutoConfigureMockMvc
@Import(PinnedBusinessDate.class)
@TestMethodOrder(MethodOrderer.OrderAnnotation.class)
class ConnectorUpgradeTest {

    static final Path BASE = Path.of("target", "connector-upgrade").toAbsolutePath();
    static final Path FIXTURE = Path.of("src", "test", "resources", "connector-upgrade", "2.9.4").toAbsolutePath();
    static final LocalDate DAY = LocalDate.of(2026, 9, 30);

    static {
        try {
            prepare();
        } catch (Exception e) {
            throw new IllegalStateException("the upgrade fixture cannot be laid out: " + e, e);
        }
    }

    /** The previous release's files and markers where the server finds them, and the VaR and exposure lakes the computed kinds read. */
    static void prepare() throws Exception {
        if (Files.exists(BASE)) {
            try (Stream<Path> s = Files.walk(BASE)) {
                for (Path p : s.sorted(Comparator.reverseOrder()).toList()) {
                    Files.delete(p);
                }
            }
        }
        copy(FIXTURE.resolve("connectors"), BASE.resolve("connectors"));
        copy(FIXTURE.resolve("generated"), BASE.resolve("data/connectors/generated"));
        Path delta = Files.createDirectories(BASE.resolve("data/delta"));
        // the VaR inputs as the current pack expects them: with LIMIT_LETTER, which its demo hierarchy LL is built from (2.9.5)
        fixture("com.ash.drishti.server.var.VarHierarchyFixture", delta);
        Path ccr = Files.createDirectories(BASE.resolve("ccr"));
        fixture("com.ash.drishti.server.exposure.ExposureHierarchyFixture", ccr);    // exposure paths with LIMIT_LETTER (2.9.5)
        // the exposure tables where the counterparty-risk pack's connectors read them
        for (String[] t : new String[][] {{"simulation-run", "risk"}, {"exposure-path", "risk"}, {"netting-set", "credit"}, {"csa", "legal"},
                {"collateral-balance", "collateral"}, {"counterparty", "reference"}, {"counterparty-group", "reference"}}) {
            if (Files.isDirectory(ccr.resolve("risk").resolve(t[0]))) {
                copy(ccr.resolve("risk").resolve(t[0]), delta.resolve(t[1]).resolve(t[0]));
            }
        }
    }

    private static void fixture(String cls, Path root) throws Exception {
        var m = Class.forName(cls).getDeclaredMethod("write", Path.class);
        m.setAccessible(true);
        m.invoke(null, root);
    }

    private static void copy(Path from, Path to) throws Exception {
        try (Stream<Path> s = Files.walk(from)) {
            for (Path p : s.toList()) {
                Path t = to.resolve(from.relativize(p).toString());
                if (Files.isDirectory(p)) {
                    Files.createDirectories(t);
                } else if (!Files.exists(t)) {
                    Files.createDirectories(t.getParent());
                    Files.copy(p, t);
                }
            }
        }
    }

    @Autowired MockMvc mvc;
    @Autowired ConnectorFiles files;
    @Autowired ConnectorManager manager;
    @Autowired TemplateUpdates updates;
    final ObjectMapper json = new ObjectMapper();

    @SuppressWarnings("unchecked")
    private Map<String, List<String>> edited() throws Exception {
        return (Map<String, List<String>>) json.readValue(FIXTURE.resolve("edits.json").toFile(), Map.class).get("edited");
    }

    private List<String> fixtureNames() throws Exception {
        try (Stream<Path> s = Files.list(FIXTURE.resolve("connectors"))) {
            return s.map(p -> p.getFileName().toString().replace(".yaml", "")).sorted().toList();
        }
    }

    @Test
    @Order(1)
    void everyUneditedFileIsTheCurrentTemplateStamped() throws Exception {
        Map<String, List<String>> edited = edited();
        List<String> checked = new ArrayList<>();
        for (String name : fixtureNames()) {
            if (edited.containsKey(name)) {
                continue;
            }
            var t = manager.template(name);
            if (t.isEmpty()) {
                continue;                                        // a pack this server does not load
            }
            String now = files.text(name);
            assertThat(now).as(name).isEqualTo(ConnectorBootstrap.generate(files, name, t.get().pack(), t.get().definition()));
            assertThat(TemplateStamp.pristine(now)).as(name + " is stamped as never edited").isTrue();
            checked.add(name);
        }
        assertThat(checked).hasSizeGreaterThan(15).contains("var-engine", "exposure-engine", "var-positions");
        try (Stream<Path> s = Files.list(BASE.resolve("connectors"))) {
            assertThat(s.map(p -> p.getFileName().toString()).filter(n -> n.contains(".before-upgrade-"))).as("the files before are kept").isNotEmpty();
        }
        // nothing else to add or decide (a kind the template names that no pack routes, pv-updates' pv-update, is the template's own)
        assertThat(updates.drifts().stream().filter(d -> !edited.containsKey(d.name()))
                .filter(d -> d.additive() || d.followsPack() || !d.conflicting().isEmpty() || !d.computeConflicts().isEmpty())
                .map(d -> d.toMap().toString())).as("nothing else drifts").isEmpty();
    }

    @Test
    @Order(2)
    void anEditedFileKeepsItsEditsAndGainsEveryKeyTheTemplateHas() throws Exception {
        // risk-store: the administrator's refresh-seconds kept, every other setting the template's
        ConnectorFiles.Definition risk = files.read("risk-store");
        ConnectorFiles.Definition riskT = files.parse("risk-store", template("risk-store"));
        Map<String, String> want = new LinkedHashMap<>(riskT.settings());
        want.put("refresh-seconds", "45");
        assertThat(risk.settings()).containsOnlyKeys(want.keySet());
        want.forEach((k, v) -> {
            if (TemplateUpdates.layoutList(k)) {
                // a layout list keeps the file's columns in their order and gains the template's new ones after them (LIMIT_LETTER in 2.9.5)
                List<String> have = List.of(risk.settings().get(k).split(","));
                assertThat(have).as(k).containsExactlyInAnyOrder(v.split(","));
                List<String> old = have.stream().filter(c -> !List.of("LIMIT_LETTER").contains(c)).toList();
                assertThat(have.subList(0, old.size())).as(k + ": the file's own columns first").isEqualTo(old);
            } else {
                assertThat(risk.settings().get(k)).as(k).isEqualTo(v);
            }
        });
        assertThat(risk.kinds()).isEqualTo(riskT.kinds());
        assertThat(TemplateStamp.pristine(risk.text())).isFalse();

        // var-whatif, generated by 2.9.3 and edited: ccy and everything else gained, the edit kept, the rest of the differences listed
        ConnectorFiles.Definition w = files.read("var-whatif");
        assertThat(w.compute().toString()).contains("ccy");
        assertThat(((Map<?, ?>) w.compute().get("limits")).get("wait")).hasToString("45s");
        TemplateUpdates.Drift d = updates.drift("var-whatif").orElseThrow();
        assertThat(d.additive()).as("nothing left to add").isFalse();
        assertThat(d.computeConflicts().stream().map(TemplateMerge.Conflict::key)).contains("limits.wait", "reads[0].id");
        ConnectorFiles.Definition wT = files.parse("var-whatif", template("var-whatif"));
        Map<String, Object> expected = TemplateMerge.set(TemplateMerge.set(wT.compute(), List.of("limits", "wait"), "45s"),
                List.of("reads", "[0]", "id"), "{id}");
        // the trigger keeps the file's kinds (2.9.3's) in their order and gains the template's new ones after them, in the template's order
        List<Object> kinds = new ArrayList<>(List.of("pnl-vector", "risk-hierarchy", "scenario-set", "portfolio"));
        for (Object k : (List<?>) ((Map<?, ?>) ((List<?>) wT.compute().get("triggers")).get(0)).get("kinds")) {
            if (!kinds.contains(k)) {
                kinds.add(k);
            }
        }
        expected = TemplateMerge.set(expected, List.of("triggers", "[0]", "kinds"), kinds);
        assertThat(TemplateMerge.same(w.compute(), expected)).as(w.compute() + " vs " + expected).isTrue();

        // use the pack's value: the reads' id becomes the template's, the edit of limits.wait stays
        mvc.perform(post("/api/v1/admin/connectors/template-updates/var-whatif/use-template-value").contentType(MediaType.APPLICATION_JSON)
                .content("{\"where\": \"definition\", \"key\": \"reads[0].id\"}")).andReturn();
        ConnectorFiles.Definition after = files.read("var-whatif");
        assertThat(after.compute().toString()).contains("{id}~ccy={params.ccy}");
        assertThat(((Map<?, ?>) after.compute().get("limits")).get("wait")).hasToString("45s");
    }

    private String template(String name) {
        var t = manager.template(name).orElseThrow();
        return ConnectorBootstrap.generate(files, name, t.pack(), t.definition());
    }

    private JsonNode compute(String connector, String kind, String body) throws Exception {
        var r = mvc.perform(post("/api/v1/compute/" + connector + "/" + kind).contentType(MediaType.APPLICATION_JSON).content(body))
                .andReturn().getResponse();
        assertThat(r.getContentAsString()).as(connector + "/" + kind).doesNotContain("DRS-5205");
        assertThat(r.getStatus()).as(connector + "/" + kind + ": " + r.getContentAsString()).isEqualTo(200);
        return json.readTree(r.getContentAsString());
    }

    @Test
    @Order(3)
    void theComputedKindsAnswerOnTheUpgradedFiles() throws Exception {
        JsonNode v = compute("var-engine", "var-result", "{\"id\": \"BANK\", \"asOf\": \"" + DAY + "\", \"wait\": 20000}");
        assertThat(v.get("state").asText()).as(v.toString()).isEqualTo("ready");
        assertThat(v.at("/result/VAR").isNumber()).isTrue();
        // the parameter the 2.9.4 drill found missing: accepted (the engine itself runs in the Python pool, which a server test may not have)
        JsonNode w = compute("var-whatif", "var-whatif", "{\"id\": \"BANK\", \"asOf\": \"" + DAY + "\", \"params\": {\"ccy\": \"EUR\"}, \"wait\": 1000}");
        // compute.enabled is off in a server test (no Python pool): refused for that, never for the parameter
        assertThat(w.get("state").asText()).as(w.toString()).isIn("ready", "pending", "running", "failed", "refused");
        assertThat(w.toString()).doesNotContain("unknown parameter").doesNotContain("ccy\"");
        JsonNode x = compute("exposure-engine", "exposure-result", "{\"id\": \"NSET:NS-X\", \"asOf\": \"" + DAY + "\", \"wait\": 20000}");
        assertThat(x.get("state").asText()).as(x.toString()).isEqualTo("ready");
    }
}
