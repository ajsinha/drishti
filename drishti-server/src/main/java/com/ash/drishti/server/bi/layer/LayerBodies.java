package com.ash.drishti.server.bi.layer;

import com.ash.drishti.common.DrishtiException;
import com.ash.drishti.common.ErrorCode;

/**
 * What saving the body of a model-layer item does (docs/architecture/BI_DESIGN.md › The model layer: the specification of wave W1, sections 2.8 and 7.4): a {@code rachana: 2} dataset or a model gets
 * the stable ids it lacks written into its YAML ({@link StableIds}); a dataset that says it was generated by a pack is refused ({@code DRS-9107}: generated
 * datasets are read-only, narrow one with {@code extends}). Any other body is kept as it is.
 */
public final class LayerBodies {

    private LayerBodies() {}

    public static String onSave(String kind, String body) {
        if (body == null || body.isBlank()) {
            return body;
        }
        boolean model = "model".equals(kind);
        if (!model && !("dataset".equals(kind) && DatasetDefParser.isVersion2(body))) {
            return body;
        }
        if (!model) {
            DatasetDefParser.Result r = DatasetDefParser.parse(body);
            if (r.dataset() != null && (r.dataset().isGenerated() || r.dataset().name().startsWith(DatasetDef.PACK_PREFIX))) {
                throw new DrishtiException(ErrorCode.LAYER_DATASET_GENERATED, "'" + r.dataset().name() + "' is generated by its pack and read-only: save a dataset that `extends: "
                        + r.dataset().name() + "` to narrow it or add columns");
            }
        } else if (ModelDefParser.parse(body).model() == null) {
            return body;
        }
        try {
            return StableIds.write(body, model);
        } catch (RuntimeException e) {
            return body;                                                     // a layout the writer does not know: kept as typed; the designer writes the ids
        }
    }
}
