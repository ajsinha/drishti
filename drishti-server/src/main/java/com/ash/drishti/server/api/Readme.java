package com.ash.drishti.server.api;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.yaml.snakeyaml.LoaderOptions;
import org.yaml.snakeyaml.Yaml;
import org.yaml.snakeyaml.constructor.SafeConstructor;

/**
 * A README of the README standard (docs/guides/PACK_GENERATORS_GUIDE.md, "The README standard"): leading HTML comments (the
 * licence, a "generated by" line), a YAML front matter between {@code ---} lines, then markdown. {@link #parse} splits it;
 * {@link #withoutKinds} drops the {@code ### `kind`} subsections of kinds a caller may not open.
 */
public record Readme(Map<String, Object> meta, String markdown) {

    private static final Pattern COMMENTS = Pattern.compile("\\A(?:\\s*<!--.*?-->)*\\s*", Pattern.DOTALL);
    private static final Pattern KIND_HEADING = Pattern.compile("^### `([^`]+)`\\s*$");

    /** The front matter (empty when none or not a mapping) and the markdown after it, comments removed. */
    @SuppressWarnings("unchecked")
    public static Readme parse(String text) {
        Matcher m = COMMENTS.matcher(text);
        String rest = m.find() ? text.substring(m.end()) : text;
        rest = rest.replace("\r\n", "\n");
        if (rest.startsWith("---\n")) {
            int end = rest.indexOf("\n---\n", 3);
            if (end > 0) {
                Object y;
                try {
                    y = new Yaml(new SafeConstructor(new LoaderOptions())).load(rest.substring(4, end));
                } catch (RuntimeException e) {
                    y = null;
                }
                Map<String, Object> meta = y instanceof Map<?, ?> map ? new LinkedHashMap<>((Map<String, Object>) map) : new LinkedHashMap<>();
                return new Readme(meta, rest.substring(end + 5));
            }
        }
        return new Readme(new LinkedHashMap<>(), rest);
    }

    /** This README without the Data structures subsections of {@code hidden} kinds, and without them in the front matter. */
    public Readme withoutKinds(Set<String> hidden) {
        if (hidden.isEmpty()) {
            return this;
        }
        List<String> out = new ArrayList<>();
        boolean skipping = false;
        for (String line : markdown.split("\n", -1)) {
            Matcher h = KIND_HEADING.matcher(line);
            if (h.matches()) {
                skipping = hidden.contains(h.group(1));
            } else if (line.startsWith("## ") || line.startsWith("# ")) {
                skipping = false;
            }
            if (!skipping) {
                out.add(line);
            }
        }
        Map<String, Object> meta = new LinkedHashMap<>(this.meta);
        if (meta.get("kinds") instanceof List<?> kinds) {
            meta.put("kinds", kinds.stream().filter(k -> !hidden.contains(String.valueOf(k))).toList());
        }
        if (meta.get("commands") instanceof Map<?, ?> commands) {
            Map<Object, Object> kept = new LinkedHashMap<>();
            commands.forEach((k, v) -> {
                if (!hidden.contains(String.valueOf(v))) {
                    kept.put(k, v);
                }
            });
            meta.put("commands", kept);
        }
        return new Readme(meta, String.join("\n", out));
    }

    public Map<String, Object> json(String key, String name) {
        Map<String, Object> out = new LinkedHashMap<>();
        out.put(key, name);
        out.put("meta", meta);
        out.put("markdown", markdown);
        return out;
    }
}
